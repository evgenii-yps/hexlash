// по которым занятие заканчивается.
//
// ЗАЧЕМ ЭТО ВООБЩЕ. До этой работы грань зажигалась простым нажатием и доставалась
// даром: потолок бойца брался за минуту, а зал FORGE был комнатой, где бойцы стоят
// и ничего не делают. Теперь грань открывается ЗАНЯТИЕМ.
//
// ⚠️ НИКАКИХ ЧИСЕЛ, КРОМЕ ОДНОГО. Владелец отложил систему ресурсов и все цифры
//    прокачки на отдельный заход. Здесь нет и не должно появиться: счётчиков,
//    очков, опыта, валюты, уровней, порогов, накоплений, полос заполнения с
//    процентами и наград за бой. ЗАНЯТИЕ — НЕ НАКОПЛЕНИЕ, А СОБЫТИЕ: началось и
//    закончилось. Единственное число во всём файле — длительность занятия, и она
//    временная (см. ниже).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, И ПОЧЕМУ ОН НИЧЕГО НЕ ЗНАЕТ ПРО ХРАНИЛИЩЕ. Правила читают
// трое: список бойцов (он решает, пускать ли), панель зала (она говорит словами,
// почему не пускают) и дерево прокачки (оно гасит грани). Если бы правило жило у
// любого из них, двое других ходили бы в чужой дом — и рано или поздно завели бы
// своё, второе, которое разошлось бы с первым.
//
// ⚠️ ЭТОТ ФАЙЛ НЕ ИМПОРТИРУЕТ ХРАНИЛИЩЕ. Список бойцов сам читает отсюда правила,
//    поэтому обратная стрелка замкнула бы круг импортов. Часы поэтому зовут ЧУЖУЮ
//    функцию, а кто именно придёт по звонку — решает тот, кто часы завёл.
//
// Экспортирует: LESSON_SEC, LESSON_MS, FREE/BUSY/READY, stateOf, assignGate,
//               facetGate, lessonEndsAt, anyLesson, startClock, stopClock.

// ───────────────────────────── CONFIG ─────────────────────────────
/**
 * ⚠️ ВРЕМЕННОЕ ЗНАЧЕНИЕ. Сколько длится ОДНО занятие, секунд. Единственное число
 * этой работы; настоящее придёт в заходе с цифрами, и менять его надо ЗДЕСЬ —
 * второго такого числа в проекте нет.
 *
 * Почему сейчас минута. Занятие обязано успевать закончиться за время обычного
 * просмотра зала: игрок назначает его, идёт смотреть остальных, возвращается — и
 * оно готово. Минута — это один неспешный обход зала. Она же держит приёмку
 * человеческой: пять занятий подряд до потолка бойца (ТЗ §8.2) — это пять минут,
 * а не полчаса.
 */
export const LESSON_SEC = 60;

/** То же число в миллисекундах — часы считают в них. */
export const LESSON_MS = LESSON_SEC * 1000;

// Как часто смотреть, не кончилось ли занятие. Раз в секунду: подпись меняется
// один раз за всё занятие, и чаще спрашивать не о чем.
const TICK_MS = 1000;

// ───────────────────── Три состояния бойца ─────────────────────
// Слова, а не числа: состояние — это то, что игрок читает, а не то, что копится.
export const FREE = 'free';
export const BUSY = 'busy';
export const READY = 'ready';

/**
 * В каком состоянии боец. ВЫВОДИТСЯ из двух полей, а не хранится третьим словом:
 * третье слово — это третья правда, и она рассохлась бы с первыми двумя.
 * @param {object|null} f боец из списка бойцов
 * @returns {'free'|'busy'|'ready'}
 */
export function stateOf(f) {
  if (!f) return FREE;
  if (f.lesson && f.lesson.until > Date.now()) return BUSY;
  if (f.ready) return READY;
  return FREE;
}

/** Когда закончится занятие, назначенное прямо сейчас. */
export function lessonEndsAt(now = Date.now()) {
  return now + LESSON_MS;
}

/** Есть ли в списке хоть одно идущее занятие — часы заводятся только ради них. */
export function anyLesson(list) {
  for (const f of list || []) if (f && f.lesson) return true;
  return false;
}

// ───────────────────── Ворота: что бойцу можно ─────────────────────
// ⚠️ ОДИН НАБОР ПРАВИЛ НА ВСЕХ. Эти две функции читают и список бойцов (он
//    отказывает), и панель с деревом (они объясняют словами). Если бы у экрана
//    была своя копия проверки, экран и хранилище разошлись бы — и игрок получил
//    бы кнопку, которая нажимается и ничего не делает.
//
// Возвращают ПРИЧИНУ ОТКАЗА (ключ) или null, когда можно.

/**
 * Можно ли назначить занятие.
 *   'busy'  — уже занимается
 *   'ready' — занятие уже отработано, сначала забери результат (право не копится)
 *   'full'  — все грани зажжены, в зале ему делать нечего
 * @param {object} f
 * @param {number} lit сколько граней у него зажжено
 * @param {number} cap сколько граней ему вообще можно зажечь
 */
export function assignGate(f, lit, cap) {
  if (!f) return 'none';
  if (stateOf(f) === BUSY) return 'busy';
  if (stateOf(f) === READY) return 'ready';
  if (lit >= cap) return 'full';
  return null;
}

/**
 * Можно ли тронуть грань — зажечь или погасить.
 *   'busy'     — занимается, руки заняты
 *   'notReady' — занятие не отработано: зажигать нечем
 *   'holds'    — гасить нельзя, пока не забрано прошлое право (иначе прав станет два)
 * @param {object} f
 * @param {boolean} lighting true — зажечь, false — погасить
 */
export function facetGate(f, lighting) {
  if (!f) return 'none';
  const st = stateOf(f);
  if (st === BUSY) return 'busy';
  if (lighting) return st === READY ? null : 'notReady';
  return st === READY ? 'holds' : null;
}

// ───────────────────── Часы ─────────────────────
//
// ⚠️ ЧАСЫ — ЭТО НЕ ХРАНИЛИЩЕ ВРЕМЕНИ. Занятие держит СРОК окончания, и этого
//    довольно: занятие, кончившееся без нас (игрок ушёл на арену, свернул вкладку,
//    обновил страницу), оказывается кончившимся в тот момент, когда на него
//    посмотрели. Часы нужны ровно для одного — чтобы подпись в открытом зале
//    сменилась сама, а не после следующего нажатия.
//
// Поэтому они и заводятся только пока в зале кто-то занимается, и сами
// останавливаются, когда занятий не осталось.
let timer = 0;

/**
 * Завести часы. `onTick` зовётся раз в секунду; вернёт false — часы встают.
 * Повторный вызов заменяет прежние часы, а не заводит вторые.
 */
export function startClock(onTick) {
  stopClock();
  if (typeof onTick !== 'function') return;
  timer = setInterval(() => {
    if (onTick() === false) stopClock();
  }, TICK_MS);
}

/** Остановить часы. Безопасно звать когда угодно, в том числе дважды. */
export function stopClock() {
  if (timer) { clearInterval(timer); timer = 0; }
}
