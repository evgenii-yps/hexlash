// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРИЗНАК ВНУТРИ АРЕНЫ. Первая попытка читала адрес
// прямо в ArenaScene — и не работала. Прямой заход на `/play/arena?dev=1`
// отбивается стражем арены (без выбранного бойца туда нельзя), а отбой уводит на
// другой адрес БЕЗ признака. Сцена арены монтировалась уже без него, и включить
// панель было нельзя вообще ничем. Признак должен читаться ОДИН РАЗ ПРИ ЗАГРУЗКЕ
// СТРАНИЦЫ, до всякой навигации, — поэтому он живёт здесь и поднимается из
// main.js на старте.
//
// ПОЧЕМУ ПРИЗНАК В АДРЕСЕ, А НЕ СОЧЕТАНИЕ КЛАВИШ. На телефоне клавиатуры нет, а
// адрес пальцем случайно не набирается. `?dev=1` включает, `?dev=0` выключает.
//
// ПОЧЕМУ ОТВЕТ ЗАПОМИНАЕТСЯ. Внутри игры адрес меняется на каждом переходе, и
// признак из строки терялся бы на первом же шаге. Память ВКЛАДКИ — то же
// хранилище и та же причина, по которой в нём живёт прогресс гостя (см.
// services/playerProgress.js): переживает обновление, умирает с вкладкой, в
// соседнюю вкладку не течёт.
//
// ⚠️ ПРАВИЛО. Этот признак управляет ТОЛЬКО ВИДИМОСТЬЮ служебных органов. Он
// НИКОГДА не включает думающий мозг модели и ничего, что стоит денег: его
// подставит кто угодно из адресной строки. То же правило и по той же причине
// стоит у признака показа для деки — см. ArenaScene.vue.

const KEY = 'hexlash_dev';

/** Решается ОДИН РАЗ при загрузке страницы. Дальше только читается. */
export const DEV_MODE = (() => {
  try {
    const q = new URLSearchParams(window.location.search).get('dev');
    if (q === '1') { sessionStorage.setItem(KEY, '1'); return true; }
    if (q === '0') { sessionStorage.removeItem(KEY); return false; }
    return sessionStorage.getItem(KEY) === '1';
  } catch (_) {
    // Нет окна или хранилище закрыто настройками браузера. Молчим и не светим
    // панель: ошибиться в сторону «спрятано» безопаснее, чем показать её игроку.
    return false;
  }
})();
