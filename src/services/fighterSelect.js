// fighterSelect.js — КТО ВЫБРАН. Один боец на стороне игрока, всегда.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. До этой работы порядок был обратный: сначала предмет,
// потом боец, — и ловить палец приходилось ДВАЖДЫ, в кличах и в баффах, одним и
// тем же кодом. Теперь боец выбирается сам по себе, раньше и независимо от
// рычагов, поэтому палец ловится ОДИН раз и здесь. Кличи и баффы спрашивают
// «кто выбран» и больше ничего про палец не знают.
//
// ГЛАВНОЕ ПРАВИЛО (ТЗ 26.09.2026). Выбранный боец есть ВСЕГДА — с первого кадра
// боя и до конца. Не «можно выбрать», а «всегда кто-то выбран». Отдельного
// поведения для боя один на один нет: там боец выбран сам собой, и игрок
// разницы не замечает. Одна механика вместо двух — чтобы не переучиваться при
// переходе из дуэли в отряд.
//
// ПРАВИЛА:
//   1. выбирается ЛЮБОЙ живой боец на стороне игрока — и свой, и союзный бот
//      (в рейде на стороне игрока трое союзников, отрезать их нельзя);
//   2. соперники, павшие и пустое место не выбираются — тап по ним не делает
//      ничего, прежний выбор остаётся;
//   3. стартовый выбор — СОБСТВЕННЫЙ боец игрока, не бот;
//   4. снять выбор нельзя ничем: без выбранного панель рычагов бесполезна;
//   5. выбранный пал — выбор сам перескакивает на следующего живого на стороне
//      игрока (панель не пустует посреди боя);
//   6. бой кончился — выбора нет, метка гаснет.
//
// КАК ВИДНО, КТО ВЫБРАН. Кружок под ногами. Кружки на плите УЖЕ ЕСТЬ — тонкие
// белые кольца под стороной игрока, — и выбранный получает свой в цвет ядра,
// остальные остаются белыми. Своего кольца этот файл не заводит: он перекрашивает
// существующее, подменив ему материал, и возвращает прежний, когда выбор ушёл.
//
// ⚠️ МАТЕРИАЛ КОЛЬЦА ОБЩИЙ НА ВСЕ КОЛЬЦА. Арена собирает их из одной геометрии и
//    одного материала (makeOwnRing) — покрасить материал на месте значило бы
//    покрасить ВСЕ кольца разом. Поэтому выбранному кольцу подсовывается свой
//    материал, а прежний запоминается на самом кольце и возвращается обратно.
//
// ⚠️ КРУЖОК — ЕДИНСТВЕННАЯ МЕТКА ВЫБОРА. Раньше их было две: плоские скобки
//    поверх кадра. Их верхние уголки ложились на плашку здоровья и читались
//    вторым знаком — «зелёной подсветкой плашки», которой никто не задумывал.
//    Сняты целиком (ТЗ 26.09.2026, откат и кружок).
//
// ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ:
//   · не знает про кличи и баффы — они спрашивают его, не наоборот;
//   · не добавляет в сцену ни одного предмета — только красит существующий;
//   · не заводит своих чисел — их у выбора нет вовсе;
//   · не рисует панель — это Vue-компонент, он читает состояние ниже.
//
// ⚠️ НИГДЕ НЕ СОХРАНЯЕТСЯ. Обновление страницы = новый бой, выбран собственный
//    боец. Это ТЗ дословно.
//
// Экспортирует: selectState, bindSelectArena, unbindSelectArena,
//               selectStartFight, selectEndFight, selectTick, selectedUnit,
//               selectUnit, onSelectFrame, onSelectTap.
import { reactive } from 'vue';
import * as THREE from 'three';
import { coreHue } from '@/data/sceneTokens.js';

/**
 * ЧТО ВИДИТ ЭКРАН. Панель рычагов и метка читают отсюда и больше ниоткуда.
 *   active — бой идёт и кто-то выбран
 *   key    — номер выбора: меняется, когда сменился боец. Панель им больше не
 *            пользуется (заголовка у неё нет), но по нему пересобираются
 *            карточки баффов: «нельзя сейчас» зависит от того, КТО выбран.
 *   coreId — ядро выбранного. Им красится кружок под ногами.
 *
 * ⚠️ САМОЙ ЗАПИСИ БОЙЦА ЗДЕСЬ НЕТ. Состояние реактивное: всё, что в него
 *    положено, Vue оборачивает своей обёрткой — вглубь, до тел Three.js.
 *    Обёртка не равна самому бойцу, и сравнение по ней промахивалось бы. Та же
 *    причина и то же решение, что у значков кличей и баффов.
 */
export const selectState = reactive({
  active: false,
  key: 0,
  coreId: '',
});

// ── Привязка к арене ─────────────────────────────────────────────────────
// Арена отдаёт три вещи и больше ничего: чем считать экранные координаты, по
// чему ловить палец и где брать живых бойцов. Сцена выбору не нужна вовсе — он
// ничего в трёхмерный мир не кладёт.
let A = null; // { camera, canvas, field }

/** Выбранный боец — ВНЕ реактивного состояния, см. предупреждение выше. */
let selected = null;
/** Свой номер каждой смене выбора. */
let seq = 0;

/**
 * Арена зовёт это один раз при сборке. Пока не позвали, выбора не существует:
 * палец не ловится, метки нет.
 */
export function bindSelectArena({ camera, canvas, field }) {
  A = { camera, canvas, field };
  canvas.addEventListener('pointerdown', onPointerDown);
  canvas.addEventListener('pointerup', onPointerUp);
  return unbindSelectArena;
}

/** Уход с арены. Всё снимается, чтобы следующий бой начался с чистого. */
export function unbindSelectArena() {
  if (!A) return;
  A.canvas.removeEventListener('pointerdown', onPointerDown);
  A.canvas.removeEventListener('pointerup', onPointerUp);
  selectEndFight();
  if (selMat) { selMat.dispose(); selMat = null; }
  A = null;
}

// ── Начало и конец боя ───────────────────────────────────────────────────

/**
 * НОВЫЙ БОЙ. Выбор сбрасывается, и первым будет собственный боец игрока.
 *
 * ⚠️ ЗДЕСЬ ВЫБРАТЬ ЕЩЁ НЕКОГО, И ЭТО НОРМАЛЬНО. Бой начинается, когда плита
 *    ПУСТА — бойцов на неё ставят позже, уже в кадрах. Поэтому выбор не
 *    назначается тут, а ДОБИРАЕТСЯ каждый кадр, пока не найдётся кого выбрать
 *    (см. selectTick). Ровно на этой ловушке ряд карт клича однажды замер в
 *    «целей нет» на весь бой: состояние считалось один раз, на пустой плите.
 */
export function selectStartFight() {
  if (!A) return;
  unpaintRing(selected);
  selected = null;
  selectState.active = false;
  publish();
}

/** БОЙ КОНЧИЛСЯ. Выбора нет, метка гаснет. */
export function selectEndFight() {
  unpaintRing(selected);
  selected = null;
  selectState.active = false;
  selectState.key = 0;
  selectState.coreId = '';
}

// ── Подписки ─────────────────────────────────────────────────────────────
//
// ⚠️ ЗАЧЕМ ЗДЕСЬ ПОДПИСКИ, А НЕ ПРЯМОЙ ВЫЗОВ. Командование (services/command.js)
//    стоит НАД выбором: оно двигает выбор и нажимает карты клича и баффа. Значит
//    выбору нельзя звать его по имени — вышло бы кольцо (выбор → командование →
//    клич → выбор), а кольцо в модулях работает ровно до первой правки, после
//    которой кто-нибудь обратится к соседу на загрузке файла, а не в кадре, и
//    получит пустоту. Поэтому направление одностороннее: кто стоит выше, тот и
//    подписывается. Выбор про подписчиков ничего не знает.
//
//    Подписок ровно две, и обе — то, чего командование не может узнать само:
//    кадр (у него нет своей привязки к арене) и тап пальцем по бойцу (палец
//    ловится здесь).

/** Подписчики кадра. */
const frameHooks = [];
/** Подписчики тапа по бойцу. */
const tapHooks = [];

/**
 * Подписаться на кадр выбора. Зовётся один раз, при загрузке подписчика.
 * @param {(t:number, field:object, live:boolean) => void} cb
 */
export function onSelectFrame(cb) {
  if (typeof cb === 'function') frameHooks.push(cb);
}

/**
 * Подписаться на ТАП ПАЛЬЦЕМ по своему бойцу. Именно палец, а не любая смена
 * выбранного: выбор переезжает и сам (боец пал — добираем следующего), и по руке
 * легенды, а это совсем другие события.
 * @param {(unit:object) => void} cb
 */
export function onSelectTap(cb) {
  if (typeof cb === 'function') tapHooks.push(cb);
}

// ── Кто выбран ───────────────────────────────────────────────────────────

/**
 * Запись выбранного бойца, или null. Спрашивают кличи и баффы — им нужен сам
 * боец, а не его описание для экрана.
 */
export function selectedUnit() {
  return isPickable(selected) ? selected : null;
}

/**
 * НАЗНАЧИТЬ ВЫБРАННОГО ИЗВНЕ. Зовёт командование (services/command.js), когда
 * легенда взялась за рычаг: карта кричит ВЫБРАННОМУ, значит перед нажатием выбор
 * обязан переехать на её цель.
 *
 * ⚠️ ЭТО НЕ ТАП, И ПЕРЕХВАТА ЗДЕСЬ НЕТ НАРОЧНО. Тап по бойцу возвращает
 *    управление игроку (см. onPointerUp), а этот вход — рука самой легенды: если
 *    бы он тоже перехватывал, легенда отбирала бы управление у себя же первым
 *    своим действием и больше никогда бы не командовала.
 *
 * Негодного бойца (павшего, чужого) молча не берёт — как и палец.
 */
export function selectUnit(u) {
  if (!A || !isPickable(u)) return false;
  setSelected(u);
  return true;
}

/** Живые на стороне игрока. И свои, и союзные боты (правило 1). */
function ourSide() {
  if (!A) return [];
  return A.field.living().filter((u) => u.sideId === 'player');
}

/** Годен ли боец в выбранные прямо сейчас. */
function isPickable(u) {
  if (!u || u.dead || !u.f) return false;
  if (u.sideId !== 'player') return false;          // правило 2
  return u.f.getHp() > 0;
}

/**
 * Назначить выбранного. Публикует заголовок и цвет только если боец правда
 * сменился: панель меняется заметно, и дёргать её каждый кадр незачем.
 */
function setSelected(u) {
  if (selected === u) return;
  unpaintRing(selected);
  selected = u;
  seq += 1;
  publish();
  paintRing(selected);
}

/** Переписать описание выбранного в состояние экрана. */
function publish() {
  if (!isPickable(selected)) {
    selectState.active = false;
    return;
  }
  selectState.coreId = (selected.spec && selected.spec.coreId) || '';
  selectState.key = seq;
  selectState.active = true;
}

/**
 * Добрать выбор, если выбирать некого или выбранный пал (правила 3 и 5).
 * Сначала СОБСТВЕННЫЙ боец игрока, и только если своих не осталось — союзный
 * бот: стартовый выбор обязан быть своим, а перескок после смерти — любым живым
 * на стороне игрока.
 */
function ensureSelection() {
  if (isPickable(selected)) return;
  const live = ourSide();
  const own = live.find((u) => !(u.spec && u.spec.isBot));
  setSelected(own || live[0] || null);
}

// ── Палец ────────────────────────────────────────────────────────────────
// Тап, а не протяжка. Порог тот же, каким арена отличает тап от вращения
// камеры, и тот же, что был у кличей и баффов, — иначе выбор срабатывал бы на
// каждом развороте.
const TAP_SLOP_PX = 5;
let downX = 0;
let downY = 0;
let downOn = false;
const _ray = new THREE.Raycaster();
const _ndc = new THREE.Vector2();

function onPointerDown(e) {
  downOn = true; downX = e.clientX; downY = e.clientY;
}

function onPointerUp(e) {
  const wasTap = downOn && Math.hypot(e.clientX - downX, e.clientY - downY) <= TAP_SLOP_PX;
  downOn = false;
  if (!wasTap || !selectState.active) return;
  const unit = pickUnitAt(e.clientX, e.clientY);
  // Мимо бойца, по сопернику или по павшему — НИЧЕГО. Прежний выбор остаётся:
  // снять выбор нельзя ничем (правила 2 и 4).
  if (!isPickable(unit)) return;
  // Палец объявляется ДО смены выбора: на этом висит перехват управления у
  // легенды (ТЗ, одно из трёх мест), и порядок здесь виден глазами — сначала
  // палец забирает руль, и только потом выбор переезжает туда, куда ткнули.
  for (const cb of tapHooks) cb(unit);
  setSelected(unit);
}

/** Кого накрыл палец. Луч из камеры по телам живых на стороне игрока. */
function pickUnitAt(clientX, clientY) {
  if (!A) return null;
  const r = A.canvas.getBoundingClientRect();
  _ndc.x = ((clientX - r.left) / r.width) * 2 - 1;
  _ndc.y = -((clientY - r.top) / r.height) * 2 + 1;
  _ray.setFromCamera(_ndc, A.camera);
  let best = null;
  let bestD = Infinity;
  for (const u of ourSide()) {
    const hit = _ray.intersectObject(u.f.group, true);
    if (hit.length && hit[0].distance < bestD) { bestD = hit[0].distance; best = u; }
  }
  return best;
}

// ── Кадр ─────────────────────────────────────────────────────────────────

/**
 * Зовётся ареной каждый кадр: держит выбор живым и кружок покрашенным.
 *
 * @param {number} dt секунд с прошлого кадра (не нужен, принимается для
 *                    единообразия с buffTick и klichTick — все три зовутся рядом)
 * @param {number} t  время боя (часы арены; выбору не нужно, см. выше)
 */
export function selectTick(dt, t) { // eslint-disable-line no-unused-vars
  if (!A) return;
  ensureSelection();
  // КАДР ПОДПИСЧИКАМ ОТДАЁТСЯ ОТСЮДА, И ЭТО НЕ ПРИХОТЬ. Арена — защищённый файл,
  // ей нельзя добавлять знание про то, что стоит выше; а выбор бойца уже привязан
  // к арене, уже получает кадр и держит поле боя. Он же и ближайший сосед по
  // смыслу для командования: действие легенды — это «выбрать и нажать». Зовётся
  // ПОСЛЕ ensureSelection, чтобы подписчик решал по живому составу, и последним из
  // трёх кадров рычагов, чтобы заряды с откатами были уже пересчитаны.
  for (const cb of frameHooks) cb(t, A.field, selectState.active);
  // ПЕРЕКРАСКА ПОДТВЕРЖДАЕТСЯ КАЖДЫЙ КАДР, И ЭТО НЕ ЛИШНЕЕ. Кольцо бойцу могут
  // завести или снять не спрашивая нас (арена делает это при выходе на плиту и
  // при выбывании), и краска тогда потерялась бы молча. Проверка — сравнение
  // двух ссылок, стоит ноль.
  if (selected && selected.ring && selMat && selected.ring.material !== selMat) paintRing(selected);
}

// ── Кружок под ногами ────────────────────────────────────────────────────

/**
 * ЦВЕТ КОЛЬЦА ВЫБРАННОГО. Берётся из четырёх существующих ядер, новых нет.
 *
 * ⚠️ ЯРЧЕ БЕЛОГО, НО НЕ СВЕТИТСЯ. Обычное кольцо стоит на 0.34 — в цвете такая
 *    прозрачность не читалась бы вовсе. Ярче оно только заливкой: ни свечения,
 *    ни доп. смешивания, ни исключения из тонировки — на арене светится один
 *    разлом, и метка на полу не имеет права стать вторым источником света.
 */
const SEL_RING_OPACITY = 0.9;

/** Наш материал — один на всю сцену, у него меняется только цвет. */
let selMat = null;

function ensureSelMat() {
  if (!selMat) {
    selMat = new THREE.MeshBasicMaterial({
      color: 0xffffff, transparent: true, opacity: SEL_RING_OPACITY, depthWrite: false,
    });
  }
  return selMat;
}

/** Покрасить кольцо выбранного в цвет его ядра. */
function paintRing(u) {
  const mesh = u && u.ring;
  if (!mesh) return;                       // кольца у бойца нет — красить нечего
  const hex = u.spec && u.spec.coreId ? coreHue(u.spec.coreId) : '';
  if (!hex) return;                        // ядро неизвестно — оставляем белым
  const mat = ensureSelMat();
  mat.color.set(hex);
  // Прежний материал запоминается НА САМОМ КОЛЬЦЕ: так его вернёт даже тот, кто
  // не знает, каким он был, — и подмена не зависит от порядка вызовов.
  if (!mesh.userData.selBaseMat) mesh.userData.selBaseMat = mesh.material;
  mesh.material = mat;
}

/** Вернуть кольцу его обычный белый материал. */
function unpaintRing(u) {
  const mesh = u && u.ring;
  if (!mesh || !mesh.userData.selBaseMat) return;
  mesh.material = mesh.userData.selBaseMat;
  mesh.userData.selBaseMat = null;
}
