// spar.js — БОЙ ИЗ SPAR. То, что игрок собрал на экране настройки и понёс в бой.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Экран SPAR собирает сопернику ядро и кристаллы, а
// потом уводит игрока на настоящую арену — ту же, что во всех прочих режимах. По
// дороге собранное надо где-то держать. Держать его в сейфе прогресса нельзя:
// SPAR по своему уговору НИЧЕГО НИКУДА НЕ ЗАПИСЫВАЕТ, а запись в сейф боя ещё и
// затёрла бы игроку состав и режим, выбранные в воротах. Поэтому сборка живёт
// здесь — в памяти вкладки, ровно как ход забега и заряды кличей.
//
// ГДЕ ОН СТОИТ СРЕДИ ПРОЧИХ. Рядом с services/klich.js, services/buffs.js и
// services/command.js, по тому же образцу: правила посередине, между защищённой
// ареной и экранами. Ни арена, ни экран не знают друг о друге.
//
// ⚠️ ЭТОТ ФАЙЛ НЕ ТЯНЕТ НИ ХРАНИЛИЩЕ, НИ РОУТЕР. Он только держит запись. Кто её
//    кладёт и кто читает — решают те, кто его зовёт; иначе он бы оказался вторым
//    местом, знающим устройство боя.
//
// ⚠️ ЗАПИСЬ НАБЛЮДАЕМАЯ, И ЭТО НЕ УКРАШЕНИЕ. Её читают геттеры состояния боя, а
//    геттеры Vuex кешируются: обычную переменную модуля они бы не заметили и
//    отдали бы арене сторону игрока, посчитанную ДО ухода в SPAR. Поймано до
//    первого прогона, разбором устройства геттеров. Ссылка поверхностная
//    (shallowRef): внутрь дерева соперника никто не смотрит по частям, его меняют
//    целиком, и глубокое наблюдение стоило бы обхода пятнадцати кристаллов даром.
//
// ⚠️ УМИРАЕТ ВМЕСТЕ СО СТРАНИЦЕЙ, И ЭТО НАРОЧНО. Обновление страницы посреди боя
//    в SPAR теряет сборку — как обычный бой теряет свой ход. Сторож арены на
//    этот случай уводит игрока назад в SPAR, а не выбрасывает на выбор состава.
//
// ⚠️ SPAR НИЧЕГО НЕ НАЧИСЛЯЕТ И НЕ СПИСЫВАЕТ. Признак отсюда читают три места, и
//    каждое гасит свою запись в прогресс: итог боя не даёт LASH, баффы не
//    списываются из запаса, стартовый запас не выдаётся. Четвёртого места, где
//    бой пишет в прогресс, в игре нет — проверено поиском (см. отчёт разведки).
//
// Экспортирует: setSparBout, readSparBout, isSparBout, clearSparBout.
import { shallowRef } from 'vue';

/**
 * @typedef {object} SparBout
 * @property {string} fighterId   боец игрока — идентификатор в списке бойцов
 * @property {string} foeCoreId   ядро соперника
 * @property {Array}  foeTree     дерево соперника («Печать» с зажжёнными кристаллами)
 * @property {Array<string|null>} myKit  баффы своего бойца, три слота
 * @property {Array<string|null>} foeKit баффы соперника, три слота
 */

/** @type {import('vue').ShallowRef<SparBout|null>} */
const bout = shallowRef(null);

/**
 * Дерево копируется, а не берётся ссылкой. Экран SPAR остаётся живым, пока идёт
 * бой (игрок вернётся в него и будет править сборку дальше) — и правка на экране
 * не должна менять соперника, который уже на плите.
 */
const copyTree = (tree) => (Array.isArray(tree)
  ? tree.map((branch) => ({ ...branch, faces: (branch.faces || []).map((f) => ({ ...f })) }))
  : null);

/** Три слота ровно, чем бы ни позвали: набор из четырёх молча дал бы четвёртый бафф. */
const copyKit = (kit) => {
  const out = [null, null, null];
  if (Array.isArray(kit)) for (let i = 0; i < out.length; i++) out[i] = kit[i] || null;
  return out;
};

/**
 * Положить сборку и уйти в бой. Зовёт экран SPAR, и только он.
 *
 * Неполная сборка (нет бойца или не собралось дерево соперника) НИЧЕГО не
 * кладёт: бой без одной из сторон — это не бой, и лучше остаться на экране, чем
 * уехать на арену, где половина плиты пуста.
 *
 * @param {SparBout} rec
 * @returns {boolean} true — сборка принята, можно уходить на арену
 */
export function setSparBout(rec) {
  if (!rec || !rec.fighterId || !rec.foeCoreId || !Array.isArray(rec.foeTree)) {
    bout.value = null;
    return false;
  }
  bout.value = {
    fighterId: rec.fighterId,
    foeCoreId: rec.foeCoreId,
    foeTree: copyTree(rec.foeTree),
    myKit: copyKit(rec.myKit),
    foeKit: copyKit(rec.foeKit),
  };
  return true;
}

/** Сборка или null. */
export function readSparBout() {
  return bout.value;
}

/** Идёт ли бой из SPAR. Короткий вопрос для тех, кому нужен только признак. */
export function isSparBout() {
  return !!bout.value;
}

/**
 * Забыть сборку. Зовёт роутер на каждом переходе за пределы пары адресов
 * «SPAR ↔ арена SPAR» — по образцу признака показа, и ровно по той же причине:
 * признак, который никто не снимает, однажды переживёт свой экран и молча
 * подменит соперника в обычном бою.
 */
export function clearSparBout() {
  bout.value = null;
}
