//    неё «камера не завелась» и «клавиши не доходят» выглядят одинаково.
//
//    Отсюда же: закрытое хранилище вкладки больше не отнимает у игрока камеру.
//    Раньше отнимало — признак не удавалось запомнить, и полёт не включался.
//    Теперь потеря признака стоит только подсказки.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИЗНАК, А НЕ `?dev=1`. Служебный режим вытаскивает в кадр
// панель, счётчики и линейки. Этот признак не даёт ни одной из них — только
// метку готовности, и больше ничего.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧТЕНИЕ АДРЕСА В СЦЕНЕ. Ровно та же причина, по
// которой так устроен `devMode.js`, и она проверена на нём: прямой заход на
// `/play/arena?freecam=1` отбивается стражем арены (без выбранного бойца туда
// нельзя), а отбой уводит на другой адрес УЖЕ БЕЗ признака. Сцена арены
// смонтировалась бы без него, и включить полёт было бы нельзя ничем. Признак
// обязан читаться ОДИН РАЗ ПРИ ЗАГРУЗКЕ СТРАНИЦЫ, до всякой навигации.
//
// Отсюда же следует удобство показа: признак ставится один раз на любом адресе
// («/play/home?freecam=1»), переживает всю дорогу до арены и живёт до конца
// вкладки. Набирать его в адресной строке перед самым боем не надо.
//
// ⚠️ ПРАВИЛО, ОБЩЕЕ С `devMode.js` И С ПРИЗНАКОМ ПОКАЗА. Этот признак управляет
//    ТОЛЬКО меткой. Он НИКОГДА не включает думающий мозг модели и ничего, что
//    стоит денег: его подставит кто угодно из адресной строки.
//
// ⚠️ И ОН НИЧЕГО НЕ МЕНЯЕТ В БОЮ. Камера только смотрит: бойцы не замирают, ход
//    боя и расчёт урона не трогаются вовсе.

const KEY = 'hexlash_freecam';

/** Решается ОДИН РАЗ при загрузке страницы. Дальше только читается. */
export const FREE_CAM_MODE = (() => {
  try {
    const q = new URLSearchParams(window.location.search).get('freecam');
    if (q === '1') { sessionStorage.setItem(KEY, '1'); return true; }
    if (q === '0') { sessionStorage.removeItem(KEY); return false; }
    return sessionStorage.getItem(KEY) === '1';
  } catch (_) {
    // Нет окна или хранилище закрыто настройками браузера. Молчим и не даём
    // полёт: ошибиться в сторону «выключено» безопаснее, чем в сторону «жив
    // лишний обработчик клавиш у игрока».
    return false;
  }
})();
