/**
 * ПЕРЕХВАТ — управление возвращается игроку немедленно.
 *
 * Зовётся из трёх мест (ТЗ): тап по тумблеру, тап по любой карте рычага, тап по
 * бойцу. Ограничений на число перехватов нет.
 *
 * ⚠️ УЖЕ ПРИМЕНЁННОЕ НЕ ОТКАТЫВАЕТСЯ, И ЗАРЯДЫ НЕ ВОЗВРАЩАЮТСЯ (ТЗ). Перехват
 *    — это «дальше веду я», а не «отменить то, что она успела».
 */
export function takeOver() {
  if (!commandState.legendLeads) return;
  commandState.legendLeads = false;
}

/** Тап по самому тумблеру: туда и обратно, сколько угодно раз. */
export function toggleCommand() {
  if (!commandState.active) return;
  commandState.legendLeads = !commandState.legendLeads;
}

// ── Кадр ─────────────────────────────────────────────────────────────────

/**
 * ГДЕ НАЧАЛО И КОНЕЦ БОЯ. Своих объявлений о них у командования нет — они
 * выводятся из того, идёт ли бой прямо сейчас.
 *
 * ⚠️ ПОЧЕМУ НЕ ПОПРОСИТЬ ПОЗВАТЬ НАС НА СТАРТЕ. Тогда выбору пришлось бы знать
 *    про командование по имени, а это ровно то кольцо, которого мы избегаем
 *    (см. шапку). Переход «боя не было → бой идёт» — тот же факт, добытый без
 *    кольца. Всё-мертвы в середине боя читается как конец, и это верно: бой на
 *    этом и кончается.
 */
let wasLive = false;

/**
 * Кадр. Приходит подпиской из services/fighterSelect.js — он привязан к арене,
 * получает кадр, держит поле боя и идёт ПОСЛЕДНИМ из трёх кадров рычагов, так что
 * заряды с откатами на этот кадр уже пересчитаны и легенда читает свежее.
 *
 * @param {number} t     время боя (часы арены)
 * @param {object} fld   поле боя
 * @param {boolean} live идёт ли бой (есть кого выбрать на стороне игрока)
 */
function frame(t, fld, live) {
  nowT = t;
  field = fld;

  if (live && !wasLive) startFight();
  if (!live && wasLive) endFight();
  wasLive = live;

  if (!live || !field) { commandState.active = false; return; }

  // Состав: отметка только растёт (см. squadSeen).
  const own = ourSide();
  if (own.length > squadSeen) squadSeen = own.length;

  // Тумблер возможен? Легенда есть И состав не одиночный.
  //
  // ⚠️ БОЙ-НАСТРОЙКА SPAR — ИМЕНОВАННОЕ ИСКЛЮЧЕНИЕ (решение владельца 27.09.2026).
  //    Там состав всегда одиночный, а посмотреть, как легенда ведёт бой, нужно
  //    именно вблизи — за этим SPAR и сделан. Условие для него одно: легенда есть.
  //
  //    ⚠️ ЭТО ИСКЛЮЧЕНИЕ СТОИТ ДЕНЕГ, И ЦЕНА ИЗВЕСТНА. Правило «легенда и тела
  //       НИКОГДА не думают в одном бою» здесь перестаёт держаться: бой в SPAR
  //       один на один, значит оба тела думают моделью (по 12 обращений), и
  //       легенда добавляет сверху свои 5 — 29 обращений за бой вместо 24.
  //       Владелец принял этот рост осознанно. Подробный разбор — в
  //       data/commandBalance.js, у потолка обращений легенды.
  commandState.active = !!legendRec && (squadSeen > 1 || isSparBout());
  if (!commandState.active) { commandState.legendLeads = false; commandState.line = ''; return; }

  // Строка решений гаснет сама, по своим часам.
  if (commandState.line && nowT >= lineUntil) { commandState.line = ''; commandState.reply = ''; }

  if (!commandState.legendLeads) return;

  // Все свои мертвы — легенда молчит (ТЗ). Строка при этом уже погашена выше
  // или погаснет по сроку: обрывать её на полуслове незачем.
  if (!own.length) return;

  // Правило 4: первые секунды боя не делается ВООБЩЕ ничего.
  if (nowT < C.quietStartSec) return;

  // ДУМАЮЩИЙ МОЗГ. Будится на переломах, ответ приходит когда придёт; пока его
  // нет — работает табличка, ровно как до части B. Мозга может не быть вовсе
  // (нет накладки, нет сети, нет ключа) — тогда весь этот кусок стоит ноль.
  //
  // ⚠️ СТОИТ ПОСЛЕ ТИХИХ ПЕРВЫХ СЕКУНД, А НЕ ПЕРЕД НИМИ, И ЭТО НЕ МЕЛОЧЬ.
  //    Первая побудка — «бой начался», общий настрой на состав. Если будить в
  //    нулевой кадр, ответ придёт секунды через полторы, а взять его легенда
  //    сможет только на пятой — и он к тому моменту протух по своему же сроку
  //    годности. Обращение сгорело бы впустую КАЖДЫЙ бой, ровно одно из пяти.
  //    Поэтому «старт боя» для легенды — это первый миг, когда ей вообще
  //    позволено действовать, а не первый кадр на часах.
  //
  // ⚠️ ПАУЗА МЕЖДУ ДЕЙСТВИЯМИ БУДИТЬ НЕ МЕШАЕТ, И ТОЖЕ НАРОЧНО. Перелом может
  //    случиться в середине паузы, и не заметить его значило бы пропустить
  //    именно тот момент, ради которого модель и нужна.
  if (brainAlive()) brainTick(nowT, buildBrainPayload, own, foeSide());

  // Своя пауза между действиями, поверх откатов рычагов.
  if (nowT - lastActAt < C.minGapSec) return;

  // Совет модели, если он есть и не протух. Потребляется один раз.
  const advice = brainAlive() ? takeBrainAdvice(nowT) : null;
  if (advice) {
    // «Ничего не тратить» — это РЕШЕНИЕ, а не отказ отвечать. Табличку на этот
    // раз не спрашиваем: иначе она молча переиграла бы легенду, которая только
    // что решила беречь заряд. Реплику при этом показываем — легенда сказала,
    // почему молчит рычагами.
    if (advice.lever === 'none') { sayOnly(advice.line); return; }
    const plan = planFromAdvice(advice, own);
    if (plan) { act(plan, advice.line); return; }
    // Совет оказался неисполним (боец умер, пока ответ летел; заряд кончился) —
    // тихо падаем на табличку, как при любом другом отказе.
  }

  const plan = decide(own);
  if (!plan) return;
  act(plan);
}

