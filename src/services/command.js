let nowT = 0;
/** Когда легенда действовала последний раз. */
let lastActAt = -Infinity;
/** До какого времени держать строку решений. */
let lineUntil = 0;
/**
 * ЗАПИСЬ ЛЕГЕНДЫ из сейфа ростера, либо null. Говорят СНАРУЖИ.
 *
 * ⚠️ ПОЧЕМУ НЕ СПРОСИТЬ НАПРЯМУЮ. Ни один файл в services/ не тянет Vuex, и
 *    заводить первый такой не за чем: накладка, у которой доступ к хранилищу
 *    есть по праву, отдаёт запись одной строкой. Null по умолчанию —
 *    намеренно: не сказали ничего, значит легенды нет и тумблера нет.
 *
 * ⚠️ РАНЬШЕ ЗДЕСЬ ЛЕЖАЛО ОДНО «ДА/НЕТ», И ЭТОГО СТАЛО МАЛО. Строка решений
 *    подписывается ИМЕНЕМ легенды (правка к ТЗ части B), а имя живёт в самой
 *    записи. Брать запись целиком, а не выковыривать из неё имя снаружи, —
 *    решение на один шаг вперёд: голосу легенды из части B понадобятся оттуда
 *    же ядро и зажжённые грани, и второй двери для них заводить не придётся.
 */
let legendRec = null;
/**
 * Сколько своих БЫВАЛО на плите в этом бою, наибольшее.
 *
 * ⚠️ НАИБОЛЬШЕЕ, А НЕ СЕЙЧАШНЕЕ, И ЭТО ВАЖНО. Условие тумблера — «состав не
 *    одиночный» (решение владельца: считаем бойцов, а режимы не перечисляем).
 *    Считать по живым СЕЙЧАС нельзя двумя способами сразу: на первых кадрах
 *    плита ещё ПУСТА, бойцов ставят позже (та же ловушка, на которой замирал ряд
 *    карт клича), — и тумблер не появился бы вовсе; а к концу боя своих остаётся
 *    один, и тумблер исчезал бы у игрока из-под пальца посреди боя. Поэтому
 *    отметка только растёт и живёт до конца боя.
 */
let squadSeen = 0;
/**
 * Что легенда наложила и до какого времени: боец → { lever, until }.
 *
 * ⚠️ ЗАЧЕМ СВОЯ ЗАПИСЬ, КОГДА ЕСТЬ КЛИЧ. Чтобы не кричать одно и то же одному
 *    и тому же, пока прежний крик ещё действует: заряды кончились бы за десять
 *    секунд, а манера бойца от повтора не изменилась бы. Клич свой список
 *    наружу не отдаёт, и заставлять его — лишняя правка ради одной проверки.
 *    Запись приблизительная НАРОЧНО: разойдётся она только в сторону
 *    осторожности (легенда промолчит лишний раз), а павшие из неё вычищаются.
 */
const mine = new Map();

// ── Снаружи ──────────────────────────────────────────────────────────────

/**
 * Отдать команде запись легенды (или null, когда её нет). Зовёт накладка.
 *
 * Имя считается здесь и сразу: оно меняется только вместе с записью, а
 * пересчитывать его на каждое решение значило бы делать одну и ту же работу
 * трижды за бой.
 */
export function setLegend(rec) {
  legendRec = rec || null;
  commandState.who = legendRec ? legendName(legendRec) : '';
  if (!legendRec) { commandState.legendLeads = false; commandState.active = false; }
}

/**
 * ⚠️ ЖАЛОБА НА ДЫРУ В ЗАПИСИ — РОВНО ОДИН РАЗ. Имени нет ни в каком виде —
 *    значит запись легенды битая, и об этом просят доложить отдельно (правка к
 *    ТЗ). Но проверка стоит на каждой смене записи, а жаловаться в консоль по
 *    кругу — заваливать её мусором; тот же приём и та же причина, что у жалобы
 *    на недоступный думающий мозг в бойце.
 */
let namelessWarned = false;

/**
 * ЧЬИМ ИМЕНЕМ ПОДПИСАНА СТРОКА РЕШЕНИЙ. Три ступени, вниз до первой, которая
 * дала имя.
 *
 * ⚠️ ПОЗЫВНОЙ ИСХОДНОГО БОЙЦА — ГЛАВНЫЙ И ЕДИНСТВЕННЫЙ ЖЕЛАЕМЫЙ ОТВЕТ. Легенда
 *    — это конкретный боец, который дошёл до вознесения; звать его служебным
 *    словом LEGEND ровно так же неверно, как звать бойца словом FIGHTER.
 *    Позывной кладётся в запись в момент обряда (ростер, ASCEND) и переживает
 *    сейф: восстановление вообще ОТБРАСЫВАЕТ запись без строкового позывного,
 *    так что легенды без этого поля в памяти не бывает. Пустая строка поле
 *    проходит — вот её и отсекаем.
 *
 * ⚠️ ЯДРО — ВТОРАЯ СТУПЕНЬ ПО УЖЕ ДЕЙСТВУЮЩЕМУ ПРАВИЛУ ОТ 26.09, а не по
 *    новому: строка решений уже зовёт союзного бота именем его ядра, когда
 *    позывного нет. Здесь то же правило и тот же источник имени.
 *
 * ⚠️ ЯДРО СПРАШИВАЕТСЯ ЧЕРЕЗ СВЕРКУ, А НЕ НА ВЕРУ. getCore на незнакомом ядре
 *    возвращает не пустоту, а BULWARK, — и это разумно там, где нужно хоть
 *    что-нибудь нарисовать, но здесь дало бы прямую ложь: строка подписалась бы
 *    ядром, которого у легенды нет. Сверка `.id === id` доказывает, что ядро
 *    правда нашлось, и не требует заводить второй список ядер.
 */
function legendName(rec) {
  const call = typeof rec.callsign === 'string' ? rec.callsign.trim() : '';
  if (call) return call;
  const core = rec.core ? getCore(rec.core) : null;
  if (core && core.id === rec.core) return core.name;
  // Ни позывного, ни ядра. Строка останется со служебным LEGEND — см. жалобу.
  if (!namelessWarned) {
    namelessWarned = true;
    try {
      console.warn('[command] у легенды нет ни позывного, ни ядра — строка решений подписывается служебным LEGEND', rec);
    } catch (_) { /* noop */ }
  }
  return '';
}

/** НОВЫЙ БОЙ. Тумблер в «ВЕДУ Я», отметка состава с нуля (ТЗ). */
function startFight() {
  commandState.legendLeads = false;
  commandState.line = '';
  commandState.reply = '';
  lastActAt = -Infinity;
  lineUntil = 0;
  squadSeen = 0;
  mine.clear();
  brainStartFight();
}

/** БОЙ КОНЧИЛСЯ. Тумблер уходит с экрана, ничего не переносится дальше. */
function endFight() {
  commandState.active = false;
  commandState.legendLeads = false;
  commandState.line = '';
  commandState.reply = '';
  lastActAt = -Infinity;
  lineUntil = 0;
  squadSeen = 0;
  mine.clear();
  field = null;
  brainStartFight();
}

