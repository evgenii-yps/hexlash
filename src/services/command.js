// command.js — КОМАНДОВАНИЕ. Тумблер, перехват и легенда, которая тратит
// рычаги по простым правилам.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Питч игры — «ты тренируешь ИИ, пока он не станет
// тренером». Восхождение уже есть, а легенда после него ничего не делала: круг
// обрывался. Здесь он замыкается минимальной честной формой — легенда нажимает
// ТЕ ЖЕ рычаги, что игрок, а игрок в любой миг забирает управление назад.
//
// ГДЕ ОН СТОИТ СРЕДИ ПРОЧИХ. Третьим рядом с services/klich.js и
// services/buffs.js, по тому же образцу: правила посередине, между защищённой
// ареной и накладками Vue. Ни арена, ни панель про команду не знают.
//
// ⚠️ ГЛАВНОЕ РЕШЕНИЕ: ЛЕГЕНДА ИДЁТ В ТУ ЖЕ ДВЕРЬ, ЧТО ПАЛЕЦ. Она не применяет
//    рычаг сама — она ВЫБИРАЕТ бойца и НАЖИМАЕТ карту, ровно теми же двумя
//    вызовами, какими это делает игрок (selectUnit + useKlichCard/useBuffCard).
//    Своей копии применения здесь нет НАРОЧНО: копия однажды разошлась бы с
//    оригиналом, и легенда стала бы «мочь» то, чего игрок не может, — например
//    кричать в откате или из пустого запаса. Отсюда же даром достаётся всё
//    остальное: заряды списываются те же, откат встаёт тот же, кружок под
//    ногами переезжает сам, значок над бойцом рисуется сам.
//
// ⚠️ ЭТО НЕ МОДЕЛЬ. Думающий мозг здесь не участвует и не включается ничем:
//    правила ниже — четыре сравнения чисел, они не стоят ни одного обращения к
//    модели и ни копейки. Признак из адресной строки тоже ничего здесь не
//    включает (то же правило, что у признака показа в арене).
//
// ⚠️ НИГДЕ НЕ СОХРАНЯЕТСЯ. Тумблер встаёт в «ВЕДУ Я» на каждом входе в бой (ТЗ)
//    и не переживает уход с арены. Это решение, а не недоделка: управление —
//    это то, что игрок берёт сейчас, а не то, что он когда-то настроил.
//
// ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ:
//   · не заводит своих чисел — все в data/commandBalance.js;
//   · не применяет рычаги сам — см. решение выше;
//   · не знает, есть ли легенда: ему это говорят снаружи (см. setLegendPresent);
//   · не рисует тумблер и строку — это components/command/CommandOverlay.vue.
//
// ⚠️ КАДР ПРИХОДИТ ПОДПИСКОЙ, А НЕ ВЫЗОВОМ СВЕРХУ. Командование стоит НАД выбором
//    бойца, кличем и баффом: оно двигает выбор и нажимает их карты. Значит звать
//    его по имени им нельзя — вышло бы кольцо в модулях. Поэтому подписываемся
//    сами, на загрузке файла (см. самый низ). А загружает нас накладка
//    components/command/CommandOverlay.vue: нет накладки — нет и командования,
//    что честно.
//
// Экспортирует: commandState, setLegendPresent, toggleCommand, takeOver.
import { reactive } from 'vue';
import { COMMAND_BALANCE as C } from '@/data/commandBalance.js';
import { KLICH_BALANCE } from '@/data/klichBalance.js';
import { getCore } from '@/data/upgradeData.js';
import { klichFightState, useKlichCard } from './klich.js';
import { buffFightState, useBuffCard, hasBuffOn } from './buffs.js';
import { selectUnit, onSelectFrame, onSelectTap } from './fighterSelect.js';

/**
 * ЧТО ВИДИТ ЭКРАН. Тумблер и строка решений читают отсюда и больше ниоткуда.
 *   active      — тумблер вообще возможен: бой идёт, легенда есть, и своих на
 *                 плите больше одного. Ложь — тумблера НЕТ НА ЭКРАНЕ ВОВСЕ
 *                 (ТЗ: не выключенного, не серого, а отсутствующего).
 *   legendLeads — позиция тумблера. Ложь = «ВЕДУ Я».
 *   line        — строка решений или пустая строка. Пустая = молчит.
 */
export const commandState = reactive({
  active: false,
  legendLeads: false,
  line: '',
});

/** Поле боя. Приходит каждый кадр, своей привязки к арене у команды нет. */
let field = null;
/** Время боя (часы арены). */
let nowT = 0;
/** Когда легенда действовала последний раз. */
let lastActAt = -Infinity;
/** До какого времени держать строку решений. */
let lineUntil = 0;
/**
 * Есть ли у игрока легенда. Говорят СНАРУЖИ.
 *
 * ⚠️ ПОЧЕМУ НЕ СПРОСИТЬ НАПРЯМУЮ. Ни один файл в services/ не тянет Vuex, и
 *    заводить первый такой не за чем: команде нужен один-единственный факт, и
 *    накладка, у которой доступ к хранилищу есть по праву, отдаёт его одной
 *    строкой. Ложь по умолчанию — намеренно: не сказали ничего, значит легенды
 *    нет и тумблера нет.
 */
let legendPresent = false;
/**
 * Сколько своих БЫВАЛО на плите в этом бою, наибольшее.
 *
 * ⚠️ НАИБОЛЬШЕЕ, А НЕ СЕЙЧАШНЕЕ, И ЭТО ВАЖНО. Условие тумблера — «состав не
 *    одиночный» (решение владельца: считаем бойцов, а режимы не перечисляем).
 *    Считать по живым СЕЙЧАС нельзя двумя способами сразу: на первых кадрах
 *    плита ещё ПУСТА, бойцов ставят позже (та же ловушка, на которой замирал ряд
 *    карт клича), — и тумблер не появился бы вовсе; а к концу боя своих остаётся
 *    один, и тумблер исчезал бы у игрока из-под пальца посреди боя. Поэтому
 *    отметка только растёт и живёт до конца боя.
 */
let squadSeen = 0;
/**
 * Что легенда наложила и до какого времени: боец → { lever, until }.
 *
 * ⚠️ ЗАЧЕМ СВОЯ ЗАПИСЬ, КОГДА ЕСТЬ КЛИЧ. Чтобы не кричать одно и то же одному
 *    и тому же, пока прежний крик ещё действует: заряды кончились бы за десять
 *    секунд, а манера бойца от повтора не изменилась бы. Клич свой список
 *    наружу не отдаёт, и заставлять его — лишняя правка ради одной проверки.
 *    Запись приблизительная НАРОЧНО: разойдётся она только в сторону
 *    осторожности (легенда промолчит лишний раз), а павшие из неё вычищаются.
 */
const mine = new Map();

// ── Снаружи ──────────────────────────────────────────────────────────────

/** Сказать команде, есть ли у игрока легенда. Зовёт накладка. */
export function setLegendPresent(on) {
  legendPresent = !!on;
  if (!legendPresent) { commandState.legendLeads = false; commandState.active = false; }
}

/** НОВЫЙ БОЙ. Тумблер в «ВЕДУ Я», отметка состава с нуля (ТЗ). */
function startFight() {
  commandState.legendLeads = false;
  commandState.line = '';
  lastActAt = -Infinity;
  lineUntil = 0;
  squadSeen = 0;
  mine.clear();
}

/** БОЙ КОНЧИЛСЯ. Тумблер уходит с экрана, ничего не переносится дальше. */
function endFight() {
  commandState.active = false;
  commandState.legendLeads = false;
  commandState.line = '';
  lastActAt = -Infinity;
  lineUntil = 0;
  squadSeen = 0;
  mine.clear();
  field = null;
}

// ── Тумблер и перехват ───────────────────────────────────────────────────

/**
 * ПЕРЕХВАТ — управление возвращается игроку немедленно.
 *
 * Зовётся из трёх мест (ТЗ): тап по тумблеру, тап по любой карте рычага, тап по
 * бойцу. Ограничений на число перехватов нет.
 *
 * ⚠️ УЖЕ ПРИМЕНЁННОЕ НЕ ОТКАТЫВАЕТСЯ, И ЗАРЯДЫ НЕ ВОЗВРАЩАЮТСЯ (ТЗ). Перехват
 *    — это «дальше веду я», а не «отменить то, что она успела».
 */
export function takeOver() {
  if (!commandState.legendLeads) return;
  commandState.legendLeads = false;
}

/** Тап по самому тумблеру: туда и обратно, сколько угодно раз. */
export function toggleCommand() {
  if (!commandState.active) return;
  commandState.legendLeads = !commandState.legendLeads;
}

// ── Кадр ─────────────────────────────────────────────────────────────────

/**
 * ГДЕ НАЧАЛО И КОНЕЦ БОЯ. Своих объявлений о них у командования нет — они
 * выводятся из того, идёт ли бой прямо сейчас.
 *
 * ⚠️ ПОЧЕМУ НЕ ПОПРОСИТЬ ПОЗВАТЬ НАС НА СТАРТЕ. Тогда выбору пришлось бы знать
 *    про командование по имени, а это ровно то кольцо, которого мы избегаем
 *    (см. шапку). Переход «боя не было → бой идёт» — тот же факт, добытый без
 *    кольца. Всё-мертвы в середине боя читается как конец, и это верно: бой на
 *    этом и кончается.
 */
let wasLive = false;

/**
 * Кадр. Приходит подпиской из services/fighterSelect.js — он привязан к арене,
 * получает кадр, держит поле боя и идёт ПОСЛЕДНИМ из трёх кадров рычагов, так что
 * заряды с откатами на этот кадр уже пересчитаны и легенда читает свежее.
 *
 * @param {number} t     время боя (часы арены)
 * @param {object} fld   поле боя
 * @param {boolean} live идёт ли бой (есть кого выбрать на стороне игрока)
 */
function frame(t, fld, live) {
  nowT = t;
  field = fld;

  if (live && !wasLive) startFight();
  if (!live && wasLive) endFight();
  wasLive = live;

  if (!live || !field) { commandState.active = false; return; }

  // Состав: отметка только растёт (см. squadSeen).
  const own = ourSide();
  if (own.length > squadSeen) squadSeen = own.length;

  // Тумблер возможен? Легенда есть И состав не одиночный.
  commandState.active = legendPresent && squadSeen > 1;
  if (!commandState.active) { commandState.legendLeads = false; commandState.line = ''; return; }

  // Строка решений гаснет сама, по своим часам.
  if (commandState.line && nowT >= lineUntil) commandState.line = '';

  if (!commandState.legendLeads) return;

  // Все свои мертвы — легенда молчит (ТЗ). Строка при этом уже погашена выше
  // или погаснет по сроку: обрывать её на полуслове незачем.
  if (!own.length) return;

  // Правило 4: первые секунды боя не делается ВООБЩЕ ничего.
  if (nowT < C.quietStartSec) return;
  // Своя пауза между действиями, поверх откатов рычагов.
  if (nowT - lastActAt < C.minGapSec) return;

  const plan = decide(own);
  if (!plan) return;
  act(plan);
}

// ── Правила ──────────────────────────────────────────────────────────────

/** Живые на стороне игрока. И свои, и союзные боты — как у выбора бойца. */
function ourSide() {
  if (!field) return [];
  return field.living().filter((u) => u.sideId === 'player');
}

/** Живые на всех прочих сторонах. Сторон в бою бывает больше двух. */
function foeSide() {
  if (!field) return [];
  return field.living().filter((u) => u.sideId !== 'player');
}

/** Доля здоровья от полного. Та же арифметика, что у автомата ботов в баффах. */
function hp01(u) {
  const f = u && u.f;
  if (!f || !f.maxHp) return 1;
  return f.getHp() / f.maxHp;
}

/** Расстояние между двумя бойцами на плите. */
function gapBetween(a, b) {
  if (!a || !b || !a.f || !b.f) return Infinity;
  return a.f.group.position.distanceTo(b.f.group.position);
}

/** Свободен ли клич прямо сейчас: заряд есть И откат прошёл. */
function klichFree(id) {
  const card = klichFightState.cards.find((c) => c.id === id);
  if (!card || card.left <= 0) return false;
  const cool = klichFightState.cool[id];
  return !(cool && cool.left > 0.05);
}

/** Сколько зарядов у клича осталось. Ноль и для клича, которого нет. */
function klichLeft(id) {
  const card = klichFightState.cards.find((c) => c.id === id);
  return card ? card.left : 0;
}

/**
 * Свободен ли бафф прямо сейчас. Вида может не быть в наборе вовсе — игрок
 * берёт в бой то, что купил, и пустой запас это честное «нечем» (ТЗ: легенда
 * тогда просто ждёт, без сообщений «не могу»).
 */
function buffFree(id) {
  const card = buffFightState.cards.find((c) => c.id === id);
  if (!card || card.left <= 0) return false;
  const cool = buffFightState.cool[id];
  return !(cool && cool.left > 0.05);
}

/** Не действует ли ЕЩЁ на бойце тот же самый рычаг от легенды. */
function stillMine(unit, lever) {
  const e = mine.get(unit);
  return !!e && e.lever === lever && nowT < e.until;
}

/**
 * ЧТО СДЕЛАТЬ ПРЯМО СЕЙЧАС. Четыре правила из ТЗ, по порядку, до первого
 * сработавшего. Своей сообразительности здесь нет и не должно быть: это
 * «связно», а не «умно».
 *
 * ⚠️ ПОСЛЕДНИЙ ЗАРЯД КЛИЧА ЛЕГЕНДА БЕРЕЖЁТ (ТЗ): его можно тратить только
 *    когда кто-то из своих в критическом здоровье. Правило 1 — единственное,
 *    которое работает именно в этом случае, поэтому правилам 2 и 3 нужно два
 *    заряда, а правилу 1 довольно одного. Проверка выражена ровно так, а не
 *    отдельным условием в трёх местах.
 */
function decide(own) {
  // ── Правило 1. СВОЙ ПАДАЕТ — спасаем. Самого израненного из всех.
  const hurt = own
    .filter((u) => hp01(u) < C.hurtHp01)
    .sort((a, b) => hp01(a) - hp01(b))[0];
  if (hurt) {
    // Сначала клич: он бесплатный и живёт один бой.
    if (klichFree('hold') && !stillMine(hurt, 'hold')) {
      return { kind: 'klich', lever: 'hold', unit: hurt };
    }
    // ДЕРЖАТЬ в откате или кончился — бафф восстановления (ТЗ, правило 1).
    //
    // ⚠️ БАФФ — ТОЛЬКО ЗДЕСЬ, И БОЛЬШЕ НИГДЕ (решение владельца). Автомат ботов
    //    в баффах кидает их «по ходу боя» на трёх разных условиях; легенда так
    //    НЕ делает. Причина простая: бафф — купленный товар, он живёт между
    //    боями и стоит монеты, а клич выдаётся на бой бесплатно. Легенда, которая
    //    тратит купленное «просто так», обчищала бы игрока за его же спиной.
    //    Поэтому бафф у неё — крайняя мера в единственном случае: своего сейчас
    //    убьют, а крикнуть нечем.
    if (buffFree('towel') && !hasBuffOn(hurt)) {
      return { kind: 'buff', lever: 'towel', unit: hurt };
    }
    // Нечем спасать — ждём отката. Ниже не идём НАРОЧНО: пока своего убивают,
    // добивать чужого и отступать неуместно, даже если правила 2 и 3 сошлись.
    return null;
  }

  // Дальше правила тратят заряды «не по нужде» — значит последний берегут.
  const spare = (id) => klichFree(id) && klichLeft(id) > 1;

  // ── Правило 2. ЧУЖОЙ ПРИ СМЕРТИ и рядом есть свежий свой — добиваем.
  if (spare('push')) {
    for (const foe of foeSide()) {
      if (hp01(foe) >= C.foeWeakHp01) continue;
      const pusher = own.find((u) => hp01(u) > C.pusherHp01
        && gapBetween(u, foe) < C.nearDist
        && !stillMine(u, 'push'));
      if (pusher) return { kind: 'klich', lever: 'push', unit: pusher };
    }
  }

  // ── Правило 3. НАС МЕНЬШЕ — самого слабого в отход.
  if (spare('fallback') && own.length < foeSide().length) {
    const weakest = [...own].sort((a, b) => hp01(a) - hp01(b))[0];
    if (weakest && !stillMine(weakest, 'fallback')) {
      return { kind: 'klich', lever: 'fallback', unit: weakest };
    }
  }

  return null;
}

// ── Действие ─────────────────────────────────────────────────────────────

/**
 * ВЫБРАТЬ И НАЖАТЬ — теми же двумя вызовами, что и палец игрока.
 *
 * ⚠️ ПОРЯДОК ОБЯЗАТЕЛЕН: сначала выбор, потом карта. Карта кричит ВЫБРАННОМУ, и
 *    если выбор не переехал, легенда крикнет не тому. Заодно этим и держится
 *    обещание ТЗ «видно, куда она бьёт»: кружок под ногами переезжает не ради
 *    показа, а потому что это и есть её цель.
 *
 * ⚠️ СТРОКА ПИШЕТСЯ ТОЛЬКО ПО ФАКТУ. Карта может отказать (боец погиб в этот
 *    самый кадр, запас опустел во второй вкладке) — тогда заряд не списан, и
 *    сказать «легенда крикнула» было бы враньём. Поэтому обе двери возвращают
 *    «получилось или нет», и молчание здесь честнее сообщения.
 */
function act(plan) {
  const { kind, lever, unit } = plan;
  if (!unit || unit.dead) return;

  selectUnit(unit);
  const ok = kind === 'klich' ? useKlichCard(lever) : useBuffCard(lever);
  if (!ok) return;

  lastActAt = nowT;
  mine.set(unit, { lever, until: nowT + holdOf(kind) });
  commandState.line = lineFor(lever, unit);
  lineUntil = nowT + C.lineHoldSec;

  // Павшие из записи вычищаются здесь: своего кадра у неё нет, а бойцов на плите
  // единицы — перебрать их раз в три секунды стоит ноль.
  for (const [u] of [...mine]) if (u.dead) mine.delete(u);
}

/**
 * НА СКОЛЬКО ЛЕГЕНДА СЧИТАЕТ РЫЧАГ «ЕЩЁ ДЕЙСТВУЮЩИМ» — чтобы не кричать одно и
 * то же одному и тому же.
 *
 * Число берётся у самого клича и своего здесь нет (см. шапку commandBalance):
 * полную силу сдвиг несёт holdSec, потом тает fadeSec — всё это время повторять
 * его незачем.
 *
 * ⚠️ У БАФФА СВОЕЙ ЗАПИСИ НЕ ДЕРЖИМ, И ЭТО НАРОЧНО. Про баффы есть источник
 *    точнее — сам бафф (hasBuffOn): он отказывает второму баффу на том же бойце
 *    по своему правилу, и приблизительная копия срока рядом с точным ответом
 *    только однажды разошлась бы с ним. Поэтому баффу довольно паузы между
 *    действиями.
 */
function holdOf(kind) {
  if (kind !== 'klich') return C.minGapSec;
  return KLICH_BALANCE.holdSec + KLICH_BALANCE.fadeSec;
}

/**
 * СТРОКА РЕШЕНИЙ — служебная и прямая, как требует ТЗ. Голос ядра и человеческая
 * формулировка — часть B; выдумывать её здесь нельзя.
 *
 * ⚠️ БАФФ НАЗЫВАЕТСЯ ТАК ЖЕ ЯВНО, КАК КЛИЧ (решение владельца). Игрок не должен
 *    узнавать о потраченном полотенце по опустевшему запасу.
 *
 * ⚠️ ИМЕНА РЫЧАГОВ БЕРУТСЯ У САМИХ РЫЧАГОВ, А НЕ ПИШУТСЯ ЗДЕСЬ. Второй список
 *    названий разошёлся бы с первым при первой же правке, и строка начала бы
 *    называть рычаг иначе, чем карта под ним.
 *
 * ⚠️ У СОЮЗНОГО БОТА ПОЗЫВНОГО НЕТ — ТОГДА ЗОВЁМ ЕГО ИМЕНЕМ ЯДРА. Правило не
 *    новое: так уже решено для панели выбранного бойца («заголовок — ник бойца,
 *    а у союзного бота имя его ядра»), и здесь взято оттуда же вместе с
 *    источником имени. Без этого строка обрывалась бы на рычаге — а в рейде
 *    своих бойцов у игрока один из четырёх, и цели не было бы почти никогда.
 *
 * ⚠️ ЯДРО СПРАШИВАЕТСЯ, ТОЛЬКО ЕСЛИ ОНО ЕСТЬ. getCore на незнакомом ядре
 *    возвращает не пустоту, а BULWARK — это разумно там, где нужно хоть
 *    что-нибудь нарисовать, но здесь дало бы прямую ложь: строка назвала бы
 *    цель ядром, которого у неё нет. Лучше без имени, чем с чужим.
 */
function lineFor(lever, unit) {
  const k = klichFightState.cards.find((c) => c.id === lever);
  const b = buffFightState.cards.find((c) => c.id === lever);
  const name = (k && k.name) || (b && b.name) || lever.toUpperCase();
  const spec = unit.spec || {};
  const nick = spec.name || (spec.coreId ? getCore(spec.coreId).name : '');
  return nick ? `${name} → ${nick}` : name;
}

