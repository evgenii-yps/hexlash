// fightResult.js — ИТОГ БОЯ. Выиграл игрок или проиграл, и что делать дальше.
//
// ЗАЧЕМ ЭТО ВООБЩЕ. До этой работы арена не сообщала исход НИКАК: бой замирал, и
// всё. Без служебного режима на экране не оставалось ни одной кнопки — ни начать
// заново, ни уйти; единственной дверью была кнопка «назад» браузера. На поле из
// шести тел даже понять, чья сторона выстояла, было нельзя.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Про итог знают двое: арена (она одна знает, чем бой
// кончился) и панель (она одна знает, как об этом сказать). Держать это внутри
// арены значило бы, что панель лезет в защищённую сцену за исходом.
//
// ЗАБЕГ СЮДА НЕ ХОДИТ. У CHAIN свои панели и свой счёт раундов: победа в раунде
// там означает не «бой выигран», а «идём дальше». Арена включает этот итог
// только вне забега — см. её же endFight.
//
// ЗАРАБОТОК LASH ТОЖЕ ЗДЕСЬ, И ЭТО НЕ СЛУЧАЙНО. Конец боя — единственное место,
// где известно «бой кончился и вот чем». Если бы монеты начисляла сцена, их
// пришлось бы начислять в каждом её выходе из боя; если бы панель — они бы
// начислялись заново на каждом её показе. Здесь же вызов ровно один на бой.
//
// Экспортирует: fightResultState, showFightResult, hideFightResult, bindFightAgain.
import { reactive } from 'vue';
import { awardBoutLash } from './lash.js';

/**
 * Что показывает панель итога.
 *   visible — панель на экране
 *   outcome — 'victory' сторона игрока выстояла · 'defeat' пала
 */
export const fightResultState = reactive({
  visible: false,
  outcome: null,
  // Какой бой кончился. Заголовок от этого не зависит — победа есть победа, —
  // а строка под ним зависит: рейд выигран падением босса, а не тем, что своя
  // сторона осталась одна. Пусто = обычный бой.
  kind: null,
  // ГОТОВЫЕ СТРОКИ ОТ ТОГО, КТО ЗНАЕТ ИСХОД. Пусто — панель берёт свои, как
  // брала всегда.
  //
  // ЗАЧЕМ. У открытого поля исход — это МЕСТО («Place 7 of 20»), а место знает
  // только тот, кто считал бой. Разбирать режимы внутри панели (ещё один `if` по
  // имени режима, как у рейда) нельзя: панель одна на все режимы, и с каждым
  // новым она превращалась бы в список чужих правил. Здесь же вместо правила
  // лежит готовая строка, и панель по-прежнему не знает ни одного режима.
  titleOver: null,
  noteOver: null,
  // СКОЛЬКО МОНЕТ ДАЛ ЭТОТ БОЙ. 0 — панель про монеты молчит.
  lashGain: 0,
});

// Кто умеет начать новый бой. Ставит арена (только она это умеет), зовёт панель.
// Живёт здесь, а не в панели: панель не должна знать про сцену, а сцена — про
// кнопки. Снимается при уходе с арены, иначе следующая панель дёрнула бы
// разобранную сцену.
let fightAgain = null;

/** Арена отдаёт способ начать новый бой. Вернуть — снять. */
export function bindFightAgain(fn) {
  fightAgain = typeof fn === 'function' ? fn : null;
  return () => { if (fightAgain === fn) fightAgain = null; };
}

/**
 * Показать итог.
 * @param {boolean} won выстояла ли сторона игрока
 * @param {string?} kind какой это был бой — 'raid' или ничего для обычного
 * @param {object} [over] готовые строки вместо своих — { title, note }. См. причину
 *                 у titleOver выше. Не передан — панель говорит как говорила.
 */
export function showFightResult(won, kind = null, over = null) {
  // ⚠️ НАЧИСЛЕНИЕ РОВНО ОДНО НА БОЙ. Панель уже на экране — значит этот бой уже
  //    посчитан, и второй вызов (случайный повтор, два пути к итогу) не должен
  //    дать вторых монет. Выйти нельзя: строки итога всё равно надо обновить, —
  //    поэтому сторожится именно начисление, а не весь показ.
  //
  //    Обновление страницы вторых монет тоже не даёт: счётчик живёт в памяти, и
  //    после перезагрузки панели итога на экране нет — арена собирает новый бой.
  //    Уход из боя на полпути не даёт вовсе ничего: сюда просто не приходят.
  if (!fightResultState.visible) fightResultState.lashGain = awardBoutLash(won);
  fightResultState.outcome = won ? 'victory' : 'defeat';
  fightResultState.kind = kind || null;
  fightResultState.titleOver = (over && over.title) || null;
  fightResultState.noteOver = (over && over.note) || null;
  fightResultState.visible = true;
}

/** Убрать панель. */
export function hideFightResult() {
  fightResultState.visible = false;
  fightResultState.outcome = null;
  fightResultState.kind = null;
  fightResultState.titleOver = null;
  fightResultState.noteOver = null;
  fightResultState.lashGain = 0;
}

/**
 * Игрок нажал «драться снова». Панель уходит, арена собирает новый бой.
 *
 * ⚠️ Двойное нажатие: панель гасится ПЕРВОЙ строкой, и второе нажатие приходит
 *    уже к невидимой кнопке. Плюс сюда же — проверка на visible: без неё второе
 *    нажатие в тот же кадр, до перерисовки, запустило бы второй бой.
 */
export function fightAgainNow() {
  if (!fightResultState.visible) return false;
  hideFightResult();
  if (fightAgain) fightAgain();
  return true;
}
