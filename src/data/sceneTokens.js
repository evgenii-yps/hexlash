/* Второй тон ВЫВОДИТСЯ из основного — одно правило на все четыре ядра.
   Светлый конец — ink, а не чистый белый: #FFFFFF из проекта удалён. */
export const CORE_SUP_MIX = 0.65;

/** Тот же цвет в записи «r, g, b» — для rgba() в стилях. Выводится, не
    объявляется: rgb-копия цвета ядра была ещё одним его объявлением. */
export function coreRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}`;
}

/** Осветлённая пара к цвету ядра. Возвращает '#rrggbb'. */
export function coreSup(hex, mix = CORE_SUP_MIX) {
  const a = parseInt(hex.slice(1), 16);
  const b = parseInt(cssToken('--ink').slice(1), 16);
  const ch = (sh) => Math.round((((a >> sh) & 255) * mix) + (((b >> sh) & 255) * (1 - mix)));
  return `#${((ch(16) << 16) | (ch(8) << 8) | ch(0)).toString(16).padStart(6, '0')}`;
}

