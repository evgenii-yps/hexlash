/* ── ЧТЕНИЕ ТОКЕНОВ ИЗ СТИЛЕЙ ───────────────────────────────────────────────
   Цвет ядра объявлен ОДИН раз — в src/styles/tokens.css. Здесь его копии нет
   и быть не должно (Правка 1.3 §1): второе объявление — ошибка, даже когда
   значения совпадают. Ровно так когда-то разъехались вторые тона ядер, и ровно
   так в проде оказалось два разных логотипа.

   Чтение ЛЕНИВОЕ и с кэшем. Это не оптимизация, а гарантия момента:
   upgradeData.js подтягивается через хранилище на самом старте, и если читать
   при загрузке модуля, стили могут быть ещё не применены. Геттеры откладывают
   чтение до первого обращения — то есть до отрисовки компонента или сборки
   сцены, когда tokens.css заведомо на месте.

   Пустое значение — не повод подставить запасное число: запасное число и есть
   второе объявление. Поэтому здесь громкая ошибка. */
const _tokenCache = new Map();
function cssToken(name) {
  if (_tokenCache.has(name)) return _tokenCache.get(name);
  const raw = typeof document === 'undefined'
    ? ''
    : getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  if (!raw) {
    throw new Error(
      `[hexlash] токен ${name} не прочитался из стилей. Значение объявлено в ` +
      'src/styles/tokens.css и должно приходить только оттуда. Проверь, что ' +
      'tokens.css грузится первым в main.js. Возвращать сюда запасное число ' +
      'нельзя — это второе объявление (Правка 1.3 §1).',
    );
  }
  _tokenCache.set(name, raw);
  return raw;
}

