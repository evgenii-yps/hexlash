// commandBalance.js — ЧИСЛА КОМАНДОВАНИЯ. Когда легенда берётся за рычаг.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. ТЗ требует дословно: «пороги собрать в одном месте
// рядом с числами клича, чтобы правились без поиска по коду». Балансный проход
// — отдельная работа, и он будет править ровно этот файл и больше ничего.
//
// ⚠️ ЧИСЛА ЧЕРНОВЫЕ. Они взяты из ТЗ и НЕ выверены игрой. Пока легенда просто
//    ведёт себя связно; «ведёт хорошо» — задача баланса, не этой.
//
// ⚠️ ЗДЕСЬ НЕТ НИ ОДНОГО ЧИСЛА ПРО САМИ РЫЧАГИ. Сколько клич держится, сколько
//    стоит откат и сколько зарядов на бой — знают data/klichBalance.js и
//    data/buffBalance.js. Легенда их не переопределяет: она нажимает те же
//    рычаги на тех же условиях, что палец игрока, и второго набора правил у неё
//    быть не должно. Продублировать здесь, скажем, откат значило бы однажды
//    развести два числа и получить легенду, которая «может», когда игрок не
//    может.
//
// Экспортирует: COMMAND_BALANCE.

export const COMMAND_BALANCE = {
  /**
   * ПЕРВЫЕ СЕКУНДЫ БОЯ ЛЕГЕНДА МОЛЧИТ (правило 4). Пусть бой начнётся сам:
   * крик в первый же кадр читался бы как «она решила за меня ещё до того, как
   * что-то случилось».
   */
  quietStartSec: 5,

  /**
   * ПАУЗА МЕЖДУ ДВУМЯ ДЕЙСТВИЯМИ ЛЕГЕНДЫ. Своя, поверх откатов рычагов.
   *
   * ⚠️ БЕЗ НЕЁ ОНА ВЫГЛЯДИТ ДЁРГАНО, И ЭТО ГЛАВНАЯ ПРИЧИНА. Откаты у трёх
   *    кличей независимы, значит без этой паузы легенда могла бы в один кадр
   *    крикнуть одно, в следующий — другое, и игрок увидел бы не решение, а
   *    судороги. Три секунды — примерно темп, в котором человек успевает
   *    прочитать строку решений и связать её с тем, что на плите.
   */
  minGapSec: 3,

  /**
   * СВОЙ В КРИТИЧЕСКОМ ЗДОРОВЬЕ — доля от полного (правило 1). Ниже этого
   * легенда спасает: сначала ДЕРЖАТЬ, и только если нечем — бафф.
   */
  hurtHp01: 0.35,

  /**
   * ПРОТИВНИК ПРИ СМЕРТИ — доля от полного (правило 2). Ниже этого он добиваем.
   */
  foeWeakHp01: 0.25,

  /**
   * СВОЙ, КОТОРОМУ МОЖНО ДОВЕРИТЬ ДОБИВАНИЕ (правило 2). Выше этого он идёт
   * вперёд без риска обменяться и упасть самому.
   */
  pusherHp01: 0.60,

  /**
   * «РЯДОМ С НИМ» — в единицах мира, как у баффов (правило 2).
   *
   * ⚠️ ЧИСЛО ВЗЯТО ПО ОБРАЗЦУ ВЕДРА. У баффа уже есть порог «сблизился для
   *    атаки» (buffBalance.bot.bucketNearDist = 2.2), и заводить здесь другое
   *    понятие близости было бы враньём: близко на плите — это одно расстояние,
   *    а не два. Взято чуть шире: ведро ловит момент сближения, а легенда
   *    решает, успеет ли боец дойти.
   */
  nearDist: 2.4,

  /**
   * СКОЛЬКО ДЕРЖИТСЯ СТРОКА РЕШЕНИЙ, прежде чем погаснуть (ТЗ: ~4 секунды).
   * Длиннее паузы между действиями нарочно: иначе строка успевала бы погаснуть
   * между двумя решениями, и экран мигал бы пустотой.
   */
  lineHoldSec: 4,
};
