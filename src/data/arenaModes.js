// arenaModes.js — РЕЖИМЫ БОЯ. Что именно игрок выбирает на первых островах в
// воротах арены, и сколько бойцов этот выбор просит в состав.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Размер состава был константой `SQUAD_SIZE = 1` в
// состоянии боя. Пока режим один, константа и режим — одно и то же, и разницы
// не видно; как только режимов становится двое, константа оказывается вторым
// местом, где живёт то же самое число. Таблица здесь — единственный источник:
// состояние боя спрашивает размер у выбранного режима и своего числа не держит.
//
// ЗАПЕРТЫЙ РЕЖИМ — ЧЕСТНОЕ СОСТОЯНИЕ, А НЕ ЗАГЛУШКА. SQUAD стоит в списке с
// подписью SOON и не кликается. Это решение владельца: в большом пространстве
// запертый остров читается как «ещё не открыт», тогда как на плоском экране он
// читался бы как недоделка. Поэтому он здесь, а не вычеркнут до лучших времён.
//
// Экспортирует: ARENA_MODES, MODE_IDS, DEFAULT_MODE_ID, getMode, squadSizeOf.

/**
 * @typedef {object} ArenaMode
 * @property {string} id        внутренний ключ; он же лежит в сейфе
 * @property {string} name      подпись на острове
 * @property {string} tagline   строка под именем — что это за бой
 * @property {number} squadSize сколько бойцов игрок ведёт в этом режиме
 * @property {boolean} locked   заперт — остров виден, но не выбирается
 */

/** @type {ArenaMode[]} */
export const ARENA_MODES = [
  {
    id: 'duel',
    name: 'DUEL',
    tagline: 'ONE AGAINST ONE',
    // Один — потому что столько умеет бой. Это не «пока что один для простоты»:
    // движок ведёт ровно одну пару. Когда он научится большему, число меняется
    // здесь, и вся дорога — экран выбора, страж арены, сама арена — идёт за ним.
    squadSize: 1,
    locked: false,
  },
  {
    id: 'squad',
    name: 'SQUAD',
    tagline: 'TEAM AGAINST TEAM',
    // Размер объявлен заранее и намеренно: он нужен, чтобы состав из нескольких
    // бойцов был проверяем ДО того, как режим откроют. Экран выбора и сейф уже
    // умеют список любой длины — им незачем ждать открытия режима, чтобы это
    // выяснилось. Двое, а не трое: меньшая команда открывается первой.
    squadSize: 2,
    locked: true,
  },
];

export const MODE_IDS = ARENA_MODES.map((m) => m.id);

/** Режим по умолчанию — тот, которым дерутся, если выбор ещё не сделан. */
export const DEFAULT_MODE_ID = 'duel';

/**
 * Режим по ключу. Неизвестный ключ (старый сейф, ручная правка адреса) —
 * не ошибка: отдаём режим по умолчанию, чтобы дорога в бой не обрывалась.
 * @param {string|null|undefined} id
 * @returns {ArenaMode}
 */
export function getMode(id) {
  return ARENA_MODES.find((m) => m.id === id)
    || ARENA_MODES.find((m) => m.id === DEFAULT_MODE_ID);
}

/**
 * Сколько бойцов просит режим. Единственный способ узнать размер состава —
 * второго числа в проекте нет.
 * @param {string|null|undefined} id
 * @returns {number}
 */
export function squadSizeOf(id) {
  return getMode(id).squadSize;
}
