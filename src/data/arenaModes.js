export const MODE_IDS = ARENA_MODES.map((m) => m.id);

/** Режим по умолчанию — тот, которым дерутся, если выбор ещё не сделан. */
export const DEFAULT_MODE_ID = 'duel';

/**
 * Режим по ключу. Неизвестный ключ (старый сейф, ручная правка адреса) —
 * не ошибка: отдаём режим по умолчанию, чтобы дорога в бой не обрывалась.
 * @param {string|null|undefined} id
 * @returns {ArenaMode}
 */
export function getMode(id) {
  return ARENA_MODES.find((m) => m.id === id)
    || ARENA_MODES.find((m) => m.id === DEFAULT_MODE_ID);
}

/**
 * Сколько бойцов просит режим. Единственный способ узнать размер состава —
 * второго числа в проекте нет.
 * @param {string|null|undefined} id
 * @returns {number}
 */
export function squadSizeOf(id) {
  return getMode(id).squadSize;
}

/**
 * Из каких размеров состава игрок выбирает в этом режиме. Пустой список —
 * выбора нет, размер задан режимом.
 * @returns {number[]}
 */
export function sizesOf(id) {
  return getMode(id).sizes || [];
}

/**
 * Привести размер к тому, что этот режим допускает. Незнакомое число (старый
 * сейф, правка адреса) — не ошибка: отдаём размер режима по умолчанию.
 */
export function clampSize(id, n) {
  const allowed = sizesOf(id);
  if (!allowed.length) return squadSizeOf(id);
  return allowed.includes(n) ? n : squadSizeOf(id);
}

/**
 * Какой размер состава предложить игроку ПЕРВЫМ, когда он входит в режим и
 * своего выбора ещё не делал.
 *
 * Решение живёт здесь, а не в воротах: оно про режим, и в воротах превратилось
 * бы в проверку по имени режима прямо в разметке — то есть в место, о котором
 * таблица не знает. Ростер приходит числом снаружи, потому что про список
 * бойцов таблица режимов знать не должна.
 *
 * ПОЧЕМУ У КОМАНДЫ ОСОБОЕ ПРАВИЛО. Тройка интереснее двойки, и если игроку есть
 * кого поставить — предлагаем её. Остальным режимам это не подходит: у турнира
 * так же «побольше» означало бы сразу QUAD, а его сетка длиннее и это уже не
 * предложение, а решение за игрока.
 *
 * @param {string|null|undefined} id
 * @param {number} rosterCount сколько бойцов у игрока
 * @returns {number}
 */
export function defaultSizeFor(id, rosterCount) {
  const m = getMode(id);
  if (!sizesOf(m.id).length) return m.squadSize;
  if (m.id === 'squad') return rosterCount >= 3 ? 3 : 2;
  return m.squadSize;
}
