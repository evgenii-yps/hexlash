// ⚠️ ЧИСЛА СТАРТОВЫЕ (ТЗ: «ставим стартовые и оставляем»). Крутить их — отдельная
//    работа по ощущению, на арене и глазами. НИГДЕ БОЛЬШЕ ЧИСЕЛ КЛИЧА НЕТ — ни в
//    бойце, ни в сцене, ни в панели: если число понадобилось второй раз, его
//    берут отсюда, а не переписывают рядом. Две записи одного числа расходятся
//    молча — на этом уже обжигались (см. шапку data/buffBalance.js).
//
// ЧЕМ КЛИЧ ОТЛИЧАЕТСЯ ОТ БАФФА, И ПОЧЕМУ ЭТО ДВА РАЗНЫХ ФАЙЛА.
//   Бафф двигает то, НАСКОЛЬКО боец силён: здоровье, скорость хода, множитель
//   урона. Клич двигает то, КАК он дерётся: держит дистанцию или идёт вперёд,
//   цепляется или отпускает. Они не должны дублировать друг друга ни по эффекту,
//   ни по виду — поэтому и числа врозь.
//
// ⚠️ КЛИЧ НЕ ТРОГАЕТ СИЛУ. Ни урона, ни здоровья, ни скорости удара здесь нет и
//    быть не может: всё, что он умеет, — четыре оси манеры. Появилось желание
//    добавить сюда множитель урона — это бафф, а не клич.
//
// Экспортирует: KLICH_IDS, KLICH_META, KLICH_BALANCE.

/** Порядок кличей — он же порядок карточек в ряду. */
export const KLICH_IDS = ['push', 'fallback', 'hold'];

/**
 * Имя и однобуквенная метка. Как у баффов: имена собственные, английскими
 * буквами — проект только на английском.
 *
 * ⚠️ КЛИЧИ РАЗЛИЧАЮТСЯ ЗНАЧКОМ, А НЕ ЦВЕТОМ (ТЗ). Поэтому у каждого свой
 *    рисунок стрелки (`glyph`), и ни у одного нет своего цвета: цвет на арене
 *    уже занят — розовый держит интерфейс, цвета ядер держат бойцов.
 */
/**
 * `does` — что рычаг делает, одной английской строкой.
 *
 * ⚠️ ЭТО НЕ ПОДПИСЬ ДЛЯ ЭКРАНА, а объяснение для думающего мозга легенды
 *    (COMMAND часть B): ему надо выбрать рычаг, и по одному имени «HOLD» он
 *    выбирал бы наугад. Живёт здесь, рядом с самим рычагом, а не в правилах
 *    командования: второй список однажды разошёлся бы с первым, и легенда
 *    начала бы выбирать по описанию, которого рычаг уже не выполняет.
 *    Пересказывает сдвиг осей ниже — держать в согласии с ним.
 */
export const KLICH_META = {
  push:     { id: 'push',     name: 'PUSH',     mono: 'P', glyph: 'forward',
              does: 'drives him forward into the exchange, no backing off' },
  fallback: { id: 'fallback', name: 'FALL BACK', mono: 'F', glyph: 'back',
              does: 'breaks contact, buys him room and time' },
  hold:     { id: 'hold',     name: 'HOLD',     mono: 'H', glyph: 'anchor',
              does: 'digs him in, guard up, rides out the series' },
};

/**
 * СКОЛЬКО ДЕРЖИТСЯ. ТЗ: «около восьми секунд и плавно сходит на нет». Восемь
 * разложены на две части: полную силу боец несёт `holdSec`, потом сдвиг линейно
 * тает за `fadeSec`. Резкий обрыв читался бы как поломка — боец на кадре менял
 * бы манеру, — а плавный сход совпадает с манерой движения всего проекта
 * («плавно и тяжело»).
 */
export const KLICH_BALANCE = {
  holdSec: 6,
  fadeSec: 2,

  /**
   * ЗАРЯДЫ. Три применения на каждый клич за бой, по каждому отдельно. Это
   * запас, а не перезарядка по времени: кончился — кончился до конца боя.
   */
  chargesPerKlich: 3,

  /**
   * ОТКАТ — сколько секунд рычаг не нажимается после применения.
   *
   * ⚠️ ЭТО НЕ ПЕРЕЗАРЯДКА ЗАПАСА. Потраченный заряд не возвращается никогда;
   *    откат только не даёт выпалить все три подряд. Кончился откат — рычаг
   *    снова нажимается, если заряды ещё остались.
   *
   * ⚠️ ОТКАТ ОБЩИЙ НА СТОРОНУ ИГРОКА, как и заряды, — не на бойца. Крикнул
   *    «ВПЕРЁД» одному — «ВПЕРЁД» в откате у всех, остальные два клича
   *    свободны: у каждого рычага свой откат, независимо от соседей.
   *
   * ⚠️ ЧИСЛО ЧЕРНОВОЕ, И ЭТО НАМЕРЕННО. Настоящее считается в балансном проходе
   *    после демо. Шесть секунд выбраны так, чтобы откат кончался РАНЬШЕ, чем
   *    сойдёт сам клич (holdSec + fadeSec = 8): игрок успевает перебить свой же
   *    сдвиг, и замена клича заменой остаётся — второй не складывается с первым.
   */
  cooldownSec: 6,

  /**
   * СДВИГИ ОСЕЙ. Четыре оси из восьми — те, что реально ведут тело:
   *   distance   — ниже = ближе держится, выше = дальше
   *   initiative — выше = чаще идёт в размен
   *   tempo      — выше = чаще бьёт
   *   stick      — выше = цепляется за врага, ниже = отпускает
   *
   * ⚠️ МАСШТАБ ВЫБРАН ВРОВЕНЬ С НАМЕРЕНИЯМИ (data/intentions.js: их дельты ходят
   *    от 10 до 45). Меньше — клич не читался бы за секунду-две, как требует ТЗ;
   *    заметно больше — он затирал бы характер бойца, и все трое дрались бы
   *    одинаково. Клич ЛОЖИТСЯ ПОВЕРХ намерения, а не вместо него: боец остаётся
   *    собой, но заметно кренится в названную сторону.
   *
   * ⚠️ ОСИ КЛАМПЯТСЯ 0–100 УЖЕ В БОЙЦЕ. Поэтому один и тот же клич на разных
   *    ядрах работает по-разному: тому, кто и так жмётся вплотную, «вперёд» даст
   *    меньше, чем осторожному. Это не баг, это та же механика, что у граней.
   */
  /**
   * ПРИКАЗ ВНУТРИ ГРУППЫ (TZ_klich_v2). Сдвиг осей ниже двигает тело, но до выбора намерения из
   * него доходила одна дистанция (docs/reflex-sight/REPORT.md §4), а наклон очков к группе
   * клича перевешивали резонанс ветки и теги кристаллов у собранных бойцов
   * (docs/klich-reach/REPORT_weights.md). Поэтому, пока клич на ПОЛНОЙ силе (весь `holdSec`),
   * выбор намерения по очкам идёт только среди намерений его группы; очки внутри группы —
   * обычные: оси, теги, резонанс, накал, удержание, поэтому одно и то же «ВПЕРЁД» разные бойцы
   * исполняют по-разному. Как только начался `fadeSec`, ограничение снимается; сдвиг осей и
   * дальности тает как раньше. Жёсткие нужды (выдох при пустом запасе сил, удар полным зарядом)
   * стоят выше очков и не затрагиваются; в ответе на замах выбор идёт из пересечения
   * {CATCH, BREAK, HOLD} с группой (пустое — у PUSH — значит ответ как без клича).
   *
   * ⚠️ НОВЫХ ЧИСЕЛ НЕТ: здесь только состав групп. Веса наклона (0.45 / 0.75 / 0.3) отменены.
   *
   * ⚠️ Состав групп — id намерений строками (как в branchThreshold.js): файл не ввозит
   *    intentions.js, которому самому нужны эти данные.
   */
  groups: {
    push:     ['press', 'strike'],
    fallback: ['break', 'sting', 'breathe'],
    hold:     ['hold', 'catch'],
  },

  axes: {
    // ВПЕРЁД — идёт вперёд, чаще размен, меньше разрывов дистанции.
    push:     { distance: -70, initiative: 35, tempo: 10, stick: 25 },
    // ОТХОД — рвёт дистанцию, уходит от прессинга, реже атакует.
    fallback: { distance: 90, initiative: -30, tempo: -10, stick: -35 },
    // ДЕРЖАТЬ — упирается, держит оборону, терпит серию.
    hold:     { distance: -5, initiative: -25, tempo: -20, stick: 40 },
  },
};
