/* ────────────────────────────────────────────────────────────────────────────
   Сбой вывески — ОДНА таблица на два потребителя.

   Мерцание придумано для заголовка лендинга и живёт там с 05.09.2026. С
   13.09.2026 тот же сбой несёт объёмная вывеска HEXLASH в коридоре между домом
   и плитами режимов (src/scene/transitionFlight.js). Характер обязан совпадать:
   это один и тот же бренд мигает одинаково в плоскости и в объёме.

   ⚠️ Поэтому чисел здесь ровно один набор. Раньше они стояли в `@keyframes
   lpk-glowflick` внутри landing.css; скопировать их во вторую точку значило бы
   развести два мерцания при первой же правке — ровно так когда-то разъехались
   знак в игре и иконка вкладки. Теперь таблица одна, а CSS-кадры лендинга из
   неё ВЫВОДЯТСЯ (`flickerKeyframesCss`), а не пишутся руками.

   Что описывает таблица. Один цикл 13 с содержит ДВА события в неровных местах:
   паузы между ними получаются ~5 с и ~8 с, при этом петля остаётся одна. В
   каждом событии два толчка, между их началами 179 мс (норма — не чаще трёх раз
   в секунду). Дно провала 0.4 — свет не уходит в ноль, слово читается в любой
   момент. Переключение резкое, без плавного перехода, как у плохого контакта:
   в CSS это `steps(1)`, здесь — «держим значение последнего пройденного кадра».
   Кадры 0% и 100% совпадают: при выключенных анимациях слой замирает в покое.
   ──────────────────────────────────────────────────────────────────────────── */

/** Длина одного цикла, секунды. */
export const FLICKER_PERIOD = 13;

/**
 * Кадры: [доля цикла в процентах, множитель яркости].
 * Отсортированы по возрастанию — обход в `flickerAt` на это опирается.
 * Самый низкий множитель здесь и есть дно провала.
 */
export const FLICKER_FRAMES = [
  [0, 1],
  [3.84, 1],
  [3.85, 0.4],
  [4.62, 1],
  [5.23, 0.55],
  [5.85, 1],
  [42.29, 1],
  [42.3, 0.45],
  [43.07, 1],
  [43.68, 0.62],
  [44.3, 1],
  [100, 1],
];

/** Дно: ниже этого множитель не опускается никогда. */
export const FLICKER_FLOOR = FLICKER_FRAMES.reduce((m, f) => Math.min(m, f[1]), 1);

/**
 * Множитель яркости в момент `t` (секунды, любой непрерывный счётчик сцены).
 *
 * Семантика `steps(1)` буквально: держим значение последнего пройденного кадра
 * и щёлкаем на следующий. Никакого сглаживания — сглаженный провал читается
 * дыханием, а не сбоем контакта.
 *
 * @param {number} t секунды
 * @returns {number} множитель в диапазоне [FLICKER_FLOOR, 1]
 */
export function flickerAt(t) {
  const pct = ((t % FLICKER_PERIOD) / FLICKER_PERIOD) * 100;
  let v = FLICKER_FRAMES[0][1];
  for (let i = 0; i < FLICKER_FRAMES.length; i++) {
    if (FLICKER_FRAMES[i][0] > pct) break;
    v = FLICKER_FRAMES[i][1];
  }
  return v;
}

/**
 * Те же кадры в виде правила `@keyframes` — для лендинга, который анимирует
 * прозрачность слоя ореола средствами браузера.
 *
 * Заводить петлю и гасить её по «уменьшить движение» продолжает CSS: у лендинга
 * своё правило `prefers-reduced-motion`, и ему там и место. Отсюда приезжают
 * ТОЛЬКО кадры.
 */
export function flickerKeyframesCss(name = 'lpk-glowflick') {
  const body = FLICKER_FRAMES
    .map(([pct, v]) => `  ${pct}% { opacity: ${v}; }`)
    .join('\n');
  return `@keyframes ${name} {\n${body}\n}`;
}

/**
 * Положить эти кадры в документ. Идемпотентно: второй вызов ничего не делает.
 *
 * Если по какой-то причине вызова не случилось, имя анимации в CSS не
 * разрешится и слой ореола просто останется в покое (прозрачность 1) — то же
 * самое, что видит игрок с включённым «уменьшить движение». Поломкой это не
 * читается.
 */
export function installFlickerKeyframes(name = 'lpk-glowflick') {
  if (typeof document === 'undefined') return;
  const id = `flicker-${name}`;
  if (document.getElementById(id)) return;
  const el = document.createElement('style');
  el.id = id;
  el.textContent = flickerKeyframesCss(name);
  document.head.appendChild(el);
}
