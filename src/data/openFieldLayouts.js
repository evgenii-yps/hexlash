// openFieldLayouts.js — ТРИ РАСКЛАДКИ ОТКРЫТОГО ПОЛЯ. Одна механика, меняется
// только то, на сколько сторон нарезаны двадцать тел.
//
// ЧТО ТАКОЕ ОТКРЫТОЕ ПОЛЕ. Двадцать бойцов выходят на одну большую плиту разом.
// Стороны дерутся все против всех, остаётся одна. Сетки нет, волн нет, пар нет:
// один бой от начала до конца.
//
// ПОЧЕМУ ИМЕНА ТЕ ЖЕ, ЧТО У ТУРНИРА. SOLO / DUO / QUAD означают здесь ровно то
// же, что там, — сколько бойцов в стороне, — и игроку незачем учить второй
// словарь под то же самое. Но ТАБЛИЦА СВОЯ, и это не лень: числа сторон здесь
// другие (20 / 10 / 5 против 16 / 8 / 4), и одолжить чужую таблицу значило бы
// связать два режима так, что правка одного молча поехала бы в другой.
//
// ЧИСЛО ТЕЛ НЕ ХРАНИТСЯ, А СЧИТАЕТСЯ. Тел ровно `sides × perSide`, и во всех трёх
// раскладках это двадцать. Записать двадцатку рядом значило бы завести второе
// место, где живёт одно и то же, — и первое, которое разойдётся с таблицей.
//
// МЕСТО ТОЖЕ СЧИТАЕТСЯ, А НЕ ЛЕЖИТ ТАБЛИЦЕЙ. Сторона игрока выбыла — её место
// равно числу сторон, ЖИВЫХ в этот момент, плюс один: все живые окажутся выше
// неё, все прочие уже ниже. Это же правило даёт первое место победителю (живых
// сторон, кроме него, ноль... плюс он сам — см. placeOnElimination).
//
// ГДЕ ЧИСЛА. Размер поля, радиус внимания и пороги часов — в блоке `openField`
// файла чисел боя: все числа боя живут в одном файле, второго места для них в
// проекте нет. Здесь только структура — сколько сторон и как они встают.
//
// Экспортирует: OPEN_FIELD_NAME, OPEN_FIELD_LAYOUTS, OF_LAYOUT_IDS,
//               DEFAULT_OF_LAYOUT_ID, getOfLayout, parseOfLayoutId,
//               ofLayoutByPerSide, ofLayoutNameByPerSide,
//               ofBodyCount, ofSpawnPos, placeOnElimination.

import { COMBAT_BALANCE } from '@/data/combatBalance.js';

/**
 * ИМЯ РЕЖИМА НА ЭКРАНЕ — ОДНА СТРОКА В ОДНОМ МЕСТЕ.
 *
 * Рабочее, окончательное утвердит владелец. Менять здесь и только здесь: ключ
 * режима (`openfield`) — внутренний, он в адресе и в коде, и переименование
 * подписи его не трогает.
 *
 * ⚠️ ТАБЛИЦА РЕЖИМОВ БЕРЁТ ИМЯ ОТСЮДА. 20.09.2026 у открытого поля появился свой
 *    остров в воротах, и `data/arenaModes.js` импортирует эту строку, а не
 *    переписывает её к себе. Два места, где живёт одно имя, разошлись бы на
 *    первой же правке — а имя ещё будет меняться (оно рабочее).
 */
export const OPEN_FIELD_NAME = 'HUNT';

/**
 * @typedef {object} OpenFieldLayout
 * @property {string} id      ключ; он же значение служебного признака ?openfield=
 * @property {string} name    подпись
 * @property {number} sides   сколько сторон выходит на поле
 * @property {number} perSide сколько бойцов в стороне
 */

/**
 * Все три дают двадцать тел — это и есть постоянная режима. Меняется, на сколько
 * сторон эти двадцать нарезаны, то есть насколько одиноко бойцу игрока.
 * @type {OpenFieldLayout[]}
 */
export const OPEN_FIELD_LAYOUTS = [
  { id: 'solo', name: 'SOLO', sides: 20, perSide: 1 },
  { id: 'duo',  name: 'DUO',  sides: 10, perSide: 2 },
  { id: 'quad', name: 'QUAD', sides: 5,  perSide: 4 },
];

export const OF_LAYOUT_IDS = OPEN_FIELD_LAYOUTS.map((l) => l.id);
export const DEFAULT_OF_LAYOUT_ID = 'solo';

/**
 * Раскладка по ключу. Незнакомый ключ — не ошибка: отдаём раскладку по
 * умолчанию, чтобы дорога в бой не обрывалась (то же правило, что у режимов и у
 * раскладок турнира).
 */
export function getOfLayout(id) {
  return OPEN_FIELD_LAYOUTS.find((l) => l.id === id)
    || OPEN_FIELD_LAYOUTS.find((l) => l.id === DEFAULT_OF_LAYOUT_ID);
}

/**
 * Прочитать значение служебного признака `?openfield=`. Пусто или незнакомое —
 * SOLO, как написано в ТЗ.
 * @returns {string|null} ключ раскладки или null, если признака нет вовсе
 */
export function parseOfLayoutId(raw) {
  if (raw === undefined || raw === null || raw === '') return null;
  const v = String(raw).toLowerCase();
  return OF_LAYOUT_IDS.includes(v) ? v : DEFAULT_OF_LAYOUT_ID;
}

/**
 * Раскладка по РАЗМЕРУ СТОРОНЫ. Переключатель в воротах выбирает число бойцов —
 * 1, 2 или 4, — и это число и есть `perSide`. Второго списка соответствий нет:
 * он разошёлся бы с таблицей выше при первой же правке.
 * @param {number} n сколько бойцов в стороне
 */
export function ofLayoutByPerSide(n) {
  return OPEN_FIELD_LAYOUTS.find((l) => l.perSide === n)
    || OPEN_FIELD_LAYOUTS.find((l) => l.id === DEFAULT_OF_LAYOUT_ID);
}

/** Подпись раскладки по размеру стороны — её показывает переключатель в воротах. */
export function ofLayoutNameByPerSide(n) {
  return ofLayoutByPerSide(n).name;
}

/** Сколько тел на поле в этой раскладке. Считается, не хранится — см. шапку. */
export function ofBodyCount(id) {
  const L = getOfLayout(id);
  return L.sides * L.perSide;
}

/**
 * ТОЧКИ ВЫХОДА. Стороны равномерно по кольцу у края поля, бойцы стороны — рядом,
 * по дуге того же кольца.
 *
 * ПОЧЕМУ КОЛЬЦО, А НЕ ШЕРЕНГИ. На двадцать сторон шеренга невозможна в принципе:
 * их негде поставить друг напротив друга — врагов не двое, а девятнадцать.
 * Кольцо — единственная расстановка, при которой все стороны равноправны: ни у
 * кого нет спины к краю и ни у кого нет двух соседей вместо одного.
 *
 * ПОЧЕМУ БОЙЦЫ СТОРОНЫ — ПО ДУГЕ, А НЕ КУЧЕЙ. Они должны стоять рядом (это одна
 * команда, и игрок должен видеть свою как группу), но не в точке: выйди они в
 * одно место, и первый же кадр начался бы с расталкивания тел.
 *
 * ⚠️ СОСЕДНИЕ СТОРОНЫ ОБЯЗАНЫ БЫТЬ ВНЕ ДОСЯГАЕМОСТИ. Это не украшение: стороны,
 *    начинающие бой в упоре, дерутся не «все против всех», а парами у края, и
 *    весь смысл поля пропадает. Условие держится радиусом кольца — см.
 *    `spawnRingRadius` ниже и проверку `sidesFitOnRing`.
 *
 * @param {object} L      раскладка (getOfLayout)
 * @param {number} R      радиус кольца в мировых единицах
 * @param {number} sIdx   номер стороны
 * @param {number} k      номер бойца внутри стороны
 * @returns {{x:number, z:number}}
 */
export function ofSpawnPos(L, R, sIdx, k) {
  const base = (sIdx / L.sides) * Math.PI * 2;
  // Шаг между соседями по стороне — угол, который на этом радиусе даёт рабочий
  // разлёт `spawnGap`. Тот же способ, что у общей расстановки арены: просвет
  // задан в мировых единицах, а превращается в угол по радиусу.
  const step = L.perSide > 1 ? COMBAT_BALANCE.field.spawnGap / Math.max(R, 0.001) : 0;
  const a = base + (k - (L.perSide - 1) / 2) * step;
  return { x: Math.cos(a) * R, z: Math.sin(a) * R };
}

/**
 * Радиус кольца выхода — и, через него, размер поля.
 *
 * Считается от САМОЙ ТЕСНОЙ раскладки (двадцать сторон в SOLO), а не от текущей:
 * поле у всех трёх раскладок одно, и если мерить его по QUAD, то SOLO на нём не
 * поместится. Между серединами соседних сторон должно оставаться
 * `openField.sideGap`; у сторон шире одного бойца к этому добавляется дуга самой
 * стороны, иначе крайние бойцы соседних сторон сойдутся вплотную.
 *
 * @param {object} L раскладка
 * @returns {number} радиус в мировых единицах
 */
export function spawnRingRadius(L) {
  const OF = COMBAT_BALANCE.openField;
  // Дуга, которую занимает сама сторона, в мировых единицах.
  const sideSpan = (L.perSide - 1) * COMBAT_BALANCE.field.spawnGap;
  // Длина кольца = (просвет между сторонами + ширина стороны) × число сторон.
  return ((OF.sideGap + sideSpan) * L.sides) / (Math.PI * 2);
}

/**
 * Влезают ли стороны на кольцо, не входя друг другу в досягаемость. Служебная
 * проверка для замера: если она когда-нибудь скажет «нет», значит числа поля
 * разошлись с числом сторон, и бой начнётся в упоре.
 * @returns {boolean}
 */
export function sidesFitOnRing(L) {
  const R = spawnRingRadius(L);
  const between = (Math.PI * 2 * R) / L.sides - (L.perSide - 1) * COMBAT_BALANCE.field.spawnGap;
  return between >= COMBAT_BALANCE.openField.sideGap - 1e-6;
}

/**
 * МЕСТО СТОРОНЫ, которая только что выбыла (или победила).
 *
 * `livingSides` — сколько сторон ОСТАЛОСЬ живыми в этот момент, уже без неё.
 * Все они окажутся выше, значит её место — следующее за ними. Победителю живых,
 * кроме него, ноль, и правило само даёт первое место.
 *
 * ОДНОВРЕМЕННОЕ ВЫБЫВАНИЕ. Если в одном кадре пали последние бойцы нескольких
 * сторон, живых у всех них окажется поровну — и место вышло бы одно на всех.
 * Разводит их порядок выбывания: кто пал ПОЗЖЕ, тот выше (ничьих в этой игре
 * нет). Считает это сцена, потому что порядок знает поле боя; здесь — только
 * само правило.
 *
 * @param {number} livingSides сколько сторон живо, не считая выбывшую
 * @returns {number} место, начиная с единицы
 */
export function placeOnElimination(livingSides) {
  return Math.max(1, livingSides + 1);
}
