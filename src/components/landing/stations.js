/* HEXLASH — МАРШРУТ ПОЛЁТА ПО ЛЕНДИНГУ (26.09.2026).

   Прокрутка лендинга ведёт камеру от станции к станции: она уходит то влево,
   то вправо и только в конце выходит в середину, к ядру. Здесь — весь маршрут
   и больше нигде. Камеру по этим числам считает MarketingView.vue, рисует
   landing.css.

   ⚠️ СТАНЦИИ СТОЯТ НА НАСТОЯЩИХ ВЕРШИНАХ КОЛЕЦ. Координаты не выписаны
   числами — они выводятся из VORTEX, того же описания, по которому кольца
   рисуются на экране. Выписать их сюда числами значило бы завести второе
   место, где живёт геометрия «Вихря»: подвинется кольцо — станция останется
   на старом месте, и камера будет наводиться в пустоту.

   ⚠️ Система координат — доли --core-r (половина стороны квадрата, в который
   вписано ядро), начало в середине фигуры, ось Y ВНИЗ, как на экране. */

import { VORTEX } from '@/data/coreFigure.js';

/** Вершина i кольца k в долях --core-r. Повторяет vortexRings один в один. */
export function ringVertex(k, i) {
  const r = VORTEX.first * Math.pow(VORTEX.scale, k);
  const rot = VORTEX.step * (k + 1);
  const a = ((-90 + 60 * i + rot) * Math.PI) / 180;
  return { x: r * Math.cos(a), y: r * Math.sin(a) };
}

/* Станции по порядку полёта. Пять штук — ровно столько же, сколько цветов в
   круге (coreCycle.js), по цвету на станцию.

     0 — общий план: камера стоит там же, где стоит фигура на первом экране,
         поэтому переход с первого экрана в полёт не заметен. Своего текста
         у станции нет.
     1 — влево-вверх
     2 — вправо-вниз
     3 — влево, ближе
     4 — середина: приход к ядру, полёт окончен.

   ⚠️ Удаление от середины ОБЯЗАНО убывать: 3.61 → 2.69 → 2.01 → 0. Это и есть
   «амплитуда ухода в сторону убывает к финалу» из задания. Меняя вершины,
   проверьте порядок — иначе маршрут в конце начнёт расходиться, а не сходиться.

   zoom — доля пути от «общего плана» (0) до предела приближения (1). Сам
   предел числом не задан: он считается от высоты окна, см. fitZoom. */

export const STATIONS = [
  { at: () => ({ x: 0, y: 0 }), zoom: 0,    block: null        },
  { at: () => ringVertex(3, 5), zoom: 0.25, block: 'manifesto' },
  { at: () => ringVertex(2, 2), zoom: 0.50, block: 'gameplay'  },
  { at: () => ringVertex(1, 4), zoom: 0.75, block: 'hex'       },
  { at: () => ({ x: 0, y: 0 }), zoom: 1,    block: 'roadmap'   },
];

/* Как прокрутка полёта делится между площадками и перегонами.

   Площадка — участок, где камера стоит и блок читается спокойно. Перегон —
   переезд на следующую станцию. Веса, а не доли: из них ниже собирается
   расписание, и оно само нормируется к единице — так не приходится сводить
   суммы руками при каждой правке.

   ⚠️ У СТАРТА ПЛОЩАДКИ НЕТ. Площадка нужна, чтобы читать блок, а у общего
   плана своего блока нет: пауза на нём — это несколько сотен точек прокрутки
   почти пустого экрана сразу после первого экрана. Поэтому ныряем сразу.

   ⚠️ Числа живут здесь, а не в стилях: камеру считает скрипт, и вес площадки
   ему нужен как число, а не как значение свойства. Длина полёта (сколько
   экранов прокрутки он занимает) — наоборот, в landing.css: это высота. */
export const DWELL_W = 1;
export const MOVE_W = 1.25;

/* Расписание полёта: чередование перегонов и площадок, нормированное к
   единице. Собирается один раз при загрузке. */
const SEGMENTS = (() => {
  const raw = [];
  for (let k = 0; k < STATIONS.length; k += 1) {
    if (k > 0) raw.push({ move: false, k, w: DWELL_W });
    if (k < STATIONS.length - 1) raw.push({ move: true, k, w: MOVE_W });
  }
  const total = raw.reduce((a, r) => a + r.w, 0);
  let acc = 0;
  return raw.map((r) => {
    const from = acc / total;
    acc += r.w;
    return { move: r.move, k: r.k, from, to: acc / total };
  });
})();

/* Запас от края экрана до контура фигуры в конце пути, в долях высоты окна.
   Из-за него фигура на последнем экране остаётся целой на любом окне, включая
   низкое: предел приближения считается от высоты, а не задан числом. */
export const FINAL_MARGIN = 0.04;

/**
 * Предел приближения: во сколько раз фигура вырастет к последней станции.
 * Радиус контура берётся из того же описания «Вихря», что и кольца.
 * @param {number} coreR  --core-r в точках, прочитанный у .cv
 * @param {number} vh     высота окна в точках
 */
export function fitZoom(coreR, vh, reserve = 0) {
  const contour = VORTEX.CONTOUR * coreR;
  if (!contour) return 1;
  return Math.max(1, (vh / 2 - vh * FINAL_MARGIN - reserve) / contour);
}

/* Общий план: во сколько раз фигура на старте МЕНЬШЕ своего обычного размера.

   ⚠️ Это и есть «старт — общий план» из задания, и он же делает читаемым рост
   текста. Блок на подлёте виден во столько раз мельче, во сколько камера ещё
   не доехала; если старт равен обычному размеру, весь размах приближения на
   компьютере — всего 2.2 раза на четыре перегона, по 1.2 за перегон, и текст
   не «вырастает», а просто въезжает сбоку почти готовым. С общим планом размах
   становится 3.7 раза, по 1.4 за перегон — рост видно.
   ⚠️ Побочное следствие: на первом экране фигура фона меньше, чем была. Это
   осознанно: первый экран и есть общий план. */
export const WIDE = 0.6;

/**
 * Приближение на доле пути frac (0 — общий план, 1 — предел).
 * Ход равномерный по ощущению: за каждый перегон камера приближается во
 * столько же раз, а не на столько же точек. Поэтому степень, а не прямая.
 */
export function zoomAt(frac, fit) {
  return WIDE * Math.pow(Math.max(fit, WIDE) / WIDE, frac);
}

/* Сглаживание перегона: скорость на входе и на выходе ровно ноль, поэтому нет
   рывка ни при разгоне, ни при торможении. */
export const ease = (t) => t * t * (3 - 2 * t);

/* Доля перегона, за которую камера ДОЕЗЖАЕТ до станции. Дальше она стоит на
   месте и только доприближается.

   ⚠️ Это не украшение, а главное, что делает текст читаемым на подлёте. Если
   ехать и приближаться одновременно, блок всю дорогу виден сбоку и обрезан
   краем экрана, а «вырастает» он всего в 1.2 раза — то есть въезжает почти
   готовым. Разведя движение и приближение, мы половину перегона смотрим на
   блок по центру, и он растёт на глазах. */
export const POS_LEAD = 0.45;

/**
 * Где камера при заданной доле прокрутки полёта.
 * @param {number} u 0 — начало полёта, 1 — приход в середину
 * @returns {{ i, j, tr, tp, tz, dw }} откуда, куда, сырая доля перегона (для
 *          прозрачности), доля для ПОЛОЖЕНИЯ, доля для ПРИБЛИЖЕНИЯ и доля
 *          пройденной площадки (для прохода по высокому блоку).
 */
export function legAt(u) {
  const x = Math.min(1, Math.max(0, u));
  let seg = SEGMENTS[SEGMENTS.length - 1];
  for (let n = 0; n < SEGMENTS.length; n += 1) {
    if (x <= SEGMENTS[n].to) { seg = SEGMENTS[n]; break; }
  }
  const local = (x - seg.from) / Math.max(1e-6, seg.to - seg.from);
  if (!seg.move) {
    return { i: seg.k, j: Math.min(seg.k + 1, STATIONS.length - 1), tr: 0, tp: 0, tz: 0, dw: local };
  }
  const tr = Math.min(1, Math.max(0, local));
  return {
    i: seg.k,
    j: seg.k + 1,
    tr,
    tp: ease(Math.min(1, tr / POS_LEAD)),
    tz: ease(tr),
    dw: 1,
  };
}

/** Доля прокрутки, на которой камера стоит на станции k (середина площадки). */
export function stationU(k) {
  const seg = SEGMENTS.find((sg) => !sg.move && sg.k === k);
  if (!seg) return 0; // у старта площадки нет
  return (seg.from + seg.to) / 2;
}
