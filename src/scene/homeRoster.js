// при неизменном стартовом ракурсе и неизменной плите: в портрете 390×844 десять
// бродящих тел в кадр не входят (целиком встаёт не больше 7–8 при расстоянии 1,3 м
// между центрами), а ракурс, плиту и наложение тел владелец запретил трогать.
// Кто не попал в шестёрку — НЕ СТРОИТСЯ вовсе: ни «спрятанным в кадре», ни «на
// всякий случай».
//
// ═══ КТО ПОПАДАЕТ В ШЕСТЁРКУ — порядок устойчивый, не случайный ═══
//   1. бойцы в TRAINING (по порядку ростера);
//   2. выбранный боец;
//   3. остальные по порядку ростера.
//
// ⚠️ СОСТАВ ПЕРЕСЧИТЫВАЕТСЯ ТОЛЬКО В МОМЕНТ НАЧАЛА ИЛИ КОНЦА ЗАНЯТИЯ (и один раз — при
//    сборке сцены). Вызывает эту функцию сцена, а сцена зовёт её лишь когда изменился
//    набор занятых. Ни поворот камеры, ни смена раскладки, ни таймер сюда не ведут.
//
// ⚠️ МЕСТО ЗА БОЙЦОМ ЗАКРЕПЛЕНО, пока он в шестёрке. Пересчёт состава не пересаживает
//    остающихся: тело, которое осталось, остаётся там, где стояло, а освободившееся
//    место отдаётся новичку. Иначе любое начало занятия у одного гоняло бы по плите
//    чужих бойцов.

import { stateOf } from '@/services/training.js';

// ───────────────────────────── CONFIG ─────────────────────────────

/** Сколько тел показывает главный остров. Одно число на все раскладки. */
export const HOME_CEILING = 6;

/**
 * ЧТО ПОКАЗЫВАЕТ ПОДПИСЬ «ГОТОВ».
 *   true  — три слова: FREE / TRAINING / READY (как в ТЗ v2). Готовый стоит смирно.
 *   false — два слова: закончивший занятие считается FREE и бродит как свободный.
 * Одна строка — решение владельца по п.3 можно переключить здесь и больше нигде.
 */
export const SHOW_READY = true;

/**
 * МЕСТА. Подобраны замером по сетке проекций реальной камеры на СТАРТОВОМ ракурсе, а
 * не на глаз: шесть зон, целиком видимых в кадре во всех четырёх раскладках (844×390,
 * 1280×720, 1920×1080 и портрет 390×844), с просветом между зонами не меньше 0.85 м —
 * то есть тела на краях зон не налезают друг на друга в мире — и так, чтобы тело не
 * заходило под кнопки экрана (бренд, SHOP/кабинет, EDIT SPACE, FIGHT) ни в одной из
 * раскладок. Ограничивает портрет: он видит около ±1.3 м ширины плиты.
 *
 * Поле у каждой — `x, z` центр, `hx, hz` полуразмеры ПЯТНА БЛУЖДАНИЯ, `bag` — где
 * висит груша этого места, пока боец занимается.
 *
 * ⚠️ ПЯТНА МАЛЕНЬКИЕ (0.2–0.5 м), И ЭТО ЦЕНА ПОТОЛКА В ШЕСТЬ ТЕЛ. Свободный боец не
 *    гуляет по плите, а переминается и разминается в своём пятне. Шире пятно — тело на
 *    краю вылезет за кадр или придвинется к соседу. Замер и числа — в отчёте.
 *
 * ⚠️ ГРУША — СБОКУ ОТ БОЙЦА (0.8 м), а не за спиной и не впереди: на этом ракурсе
 *    «за спиной» прячет грушу за самим телом, а «впереди» уводит её на соседа.
 *    Сторона выбрана перебором по тем же условиям: груша целиком в кадре и не ближе
 *    0.65 м к чужому пятну.
 *
 * ⚠️ Двигать места можно только вместе с перемером кадра на 390×844.
 */
export const HOME_SLOTS = [
  // Порядок — порядок заполнения: первыми (занятые, выбранный) встают передние места.
  { x: -0.35, z: 1.55,  hx: 0.10, hz: 0.10, bag: { x: 0.45,  z: 1.55 } },
  { x: -1.65, z: 0.85,  hx: 0.15, hz: 0.10, bag: { x: -0.85, z: 0.85 } },
  { x: 0.80,  z: 0.85,  hx: 0.10, hz: 0.10, bag: { x: 0.00,  z: 0.85 } },
  { x: -0.30, z: -0.85, hx: 0.10, hz: 0.10, bag: { x: -1.10, z: -0.85 } },
  { x: -1.45, z: -1.55, hx: 0.10, hz: 0.10, bag: { x: -0.65, z: -1.55 } },
  { x: -2.50, z: -1.20, hx: 0.10, hz: 0.45, bag: { x: -1.93, z: -0.63 } },
];

// ───────────────────────────── состояния ─────────────────────────────

/**
 * Состояние бойца так, как его показывает ГЛАВНЫЙ ОСТРОВ: 'free' | 'busy' | 'ready'.
 * При SHOW_READY=false готовый считается свободным.
 */
export function homeState(f) {
  const st = stateOf(f);
  return (!SHOW_READY && st === 'ready') ? 'free' : st;
}

// ───────────────────────────── состав ─────────────────────────────

/**
 * Кто встаёт на остров.
 *
 * @param {Array<{id:string, state:string}>} fighters  весь ростер, в порядке ростера
 * @param {string|null} pickedId  выбранный боец
 * @returns {string[]} id не больше HOME_CEILING штук в порядке приоритета
 */
export function chooseHomeSix(fighters, pickedId) {
  const list = fighters || [];
  const busy = list.filter((f) => f.state === 'busy');
  const picked = list.find((f) => f.id === pickedId && f.state !== 'busy') || null;
  const rest = list.filter((f) => f.state !== 'busy' && f !== picked);
  return [...busy, ...(picked ? [picked] : []), ...rest].slice(0, HOME_CEILING).map((f) => f.id);
}

/**
 * Раздать места. Остающиеся сохраняют своё место, новички занимают освободившиеся
 * в порядке приоритета.
 *
 * @param {string[]} chosen   результат chooseHomeSix
 * @param {(string|null)[]} prev  прежняя раздача: prev[slot] = id или null
 * @returns {(string|null)[]} новая раздача той же длины HOME_CEILING
 */
export function assignSlots(chosen, prev = []) {
  const next = new Array(HOME_SLOTS.length).fill(null);
  const left = new Set(chosen);
  for (let s = 0; s < next.length; s++) {
    const id = prev[s];
    if (id && left.has(id)) { next[s] = id; left.delete(id); }
  }
  const queue = chosen.filter((id) => left.has(id));
  for (let s = 0; s < next.length && queue.length; s++) {
    if (!next[s]) next[s] = queue.shift();
  }
  return next;
}
