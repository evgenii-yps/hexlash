// Задник зала — тёмный купол вокруг сцены, один на все залы.
//
// Раньше это был один и тот же код, скопированный в три файла (HomeScene,
// PveScene, SpaceScene) и уже разошедшийся: у Дома купол умел смещаться по Z и
// возвращал mesh с центром коридора, у Арены и Космоса — нет; у Дома и Кузницы
// тянулись за собой ещё два помощника, которые НИЧЕГО НЕ РИСОВАЛИ.
//
// ── 12.09.2026 · КУПОЛ СТАЛ РОВНЫМ ЧЁРНЫМ ──────────────────────────────────
// До этой правки купол был вертикальным градиентом, нарисованным на холсте
// 1024×1024 и натянутым на сферу. Замеры на отрисованных кадрах (зал FORGE,
// 1280×720) показали, что градиент приносил ТРИ дефекта сразу, и все три
// владелец увидел на проде:
//
//   1. ТЁПЛЫЙ ФОН. Средний стоп #120F0C и нижний полюс #1B150D давали в нижних
//      двух третях кадра пиксели с R−B = +6…+8 — то есть рыжину. Она лежала
//      широкой полосой за плитой и в зале, и на доме.
//   2. «РЕШЁТКА». Растянутый на сферу радиусом 45–72 градиент квантуется в
//      8 бит, и полосы Маха ложатся дугами по широтам купола. Плюс Skia сама
//      дизерит градиент на холсте регулярной точечной сеткой — на сфере она
//      увеличивается в десятки раз. Вместе это и читалось как регулярная сетка
//      «за плитой». Проверено контрастным растягиванием кадра: обе структуры
//      видны отчётливо.
//   3. ШОВ С ТУМАНОМ. Туман всех залов — FOG_COLOR (= --void). Купол же на
//      линии горизонта был уже тёплым. Правило «тон тумана = тон купола на
//      дальней границе» (Документ А 3.3) выполнялось только у верхнего полюса.
//
// Решение владельца 12.09: за пределами плиты — ровное нейтральное чёрное
// пространство, без рисунка, без зерна, без тёплого оттенка. Тёплый свет игры
// остаётся ЛОКАЛЬНЫМ: конусы ламп, подсвет под бойцом, сама плита. Поэтому
// градиента больше нет — купол залит одним цветом --void, и правило про шов
// выполняется теперь не «на дальней границе», а на любой высоте взгляда,
// потому что цвет один и тот же.
//
// Заодно исчезло то, что градиент за собой тянул: холст 1024×1024, текстура,
// мип-уровни и анизотропия на каждый зал. Купол — одна сфера с одним цветом.
//
// Что было удалено раньше и не возвращается:
//   • drawHexWeave + strokeHex — шестиугольная сетка на куполе. Оба зала держали
//     hexMaxAlpha: 0, то есть альфа каждого штриха выходила нулевой и цикл всегда
//     срывался на `continue`.
//   • dither — зерно против полос в градиенте. Оба зала держали dither: 0.
// Если сетка или зерно понадобятся — они возвращаются сюда, в одно место, и
// описываются в Документе А, а не заводятся заново в каждом зале.
import * as THREE from 'three';
import { BACKDROP } from '@/data/sceneTokens.js';

/**
 * Строит купол.
 *
 * ⚠️ Цвет НЕ параметр: купол один на все залы и красится одним значением из
 * src/data/sceneTokens.js. Второй цвет здесь — это второе объявление, ровно то,
 * из-за чего купол и разъехался с токенами до 12.09 (в токенах нижний полюс уже
 * был --void, а в коде оставался тёплым #1B150D, и читался код).
 *
 * @param {{radius:number, centerY:number, centerZ?:number|null}} o геометрия зала
 * @returns {{mesh: THREE.Mesh, dispose: () => void}}
 */
export function buildBackdrop(o) {
  const geo = new THREE.SphereGeometry(o.radius, 48, 32);
  const mat = new THREE.MeshBasicMaterial({
    color: BACKDROP.color, side: THREE.BackSide, fog: false, depthWrite: false,
  });
  const mesh = new THREE.Mesh(geo, mat);
  mesh.position.set(0, o.centerY, o.centerZ ?? 0);
  mesh.renderOrder = -10; // рисуется первым, за всем остальным

  const dispose = () => { geo.dispose(); mat.dispose(); };
  return { mesh, dispose };
}
