// boutRandom.js — СВОЙ ИСТОЧНИК СЛУЧАЙНОСТИ ДЛЯ БОЯ.
//
// ЗАЧЕМ. Раньше боец (buildFighter), поле боя (battleField) и обход преград
// (coverNav) брали числа из общего Math.random — того же, что берут дым легенды,
// пыль, текстуры и всё остальное, что рисуется. Любая правка вида арены (лишняя
// частица, другой кадр) тихо сдвигала ход боя в игре, а регрессии боя считают бой
// без сцены и этого не видели.
//
// ТЕПЕРЬ. У каждого участника боя — свой генератор. Он заводится ОДИН раз: берёт
// зерно из Math.random в момент создания и дальше с общим потоком не связан.
//   · в игре зерно случайное → бои, как и раньше, каждый раз разные;
//   · в замерах Math.random зажимается зерном, значит зерно участника тоже
//     повторяется → бой повторяется шаг в шаг, а картинка на него не влияет.
//
// ⚠️ БОЕВАЯ СЛУЧАЙНОСТЬ БЕРЁТСЯ ТОЛЬКО ОТСЮДА. Math.random внутри buildFighter /
//    battleField / coverNav — ошибка: scripts/bout-random-isolation.mjs её поймает.
//    Картинке (частицы, текстуры, туман) по-прежнему можно брать Math.random.
//
// Экспортирует: createRng, freshSeed.

/** Новое зерно из общего потока. Зовётся один раз на участника боя. */
export function freshSeed() {
  return (Math.random() * 4294967296) >>> 0;
}

/**
 * Генератор mulberry32 — тот же, что зажимает зерно в замерах. Отвечает числом
 * [0, 1), как Math.random.
 * @param {number} [seed] без аргумента — зерно из общего потока
 * @returns {() => number}
 */
export function createRng(seed = freshSeed()) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
