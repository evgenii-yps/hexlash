  //
  // ⚠️ ЧИСЛО ЗАМЕРЕНО, А НЕ ВЫБРАНО. Угол подъёма камеры над кнопкой в позе
  // покоя (линейка `__gateProbe().cam`, четыре кадра ТЗ, три и четыре бойца):
