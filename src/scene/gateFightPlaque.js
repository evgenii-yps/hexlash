const WORD = 'FIGHT';
// ⚠️ НАБОР УЖЕ, ЧЕМ У ВЫВЕСКИ, И ПРОСВЕТ МЕНЬШЕ (0.075 против 0.085). Это
// вторая половина той же правки, что подняла высоту таблички: ширину слова
// держат поля, и пока слово было широким, высота прописной упиралась в ширину
// раньше, чем в высоту. Набранное FIGHT занимало 2.90 ширины прописной, теперь
// 2.63 — на 9 % у́же, и высоту наконец решает высота.
//
// Узость тут не вольность, а фирменная черта: Saira CONDENSED. Толщина штриха
// при этом НЕ ТРОНУТА (те же 0.19), то есть буквы стали плотнее, а не тоньше —
// именно это и нужно мелкому кадру.
const TRACK = 0.075;

/** Ширина набранного слова в единицах высоты прописной. */
function wordEmWidth() {
  let x = 0;
  for (const ch of WORD) x += GLYPHS[ch].w + TRACK;
  return x - TRACK;
}

// ──────────────────────── Форма таблички и букв ────────────────────────

/** Прямоугольник со срезанными углами, вокруг (0,0). Тот же приём, что у плиты. */
function plaquePoints(halfW, halfH, chamfer) {
  const c = Math.min(chamfer, halfW * 0.6, halfH * 0.6);
  return [
    [-halfW + c, -halfH], [halfW - c, -halfH], [halfW, -halfH + c],
    [halfW, halfH - c], [halfW - c, halfH], [-halfW + c, halfH],
    [-halfW, halfH - c], [-halfW, -halfH + c],
  ];
}

function pathOf(pts, Path = THREE.Path) {
  const p = new Path();
  p.moveTo(pts[0][0], pts[0][1]);
  for (let i = 1; i < pts.length; i++) p.lineTo(pts[i][0], pts[i][1]);
  p.closePath();
  return p;
}

/**
 * Точки всех пяти букв, уже поставленные на своё место в кадре таблички.
 * @returns {{letters: number[][][], em: number, wordW: number}}
 */
function layoutWord(halfW, halfH) {
  const emW = wordEmWidth();
  // Высота прописной: сколько разрешает высота таблички — и ужимаем, только
  // если слово не влезает по ширине. Ужимать ниже порога читаемости нельзя, и
  // здесь этого не происходит: поля рассчитаны так, что ширина не побеждает.
  const em = Math.min(PLAQUE.capOfHeight * halfH * 2, (halfW * 2 * (1 - 2 * PLAQUE.padOfWidth)) / emW);
  const wordW = emW * em;
  let x = -wordW / 2;
  const baseY = -em / 2;   // полоса прописных стоит по центру таблички
  const letters = [];
  for (const ch of WORD) {
    const g = GLYPHS[ch];
    letters.push(g.out.map(([gx, gy]) => [x + gx * em, baseY + gy * em]));
    x += (g.w + TRACK) * em;
  }
  return { letters, em, wordW };
}

/**
 * ЦЕЛОСТЬ ТАБЛИЧКИ — проверка, а не украшение.
 *
 * Отвечает на вопрос ТЗ: «дают ли контуры букв ЦЕЛУЮ табличку». Сломать её
 * можно ровно двумя способами, и проверяются оба:
 *
 *   1. ЗАМКНУТЫЙ ОСТРОВОК. Пустота, которую контур буквы обносит полностью
 *      (перемычка внутри G, O, A), — это кусок таблички, который не держится
 *      ни на чём и должен был бы выпасть. В трафаретном наборе такой пустоты
 *      нет ни у одной буквы: у G камера открыта в горло. Островок мог бы
 *      появиться только вторым контуром (`holes`) — его и ищем.
 *   2. САМОПЕРЕСЕЧЕНИЕ. Контур, пересекающий сам себя, триангулируется во
 *      что попало: табличка рвётся, а на глаз это видно не на всяком ракурсе.
 *      Перебираем пары несоседних отрезков — букв пять, отрезков у самой
 *      длинной девятнадцать, считать тут нечего.
 *
 * Зовётся линейкой приёмки (`__gateProbe().fight.integrity`), поэтому живёт
 * рядом с буквами, а не в тесте: проверять надо ТУ таблицу, которая собирается.
 *
 * @returns {{ok: boolean, islands: string[], crossings: string[]}}
 */
export function plaqueIntegrity() {
  const islands = [];
  const crossings = [];

  // Пересекаются ли отрезки ab и cd (без касаний по общим концам).
  const side = (ax, ay, bx, by, cx, cy) => Math.sign((bx - ax) * (cy - ay) - (by - ay) * (cx - ax));
  const crosses = (a, b, c, d) => {
    const d1 = side(a[0], a[1], b[0], b[1], c[0], c[1]);
    const d2 = side(a[0], a[1], b[0], b[1], d[0], d[1]);
    const d3 = side(c[0], c[1], d[0], d[1], a[0], a[1]);
    const d4 = side(c[0], c[1], d[0], d[1], b[0], b[1]);
    return d1 !== d2 && d3 !== d4 && d1 !== 0 && d2 !== 0 && d3 !== 0 && d4 !== 0;
  };

  for (const ch of WORD) {
    const g = GLYPHS[ch];
    if (g.holes && g.holes.length) islands.push(ch);
    const pts = g.out;
    const n = pts.length;
    for (let i = 0; i < n; i++) {
      for (let j = i + 2; j < n; j++) {
        if (i === 0 && j === n - 1) continue;          // соседи через замыкание
        if (crosses(pts[i], pts[(i + 1) % n], pts[j], pts[(j + 1) % n])) {
          crossings.push(`${ch}:${i}×${j}`);
        }
      }
    }
  }
  return { ok: islands.length === 0 && crossings.length === 0, islands, crossings };
}

// ───────────────────────────── Сборка ─────────────────────────────

/**
 * Табличка FIGHT, стоящая на плите кнопки.
 *
 * Собирается в собственном кадре: лицо в плоскости XY, толщина по +Z, начало
 * координат — центр лица. Наклон и подъём на плиту делает группа, поэтому
 * числа внутри остаются читаемыми долями, а не смесью долей с поворотами.
 *
 * @param {object} p
 * @param {number} p.plateHalfW половина ширины плиты — от неё выведены все размеры
 * @param {number} p.topY       крышка плиты в её собственном кадре
 * @param {string} p.glowColor   розовый кнопки — свой цвет табличка не заводит
 * @returns {object} { group, top, halfW, halfH, setLit, dispose, cost }
 */
export function buildFightPlaque({ plateHalfW, topY, glowColor }) {
  const o = PLAQUE;
  const plateW = plateHalfW * 2;
  const halfW = (plateW * o.widthOfPlate) / 2;
  const halfH = (plateW * o.heightOfPlate) / 2;
  const th = plateW * o.depthOfPlate;

  // ── лицо с прорезями ──
  const outline = plaquePoints(halfW, halfH, halfH * 2 * o.chamferOfHeight);
  const shape = pathOf(outline, THREE.Shape);
  const { letters, em, wordW } = layoutWord(halfW, halfH);
  for (const pts of letters) shape.holes.push(pathOf(pts));

  const bodyGeo = new THREE.ExtrudeGeometry(shape, {
    depth: th, bevelEnabled: false, steps: 1, curveSegments: 1,
  });
  bodyGeo.translate(0, 0, -th / 2);   // толщина вокруг лица, а не от него

  const bodyMat = new THREE.MeshStandardMaterial({
    color: o.body, flatShading: true, roughness: o.roughness, metalness: o.metalness,
  });

  const group = new THREE.Group();
  group.add(new THREE.Mesh(bodyGeo, bodyMat));

  // ── глухая подложка ──
  // ОДНА деталь делает две работы, и это не экономия ради экономии — это то,
  // что удерживает табличку в трёх вызовах отрисовки из ТЗ.
  //
  //   1. ЗАКРЫВАЕТ ДНО ПРОРЕЗЕЙ. Без неё сквозь буквы видно НАСКВОЗЬ: плиту
  //      под кнопкой, её шестигранную крышку, комнату. Слово тогда — не свет в
  //      прорези, а дырка, за которой случайный узор. Так и вышло в первой
  //      сборке.
  //   2. ЗАКРЫВАЕТ СПИНУ. Сзади сквозь прорези свет выходить не должен, иначе
  //      кнопка светит в пустую комнату за собой.
  //
  // Поэтому подложка стоит У САМОЙ ЗАДНЕЙ ГРАНИ и двусторонняя: с лица её
  // видно в прорезях, со спины — вместо них.
  const inset = halfH * o.innerInset;
  const innerPts = plaquePoints(halfW - inset, halfH - inset, (halfH - inset) * 2 * o.chamferOfHeight);
  const backGeo = new THREE.ShapeGeometry(pathOf(innerPts, THREE.Shape));
  backGeo.translate(0, 0, -th / 2 + 0.002);
  group.add(new THREE.Mesh(backGeo, new THREE.MeshStandardMaterial({
    color: o.body, flatShading: true, roughness: o.roughness, metalness: o.metalness,
    side: THREE.DoubleSide,
  })));

  // ── свет за прорезями ──
  // Числа яркости сюда НЕ ЗАШИТЫ: их приносит кнопка теми же значениями, что
  // были у снятого диска (coreDim / coreArmed). Поведение «тускло — горит»
  // обязано остаться прежним, менялась картинка, а не отклик.
  //
  // Панель — ПО СЛОВУ, а не по всей табличке. Светить за глухой частью лица
  // нечему: свет оттуда всё равно никуда не выходит, а закраска прозрачного
  // аддитивного прямоугольника во всё лицо — это работа впустую на каждом
  // кадре. Замерено на телефонном кадре с четырьмя бойцами: панель во всё лицо
  // стоила 2 кадра в секунду, панель по слову — ни одного.
  const bleed = em * o.glowBleed;
  const glowGeo = new THREE.PlaneGeometry(wordW + bleed * 2, em + bleed * 2);
  glowGeo.translate(0, 0, -th / 2 + th * o.glowSink);
  const glowMat = new THREE.MeshBasicMaterial({
    color: new THREE.Color(glowColor), transparent: true, opacity: 0,
    blending: THREE.AdditiveBlending, depthWrite: false,
  });
  group.add(new THREE.Mesh(glowGeo, glowMat));

  // ── постановка на плиту ──
  // Поворот вокруг X на минус наклон кладёт лицо навстречу камере покоя и
  // уводит верх таблички назад. Подъём считаем от НИЖНЕЙ КРОМКИ: она и есть то,
  // чем табличка стоит на крышке.
  const a = THREE.MathUtils.degToRad(o.tiltDeg);
  group.rotation.x = -a;
  group.position.set(0, topY + halfH * Math.cos(a), 0);

  // Верх таблички в кадре кнопки — по нему кнопка растит коробку нажатия и
  // целится подлёт. Считаем, а не берём на глаз: наклон меняет высоту.
  const top = group.position.y + halfH * Math.cos(a);

  const setLit = (opacity) => { glowMat.opacity = opacity; };

  /**
   * ТОЧКИ ДЛЯ ЛИНЕЙКИ ПРИЁМКИ, в собственном кадре таблички.
   *
   * Приёмка обязана ответить, сколько ПИКСЕЛЕЙ занимает высота прописной и
   * толщина штриха на каждом кадре, — а не «выглядит ли читаемо». Померить это
   * снаружи нельзя: табличка откинута, и экранная высота её коробки к высоте
   * буквы отношения не имеет. Поэтому точки отдаёт она сама, а считает
   * расстояние между ними уже линейка, спроецировав их камерой.
   *
   * Все точки берутся В ПЛОСКОСТИ ЛИЦА (z = толщина/2), то есть там, где буква
   * и видна.
   */
  const metrics = () => {
    const z = th / 2;
    return {
      capTop: new THREE.Vector3(0, em / 2, z),
      capBottom: new THREE.Vector3(0, -em / 2, z),
      // Штрих меряем по горизонтали в середине лица — там, где стоит стойка I.
      strokeA: new THREE.Vector3(-S * em / 2, 0, z),
      strokeB: new THREE.Vector3(S * em / 2, 0, z),
      // Кромки ЛИЦА. Экранной коробкой ширину таблички мерить нельзя: коробка
      // строится по осям мира, а табличка откинута, и её коробка вылезает
      // вперёд на высоту наклона. На подлёте это давало 91 % ширины кадра там,
      // где лицо занимало 63 %.
      faceL: new THREE.Vector3(-halfW, 0, z),
      faceR: new THREE.Vector3(halfW, 0, z),
    };
  };

  const dispose = () => {
    bodyGeo.dispose(); backGeo.dispose(); glowGeo.dispose();
    bodyMat.dispose(); glowMat.dispose();
    group.traverse((m) => { if (m.isMesh && m.material !== bodyMat && m.material !== glowMat) m.material.dispose(); });
  };

  return {
    group, top, halfW, halfH, capHeight: em, thickness: th, tilt: a,
    setLit, metrics, dispose,
  };
}
