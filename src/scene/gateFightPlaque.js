  // скользящем ракурсе, и слово читается формой, а не подсветкой.
  glowSink: 0.22,
  // Насколько ПОДЛОЖКА уже самой таблички — доля её ПОЛУВЫСОТЫ. Она обязана
  // быть чуть меньше лица, иначе её кромка вылезает за срезанные углы и висит
