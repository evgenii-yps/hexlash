// ascensionRite.js — ЗОЛОТОЕ СЕРДЦЕ ЛЕГЕНДЫ. Один вывод цвета на весь проект.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Золотое сердце показывается в ДВУХ местах — в обряде
// (AscensionScene, момент превращения) и в зале FORGE (легенда, которая парит
// над плитой навсегда). Два независимых вывода одного цвета разошлись бы при
// первой же правке — ровно так когда-то разъехались вторые тона ядер. Поэтому
// вывод здесь один, и оба места зовут его.
//
// ⚠️ НОВОГО ЦВЕТА ЗДЕСЬ НЕ ОБЪЯВЛЕНО НИ ОДНОГО. Золото — это янтарь HEXARCH
//    (AMBER из sceneTokens.js), уже объявленный и уже служивший сердцем
//    парящей фигуры зала. Цвет ядра — coreHue(), то есть одно объявление в
//    tokens.css. Всё, что делает этот файл, — СМЕШИВАЕТ два объявленных цвета,
//    как coreSup() смешивает ядро с чернилами.
//
// ⚠️ И СОБСТВЕННОЕ СВЕЧЕНИЕ ЯДРА У ЛЕГЕНДЫ ПРИГЛУШЕНО (ТЗ §3.4). Причина —
//    правило «одно свечение на элемент»: оставь и золото, и полный ореол ядра,
//    и на груди окажутся два источника света, спорящие друг с другом. Золото
//    обязано читаться единственным источником света на фигуре.
import * as THREE from 'three';
import { AMBER, coreHue } from '../data/sceneTokens.js';

// ── НАСТРОЙКИ ОБРЯДА. Все ручки в одном месте ──────────────────────────────
export const RITE = {
  // Доля цвета ядра в золоте. Подобрана на глаз: у ONSLAUGHT золото теплеет в
  // красное, у BULWARK уходит в бирюзу, но золотом остаётся. Выше — и легенда
  // перестаёт читаться золотой; ниже — и все четыре ядра дают одно и то же
  // золото, то есть подмес не виден вовсе.
  coreTint: 0.22,
  // Насколько приглушено собственное свечение ядра. Не ноль: сердце должно
  // гореть, а не быть крашеным камнем. См. шапку — почему не полная яркость.
  glowLevel: 0.55,

  // ── ВРЕМЯ ОБРЯДА. Весь обряд от подтверждения до возврата — не длиннее
  //    шести секунд (ТЗ §3.3). Сумма ниже ≈ 3.9 с, запас взят намеренно:
  //    возврат в зал идёт под общим экраном загрузки, и его длина от нас не
  //    зависит.
  spinMs: 2400,     // разгон и остановка вращения — рывок, а не карусель
  turns: 5,         // столько полных оборотов за это время
  goldMs: 520,      // сердце наливается золотом после остановки
  holdMs: 900,      // короткая пауза перед возвратом в зал
};

/**
 * Цвет сердца легенды: золото с подмесом её ядра.
 * @param {string|null} coreId — ядро исходного бойца ('natisk' | 'nalet' | …)
 * @returns {string} шестнадцатеричная строка, готовая для buildFighter
 */
export function legendHue(coreId) {
  const gold = new THREE.Color(AMBER);
  if (!coreId) return `#${gold.getHexString()}`;
  // lerp, а не своя формула: смешение цветов в проекте делается одним способом.
  gold.lerp(new THREE.Color(coreHue(coreId)), RITE.coreTint);
  return `#${gold.getHexString()}`;
}

/**
 * Ручка к сердцу построенного бойца — снаружи, без правки buildFighter.
 *
 * Тот же приём, что уже применён в зале (PveScene.coreParts) и при гашении
 * плашки здоровья: сканируем прямых детей торса и берём то, что нашли. Ядро —
 * единственный восьмигранник под торсом, ореол — единственный спрайт там же.
 *
 * ⚠️ ЗОЛОТО НАКЛАДЫВАЕТСЯ, А НЕ ПЕРЕСОБИРАЕТСЯ. Пересборка тела ради смены
 *    цвета сердца дала бы мгновенную подмену фигуры вместо превращения, и
 *    «уменьшить движение» осталось бы вовсе без плавного перехода, которого
 *    оно требует. Поэтому цвет наливается долей: и камень, и ореол.
 *
 * ⚠️ ОРЕОЛ КРАСИТСЯ УМНОЖЕНИЕМ, и это не хитрость. Его рисунок испечён при
 *    сборке: середина почти белая, край несёт цвет ядра. Умножение на золото
 *    даёт золотое свечение, у которого в спаде остаётся ядро — ровно то
 *    «золото с подмесом цвета ядра», которого просит обряд.
 *
 * Вернувшийся `apply(mix)` зовётся КАЖДЫЙ КАДР, СРАЗУ ПОСЛЕ fighter.update():
 * тело переписывает цвет и яркость сердца само, каждый кадр заново, поэтому
 * накладывать надо поверх. Камень ЗАДАЁТСЯ от запомненной основы (домножение
 * копилось бы кадр за кадром и погасило бы его совсем), а живая яркость ореола
 * домножается — её основа дышит, и запомненное число эту жизнь бы остановило.
 *
 * @param {object} fighter — тело из buildFighter
 * @param {string} goldHex — цвет золота для ЭТОГО ядра (см. legendHue)
 * @returns {{apply:(mix:number)=>void}|null} null — сердца не нашлось
 */
export function heartHandle(fighter, goldHex) {
  const torso = fighter && fighter.joints && fighter.joints.torso;
  if (!torso) return null;
  let gem = null, halo = null;
  for (const o of torso.children) {
    if (!halo && o.isSprite) halo = o;
    else if (!gem && o.isMesh && o.geometry && o.geometry.type === 'OctahedronGeometry') gem = o;
  }
  if (!gem && !halo) return null;

  const gold = new THREE.Color(goldHex || AMBER);
  const gemBase = gem ? gem.material.color.clone() : null;
  const haloBase = halo ? halo.material.color.clone() : null;
  const _c = new THREE.Color();

  return {
    /** mix: 0 — сердце как у бойца · 1 — золото легенды. */
    apply(mix) {
      const m = mix < 0 ? 0 : mix > 1 ? 1 : mix;
      // Свечение гаснет ровно настолько, насколько наливается золото: к концу
      // обряда на фигуре остаётся один источник света, и это золото.
      const level = 1 + (RITE.glowLevel - 1) * m;
      if (gem && gemBase) {
        gem.material.color.copy(gemBase).lerp(gold, m).multiplyScalar(level);
      }
      if (halo && haloBase) {
        halo.material.color.copy(_c.copy(haloBase).lerp(gold, m));
        halo.material.opacity *= level;
      }
    },
  };
}
