// fieldShrink.js — СУЖЕНИЕ ОТКРЫТОГО ПОЛЯ. Круг поверх поля, радиус которого со
// временем уменьшается, и правило «тело не остаётся снаружи».
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Двадцать тел на большой плите доигрывают до одной
// стороны, но долго: последние выжившие оказываются так далеко друг от друга, что
// идут навстречу дольше, чем длится сам размен. Сужение подрезает именно этот
// хвост — оно сводит уцелевших, а не торопит бой.
//
// ⚠️ ГРАНИЦА ВЫТАЛКИВАЕТ, А НЕ РАНИТ. В этом файле нет ни одной строки про урон,
//    и расчёт урона в игре этой правкой не тронут. Тело снаружи получает сдвиг к
//    середине — ровно такой, чтобы вернуться НА границу, и ни на волос больше.
//
// ГДЕ ШОВ. Ровно тот же, что у выталкивания из укрытий: позицию тела пишет не
// только его навигация, и поправить её можно СНАРУЖИ, после того как боец
// отработал кадр. Защищённый файл бойца при этом не вскрывается.
//
//    ⚠️ Менять бойцу границы поля (navBounds) на ходу БЕСПОЛЕЗНО: он снимает их
//       в свои переменные при рождении и больше не перечитывает. Поэтому
//       сужение — второй, независимый контур поверх прежних границ, а не их
//       правка. Прямоугольные границы плиты остаются как были.
//
// СЕРЕДИНА КРУГА — СЕРЕДИНА ПОЛЯ. За короной круг не ходит: игрок должен заранее
// видеть, куда сходится поле, а лидер по ходу матча меняется, и круг дёргался бы
// вслед за сменой.
//
// ЧИСЕЛ ЗДЕСЬ НЕТ. Все до единого живут в блоке `openField.shrink` файла чисел
// боя; здесь только правило, как из них складывается граница.
//
// Экспортирует: createFieldShrink.

import { COMBAT_BALANCE } from '@/data/combatBalance.js';

/**
 * @param {object} o
 * @param {number} o.startRadius радиус, с которого граница трогается с места.
 *        Это кольцо выхода сторон: до него поле не сужается вовсе, а вне его
 *        лежит только запас до кромки плиты.
 * @param {object[]} [o.covers] раскладка укрытий — те, что оказались за
 *        границей, уходят в пол. Не передана — укрытий у поля нет.
 */
export function createFieldShrink({ startRadius, covers = [] }) {
  const S = COMBAT_BALANCE.openField.shrink;
  // Конечный радиус не может быть больше начального: в маленькой раскладке поле
  // и так меньше, и «сужение» вверх было бы расширением.
  const finalRadius = Math.min(S.finalRadius, startRadius);
  const beginSec = S.startSec;
  const endSec = S.startSec + S.durationSec;
  const warnSec = S.startSec - S.warnSec;

  // СОСТОЯНИЕ КАЖДОГО УКРЫТИЯ. Номер места в исходной раскладке — так и сцене, и
  // обходу называется ОДИН И ТОТ ЖЕ блок, без второго списка, который разошёлся бы.
  //
  // Состояний три, и среднее из них — главное в этом куске файла:
  //   стоит      · doneAt = 0
  //   САДИТСЯ    · doneAt > времени: блок уже осуждён и уже опускается, НО ЕЩЁ
  //                ТОРЧИТ ИЗ ПОЛА — и потому ПО-ПРЕЖНЕМУ МЕШАЕТ
  //   ушёл       · doneAt <= времени
  //
  // ⚠️ САДЯЩИЙСЯ БЛОК ОБЯЗАН МЕШАТЬ, и это правило, а не заплатка. Что видно
  //    глазу, то и не пускает: блок выталкивает тела и занимает клетки обхода
  //    ровно столько, сколько он выше пола, — ни кадром меньше.
  //
  //    Сначала он переставал мешать в тот же миг, когда его осудили. Прижатый к
  //    нему боец оказывался свободен раньше, чем блок скрылся, и полсекунды мог
  //    идти сквозь то, что ещё видно; обход в те же полсекунды считал дорогу
  //    свободной и сам туда вёл.
  //
  //    ⚠️ ЧЕСТНО: ЗАМЕР ЭТОГО НЕ ЛОВИЛ. Двадцать четыре матча (двенадцать так и
  //       двенадцать этак) дали по нулю кадров захода в обоих случаях — блоки
  //       уходят у КРОМКИ, а тела в этот момент тянет к середине, прочь от них.
  //       Правка оставлена не по замеру, а потому что она верна сама по себе и
  //       стоит ноль: разъехаться «что видно» и «что не пускает» не должны.
  const doneAt = covers.map(() => 0);
  let nowSec = 0;
  // Состав мешающих блоков изменился с прошлого опроса — обходу пора перепечь
  // сетку. Отдельный признак, а не сравнение списков: списки пришлось бы собирать
  // каждый кадр ради ответа «нет».
  let navDirty = false;
  // ДОКУДА БЛОК ДОСТАЁТ ОТ СЕРЕДИНЫ ПОЛЯ. Блок уходит, когда перестал помещаться
  // ЦЕЛИКОМ, а не когда граница прошла его середину (см. причину в блоке чисел).
  //
  // ⚠️ К РАЗМЕРУ БЛОКА ПРИБАВЛЕН РАДИУС ТЕЛА, И ЭТО НЕ ЗАПАС «НА ВСЯКИЙ СЛУЧАЙ».
  //    Тело не точка: от блока оно держится на своём радиусе, и выталкивание из
  //    укрытий считает блок раздутым ровно на него. Меряй блок без этой прибавки
  //    — и тело, севшее НА границу, оказывалось бы внутри раздутого блока,
  //    который ещё стоит. Дальше два правила тянули бы его в разные стороны:
  //    укрытие наружу, граница внутрь. Замер это и показал: без прибавки
  //    четырнадцать кадров на три матча тело стояло ВНУТРИ СТОЯЩЕГО блока, с
  //    прибавкой — ноль на шестидесяти матчах.
  const pad = COMBAT_BALANCE.openField.cover.bodyRadius;
  const reach = covers.map((c) => Math.hypot(c.x, c.z) + Math.hypot(c.hl + pad, c.ht + pad));

  /** Радиус границы на секунде `t`. До начала — начальный, после — конечный. */
  const radius = (t) => {
    if (t <= beginSec) return startRadius;
    if (t >= endSec) return finalRadius;
    const k = (t - beginSec) / S.durationSec;
    return startRadius + (finalRadius - startRadius) * k;
  };

  /** Видна ли граница игроку. Появляется вместе с обратным отсчётом. */
  const shown = (t) => t >= warnSec;

  /**
   * Обратный отсчёт до начала сужения: целые секунды от warnSec до 1. Вне этого
   * окна — null, и строки на экране нет вовсе.
   */
  const closingIn = (t) => {
    if (t < warnSec || t >= beginSec) return null;
    return Math.max(1, Math.ceil(beginSec - t));
  };

  /**
   * ШАГ ГРАНИЦЫ — ОДИН ВЫЗОВ НА КАДР. Зовётся после того, как отработали и боец,
   * и расталкивание тел, и выталкивание из укрытий: все трое пишут позицию, и
   * правило границы обязано быть последним.
   *
   * ⚠️ ДО НАЧАЛА СУЖЕНИЯ ЗДЕСЬ НЕ ПРОИСХОДИТ НИЧЕГО. Ни сдвига тел, ни ухода
   *    блоков. Это не мелочь: поле не круглое, а квадратное, и его углы лежат
   *    ДАЛЬШЕ кольца выхода — считай границу с первой секунды, и матч начинался
   *    бы уже суженным. В маленьких раскладках было хуже: раскладка укрытий
   *    считается от кольца SOLO (так она заведена до этой работы), и в DUO с QUAD
   *    все сорок блоков оказались бы «за границей» в первом же кадре и утонули бы
   *    на старте. Замер это и поймал: тринадцать кадров с телом внутри блока в
   *    DUO против нуля без сужения.
   *
   * @param {object[]} list живые тела (у каждого `f.group.position`)
   * @param {number} t секунда боя
   * @returns {{radius:number, sink:number[]}} радиус границы и номера блоков,
   *          которые ТОЛЬКО ЧТО отправились в пол
   */
  const step = (list, t) => {
    if (t < beginSec) return { radius: startRadius, sink: EMPTY };
    const R = radius(t);
    pushIn(list, R);
    return { radius: R, sink: retireCovers(R, t) };
  };

  /**
   * ВЕРНУТЬ ТЕЛА ВНУТРЬ — сам сдвиг. Наружу не отдаётся: зовёт его только шаг
   * выше, и звать его в обход шага значило бы двигать тела до 90-й секунды.
   *
   * Сдвиг РАДИАЛЬНЫЙ и минимальный: тело садится ровно на границу, а его боковое
   * движение сохраняется — значит оно скользит вдоль круга, а не упирается в
   * него намертво. Телепорта нет: граница идёт медленнее шага бойца в разы, и за
   * кадр поправка выходит в сотые доли единицы.
   *
   * @param {object[]} list живые тела (у каждого `f.group.position`)
   * @param {number} R радиус границы прямо сейчас
   * @returns {number} скольких пришлось двигать — для служебной строки и замера
   */
  const pushIn = (list, R) => {
    let n = 0;
    for (const u of list) {
      const p = u.f.group.position;
      const d = Math.hypot(p.x, p.z);
      if (d <= R || d < 1e-4) continue;
      const k = R / d;
      p.x *= k;
      p.z *= k;
      n += 1;
    }
    return n;
  };

  /**
   * УКРЫТИЯ ЗА ГРАНИЦЕЙ. Возвращает номера блоков, которые ТОЛЬКО ЧТО осуждены, —
   * по одному разу на блок. Пусто почти всегда: раскладка стоит кольцами, и
   * кольцо уходит целиком за один кадр.
   *
   * Осуждённый блок НАЧИНАЕТ ОПУСКАТЬСЯ, но мешать не перестаёт: пока он выше
   * пола, он и выталкивает тела, и занимает клетки обхода (см. `doneAt` выше).
   *
   * Кто с этими номерами что делает — дело зовущего: сцена опускает меши. Здесь
   * только правило «за границей».
   *
   * @param {number} R радиус границы прямо сейчас
   * @param {number} t секунда боя
   * @returns {number[]} номера блоков в исходной раскладке
   */
  const retireCovers = (R, t) => {
    // Тот, кто досел до конца в этом кадре, из мешающих выбывает — значит обходу
    // пора перепечь сетку.
    if (t < nowSec) navDirty = true;              // время пошло заново (новый бой)
    for (let i = 0; i < doneAt.length; i += 1) {
      if (doneAt[i] > nowSec && doneAt[i] <= t) navDirty = true;
    }
    nowSec = t;
    let gone = null;
    for (let i = 0; i < doneAt.length; i += 1) {
      if (doneAt[i] || reach[i] < R) continue;
      doneAt[i] = t + S.sinkSec;
      (gone || (gone = [])).push(i);
    }
    return gone || EMPTY;
  };

  /**
   * Менялся ли состав МЕШАЮЩИХ блоков с прошлого опроса. Опрос сбрасывает признак:
   * спрашивают его раз в кадр и ровно затем, чтобы перепечь сетку обхода.
   */
  const takeNavDirty = () => { const d = navDirty; navDirty = false; return d; };

  /**
   * Блоки, которые ещё МЕШАЮТ: стоящие и те, что садятся, но ещё выше пола. Этим
   * списком кормят обход, когда он пересчитывает сетку проходимости.
   */
  const liveCovers = () => covers.filter((_, i) => !doneAt[i] || doneAt[i] > nowSec);

  /**
   * НАЧАТЬ ЗАНОВО. Зовётся в начале каждого боя: «драться снова» выводит НОВОЕ
   * поле, и блоки, ушедшие в пол в прошлом матче, обязаны стоять. Сама граница
   * состояния не держит — она считается от времени боя, а оно и так с нуля.
   */
  const reset = () => { doneAt.fill(0); nowSec = 0; navDirty = true; };

  return {
    step, radius, shown, closingIn, takeNavDirty, liveCovers, reset,
    startRadius, finalRadius, beginSec, endSec, warnSec,
  };
}

/** Один общий пустой список: он возвращается почти каждый кадр. */
const EMPTY = [];
