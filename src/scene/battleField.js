// battleField.js — ПОЛЕ БОЯ. Кто сейчас на плите, кто кому враг, кто по кому бьёт
// и когда бой кончился.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. До фундамента бой держали две переменные в сцене арены —
// «мой боец» и «его боец», — и каждая ниточка между ними (где враг, сколько у
// него сил, что он сейчас делает) была написана дважды, зеркально. Пока бойцов
// двое, это короче любой абстракции; на троих такая запись не расширяется вообще
// — её пришлось бы написать девять раз. Здесь лежит ОДИН список и ОДНО правило
// выбора цели, а сцена только показывает то, что решено тут.
//
// ЧТО ЭТО НЕ ДЕЛАЕТ. Здесь нет ни Three.js, ни урона, ни намерений. Поле не знает,
// как боец дерётся, — только кто он, за кого он и жив ли. Расчёт урона остаётся
// внутри бойца и этой правкой не тронут: поле лишь отвечает на вопрос «кто мой
// враг прямо сейчас», а бьёт по нему боец сам, как бил всегда.
//
// СТОРОНА — ЭТО КОМАНДА, А НЕ ЧЕЛОВЕК. На одной стороне могут стоять бойцы игрока
// и боты-союзники (так устроен RAID). Поэтому признак «бот» лежит НА БОЙЦЕ, а не
// на стороне.
//
// СВОЁ ПРАВИЛО КОНЦА БОЯ. Общее правило — «жива ровно одна сторона» — подходит
// всем режимам, кроме рейда: там бой кончается падением ОДНОГО бойца (босса),
// даже если его сторона ещё на плите. Поэтому рядом с общим правилом есть шов
// `setEndRule`: режим может положить своё, и тогда спрашивают сначала его.
// Никто, кроме рейда, шва не ставит, и без него поле ведёт себя ровно как вело.
//
// Экспортирует: createBattleField.

import { COMBAT_BALANCE } from '@/data/combatBalance.js';

/** Ядра, у каждого своё правило выбора цели. Ключи — те же, что в upgradeData. */
const ONSLAUGHT = 'natisk';
const BULWARK = 'skala';
const AMBUSH = 'zasada';
// RAIDER ('nalet') отдельной веткой не нужен — он и есть запасной путь «наугад».

/**
 * @typedef {object} Unit
 * @property {object}  f       собранный боец (то, что вернул buildFighter)
 * @property {string}  sideId  за какую команду дерётся
 * @property {boolean} isBot   ведёт не игрок. Игроку не показывается — см. ТЗ
 * @property {string?} coreId  ядро: оно задаёт правило выбора цели
 */

/**
 * @param {object} [o]
 * @param {number|null} [o.attentionRadius] РАДИУС ВНИМАНИЯ — правило ОДНОГО режима.
 *   Задан числом (открытое поле) — боец применяет правило своего ядра только к
 *   врагам не дальше этого; никого в радиусе нет — идёт к ближайшему.
 *   Не задан (все пять прежних режимов и мгновенный бой) — выбор цели идёт РОВНО
 *   тем же путём, что и до этой правки: ни одной новой проверки на этом пути нет.
 * @param {object|null} [o.leader] ЛИДЕР — правило ОДНОГО режима, второе.
 *   Задан (открытое поле) — поле считает силу сторон, объявляет лидера и подменяет
 *   им «ближайшего врага» в выборе цели. Не задан — короны нет, `leaderSide()`
 *   всегда null, и выбор цели идёт прежним путём.
 *   Единственное поле внутри — `now`: часов у поля боя своих нет. Сцена отдаёт
 *   время своих часов, мгновенный бой — своё синтетическое; ровно так же устроены
 *   часы накала (boutCore.createBoutClocks).
 */
export function createBattleField({ attentionRadius = null, leader = null } = {}) {
  // Радиус живёт числом, а не признаком «режим такой-то»: поле боя про режимы не
  // знает и знать не должно. Ноль и отрицательное читаются как «радиуса нет» —
  // иначе опечатка в числе молча оставила бы бойцов без целей вовсе.
  const RADIUS = Number.isFinite(attentionRadius) && attentionRadius > 0 ? attentionRadius : null;
  const LEAD = leader && typeof leader.now === 'function' ? leader : null;
  const LC = COMBAT_BALANCE.openField.leader;
  /** @type {Unit[]} */
  let units = [];
  // Своё правило конца боя, если режим его поставил. Отвечает ключом победившей
  // стороны или null — «по своему правилу бой ещё идёт».
  let endRule = null;
  // Порядок выбывания. Нужен ровно для одного случая: если на поле не осталось
  // НИ ОДНОЙ живой стороны (последние бойцы погибли в одном кадре), победа
  // отдаётся той, чей боец выбыл ПОЗЖЕ. Ничья невозможна — так решено в ТЗ.
  let eliminatedOrder = 0;

  // Живым считается только СОБРАННЫЙ боец: тело появляется на кадр позже записи
  // в поле, и без проверки `u.f` первый же запрос цели пришёл бы к пустому месту.
  const alive = (u) => !!u && !!u.f && !u.dead;
  const living = () => units.filter(alive);

  /** Живые враги для бойца: все, кто жив и стоит за другую команду. */
  const enemiesOf = (u) => units.filter((o) => alive(o) && o.sideId !== u.sideId);

  const dist = (a, b) => {
    const pa = a.f.group.position;
    const pb = b.f.group.position;
    return Math.hypot(pa.x - pb.x, pa.z - pb.z);
  };

  // --- ВЫБОР ЦЕЛИ ------------------------------------------------------------
  // Правило ядра применяется ОДИН РАЗ — в момент, когда цели нет. Дальше цель
  // ДЕРЖИТСЯ ДО ВЫБЫВАНИЯ: боец не перескакивает на другого, пока текущий на
  // поле. Без этого правила ONSLAUGHT метался бы между врагами на каждом
  // попадании (самый слабый по здоровью меняется постоянно), и бой читался бы
  // как дёрганье, а не как охота.
  //
  // Исключение одно — ЗАСАДА: она и есть «поймать момент», поэтому переключается
  // на того, кто начал замах у неё под носом.
  const pickByCore = (u, foes) => {
    if (!foes.length) return null;
    switch (u.coreId) {
      case ONSLAUGHT:
        // Добивает: самый слабый по ОСТАВШЕМУСЯ здоровью.
        return foes.reduce((a, b) => (b.f.getHp() < a.f.getHp() ? b : a));
      case BULWARK:
        // Держит опасного: самый сильный по СИЛЕ УДАРА бойца. Не по нанесённому
        // урону — в начале боя он у всех ноль, и такое правило молча выродилось
        // бы в «первый попавшийся».
        return foes.reduce((a, b) => (strikePower(b) > strikePower(a) ? b : a));
      case AMBUSH:
        // Ближайший — пока никто не замахнулся (замах ловится в noteWindup).
        return foes.reduce((a, b) => (dist(u, b) < dist(u, a) ? b : a));
      default:
        // RAIDER и всё незнакомое — наугад.
        return foes[Math.floor(Math.random() * foes.length)];
    }
  };

  const strikePower = (u) => (u.f.stats && u.f.stats.strikePower) || 0;

  // --- ЛИДЕР -----------------------------------------------------------------
  //
  // МАГНИТ ПОЛЯ. Одна сторона объявляется лидером, и все остальные сходятся на
  // неё. Без магнита двадцать сторон дерутся двадцатью отдельными стычками по
  // краям плиты, и поле читается не как один бой, а как двадцать чужих.
  //
  // ⚠️ ЕДИНОЙ МЕРЫ СИЛЫ БОЙЦА В ИГРЕ НЕТ, И ЭТО ПРОВЕРЕНО. Функции вроде
  //    powerOf() не существует; сила бойца лежит вектором — восемь осей манеры,
  //    десяток долей в разные механики и боевой лист. Формула ниже — решение
  //    владельца 18.09.2026, а не находка в коде.
  //
  //    ЧИСЛАМИ ПРОКАЧКА ДВИГАЕТ РОВНО ДВЕ характеристики листа: силу удара и
  //    прочность. Остальные восемь ключей стоят на общей базе, граней в них не
  //    ведёт ни одна. Поэтому сила бойца — произведение двух ОТНОСИТЕЛЬНЫХ
  //    множителей: боец без граней даёт ровно 1.0, потолок ≈1.57.
  //
  //    ИЗВЕСТНАЯ СЛАБОСТЬ, ЗАПИСАННАЯ ВЛАДЕЛЬЦЕМ: числовой бонус несут 5 жёстких
  //    веток из 12, и боец, вложивший все грани в поведенческие ветки, читается
  //    здесь как сырой бот. Пересмотр — при переходе на прокачку искрами.
  //
  // Базы берутся из файла чисел боя, а не пишутся здесь: поменяется база — сила
  // поедет за ней, а не разойдётся с листом.
  const unitPower = (u) => {
    const s = u.f.stats;
    if (!s) return 1;
    const sp = (s.strikePower || 0) / COMBAT_BALANCE.strikePower;
    const th = (s.toughness || 0) / COMBAT_BALANCE.toughness;
    return sp * th;
  };

  // ЖРЕБИЙ НА РАВЕНСТВО. Стороны сравниваются по силе, и на первой короне силы
  // сплошь и рядом равны: у всех полное здоровье, а грани у большинства ничего не
  // двигают. Разбивать равенство номером стороны нельзя — сторона игрока в списке
  // ПЕРВАЯ, и корона систематически садилась бы на неё.
  //
  // ⚠️ ЖРЕБИЙ БРОСАЕТСЯ ОДИН РАЗ НА СТОРОНУ И ДЕРЖИТСЯ ВЕСЬ БОЙ. Бросай его на
  //    каждом пересчёте — и корона мигала бы между двумя равными сторонами каждые
  //    две секунды, при том что правило запаса её не пускает.
  const lots = new Map();
  const lotOf = (sideId) => {
    let v = lots.get(sideId);
    if (v === undefined) { v = Math.random(); lots.set(sideId, v); }
    return v;
  };

  let leaderSideId = null;
  let leaderChangedT = -Infinity;  // когда корона в последний раз сменила хозяина
  let nextRecalcT = -Infinity;     // когда пересчитывать силы
  let firstCrownTied = null;       // на первой короне было равенство? (для отчёта)
  let crownChanges = 0;            // сколько раз корона сменила хозяина за бой

  /** Сила стороны: сумма по живым — сила бойца × доля его здоровья. */
  const sideStrength = (sideId) => {
    let s = 0;
    for (const u of units) {
      if (!alive(u) || u.sideId !== sideId) continue;
      s += unitPower(u) * (u.f.getHp() / u.f.maxHp);
    }
    return s;
  };

  /**
   * ПЕРЕСЧЁТ КОРОНЫ. Зовётся лениво — из выбора цели, то есть каждый кадр, — но
   * работает по своим часам: не чаще, чем просит число пересчёта.
   *
   * Почему лениво, а не отдельным вызовом из цикла сцены: так мгновенный бой
   * получает лидера БЕЗ единой правки у себя, а значит замер считает то же, что
   * игрок видит глазами. Отдельный вызов пришлось бы поставить в двух местах, и
   * они однажды разошлись бы.
   */
  function tickLeader() {
    const t = LEAD.now();
    // ДО ЭТОЙ СЕКУНДЫ КОРОНЫ НЕТ ВОВСЕ: стороны ещё стоят на кольце выхода с
    // полным здоровьем, и лидер по силе — это лидер по броску граней, а не по бою.
    if (t < LC.delaySec) return;
    if (t < nextRecalcT) return;
    nextRecalcT = t + LC.recalcSec;

    const sides = livingSides();
    if (!sides.length) { leaderSideId = null; return; }

    // Сильнейшая живая сторона. Равенство — жребием, не номером.
    let best = null, bestS = -1;
    for (const id of sides) {
      const s = sideStrength(id);
      if (s > bestS || (s === bestS && lotOf(id) > lotOf(best))) { best = id; bestS = s; }
    }

    // Носителя нет (первая корона либо его сторона пала) — берём простым
    // максимумом. Запас силы на первую корону НЕ распространяется: с ним лидер на
    // старте, где у всех полное здоровье, не появился бы ни разу.
    if (!leaderSideId || !sides.includes(leaderSideId)) {
      if (firstCrownTied === null) {
        // Равенство на первой короне — то, что просили доложить числом.
        let ties = 0;
        for (const id of sides) if (sideStrength(id) === bestS) ties += 1;
        firstCrownTied = ties > 1;
      }
      setCrown(best, t);
      return;
    }

    // Корона держится. Сменить её может только заметно более сильный — и не
    // раньше, чем позволит удержание: пересчёт идёт раз в две секунды, и без
    // отдельного удержания корона могла бы сменить хозяина дважды за четыре.
    if (best === leaderSideId) return;
    if (t - leaderChangedT < LC.holdSec) return;
    if (bestS <= sideStrength(leaderSideId) * (1 + LC.margin)) return;
    setCrown(best, t);
  }

  function setCrown(id, t) {
    if (id === leaderSideId) return;
    leaderSideId = id;
    leaderChangedT = t;
    crownChanges += 1;
  }

  /**
   * Сторона пала. Если это был лидер — корона переходит НЕМЕДЛЕННО, мимо часов
   * удержания: держать корону на стороне, которой больше нет, нельзя ни секунды.
   */
  function leaderAfterKill() {
    if (!LEAD || !leaderSideId) return;
    if (livingSides().includes(leaderSideId)) return;
    nextRecalcT = -Infinity;   // пересчитать на ближайшем же обращении
    leaderChangedT = -Infinity; // удержание не задерживает уход павшей короны
  }

  /**
   * Цель бойца прямо сейчас. Это единственный ответ на вопрос «кто мой враг» —
   * все ниточки бойца (где враг, сколько у него сил, что он делает) идут отсюда.
   * @returns {Unit|null}
   */
  function targetFor(u) {
    if (!alive(u)) return null;
    const foes = enemiesOf(u);
    if (!foes.length) { u.target = null; return null; }

    // --- РАДИУС ВНИМАНИЯ. Ветка ЦЕЛИКОМ под признаком: без радиуса выполнение
    //     идёт мимо неё к прежним трём строкам, и ни одной новой проверки на
    //     старом пути нет.
    //
    //     ЗАЧЕМ ЭТО НУЖНО. На девятнадцати врагах правило ядра, применённое ко
    //     всему полю, отправляет бойца через всю карту мимо того, кто стоит рядом
    //     и уже бьёт: ONSLAUGHT ищет самого слабого, BULWARK — самого сильного
    //     бьющего, и оба находят их где угодно. Читается это не как охота, а как
    //     бессмыслица.
    //
    //     ЦЕЛЬ ПОБЛИЖЕ — ВРЕМЕННАЯ. Когда в радиусе никого нет, боец идёт к
    //     ближайшему врагу — но эта цель НЕ ДЕРЖИТСЯ до выбывания, как обычная:
    //     она взята не по правилу ядра, а за неимением лучшего. Как только в
    //     радиус кто-то вошёл, боец выбирает по-настоящему. Держи её как обычную
    //     — и ядро не сработало бы ни разу за бой: первая же цель, взятая на
    //     подходе, осталась бы навсегда.
    if (RADIUS) {
      // --- МАГНИТ ЛИДЕРА. Корона сужает выбор до бойцов стороны-лидера — и это
      //     ВСЁ, что она делает: правило ядра, удержание цели до выбывания и
      //     разворот ЗАСАДЫ на замах остаются в точности прежними, просто
      //     применяются к более узкому списку.
      //
      //     СТОРОНА ЛИДЕРА МАГНИТА НЕ ЧУВСТВУЕТ: ей сходиться не на кого, она
      //     живёт по «полю», как жила.
      const crown = LEAD ? leaderSide() : null;
      const magnet = crown && u.sideId !== crown;
      const near = foes.filter((o) => dist(u, o) <= RADIUS);
      const held = u.target && alive(u.target) && u.target.sideId !== u.sideId;
      // Настоящая цель (взята по ядру) держится до выбывания — как везде.
      //
      // ⚠️ КОРОНА УДЕРЖАНИЯ НЕ СРЫВАЕТ. Так просит ТЗ: «цель по-прежнему держится
      //    до выбывания». Сильное прочтение (боец короны, вошедший в радиус,
      //    срывает удержание, как срывает его замах для ЗАСАДЫ) замерено и
      //    доложено владельцу: в QUAD оно поднимает долю ударов по короне с 20.6
      //    до 25.8 %, в SOLO — с 8.1 до 9.0 %. Здесь стоит буквальное прочтение.
      if (held && !u.targetProvisional) return u.target;
      if (near.length) {
        // Бойцы лидера в радиусе — правило ядра среди НИХ. Их в радиусе нет, а
        // кто-то другой есть — правило ядра среди тех, кто есть: магнит это
        // правило ДОРОГИ, а не разрешение не замечать того, кто тебя бьёт.
        const crowned = magnet ? near.filter((o) => o.sideId === crown) : null;
        u.target = pickByCore(u, crowned && crowned.length ? crowned : near);
        u.targetProvisional = false;
        return u.target;
      }
      // Никого рядом. Держим прежнего временного, пока он на поле: иначе боец
      // перевыбирал бы ближайшего на каждом кадре и топтался между двумя.
      if (held) return u.target;
      // Идти — к ближайшему бойцу ЛИДЕРА. Это и есть магнит: пока в радиусе
      // пусто, ноги несут не к ближайшему вообще, а к короне.
      const far = magnet ? foes.filter((o) => o.sideId === crown) : foes;
      const pool = far.length ? far : foes;
      u.target = pool.reduce((a, b) => (dist(u, b) < dist(u, a) ? b : a));
      u.targetProvisional = true;
      return u.target;
    }

    // Держим прежнюю, пока она на поле и всё ещё враг.
    if (u.target && alive(u.target) && u.target.sideId !== u.sideId) return u.target;
    u.target = pickByCore(u, foes);
    return u.target;
  }

  /**
   * Кто-то начал замах. ЗАСАДА, у которой этот боец в пределах досягаемости,
   * бросает текущую цель и разворачивается на него — это и есть «срыв замаха»,
   * та самая механика сбива, которая у бойца уже построена.
   */
  function noteWindup(attacker) {
    if (!alive(attacker)) return;
    const reach = COMBAT_BALANCE.field.ambushSwitchReach;
    for (const u of units) {
      if (!alive(u) || u.coreId !== AMBUSH) continue;
      if (u.sideId === attacker.sideId) continue;      // своих не ловим
      if (u.target === attacker) continue;
      // Засада поймала момент — это НАСТОЯЩИЙ выбор по правилу ядра, а не цель
      // за неимением лучшего: снимаем пометку «временная», иначе радиус внимания
      // отобрал бы её на следующем же кадре.
      if (dist(u, attacker) <= reach) { u.target = attacker; u.targetProvisional = false; }
    }
  }

  // --- ЖИЗНЬ И СМЕРТЬ --------------------------------------------------------

  function add(unit) {
    const u = { target: null, targetProvisional: false, dead: false, ...unit };
    units.push(u);
    return u;
  }

  /** Боец выбыл. Возвращает его запись — сцене она нужна, чтобы убрать тело. */
  function kill(u) {
    if (!u || u.dead) return u;
    u.dead = true;
    u.order = ++eliminatedOrder;   // кто раньше, кто позже — для правила «ничьих нет»
    // Те, кто дрался с ним, остаются без цели и выберут новую по своему ядру.
    for (const o of units) if (o.target === u) { o.target = null; o.targetProvisional = false; }
    leaderAfterKill();   // пала сторона-лидер — корона уходит сразу, мимо удержания
    return u;
  }

  /** Живые стороны. Сторона жива, пока на поле есть хоть один её боец. */
  const livingSides = () => [...new Set(living().map((u) => u.sideId))];

  /**
   * КТО СЕЙЧАС ЛИДЕР — ключ стороны или null (короны ещё нет, либо режим её не
   * просил). Это ЕДИНСТВЕННЫЙ вход к короне, и он же её пересчитывает: спрашивают
   * её каждый кадр (выбор цели, луч, строка поверх боя), а считает она себя по
   * своим часам, не чаще чем просит число пересчёта.
   */
  const leaderSide = () => {
    if (!LEAD) return null;
    tickLeader();
    return leaderSideId;
  };

  /** Показания короны для отчёта: сколько раз сменилась и было ли равенство на первой. */
  const leaderStats = () => ({ changes: crownChanges, firstTied: firstCrownTied });

  /**
   * Победитель — когда живой осталась ровно одна сторона.
   * Если живых сторон НЕТ (последние погибли вместе), побеждает та, чей боец
   * выбыл позже: ничья в этой игре не предусмотрена.
   * @returns {string|null} ключ стороны или null, пока бой идёт
   */
  function winnerSide() {
    // Своё правило режима спрашивают ПЕРВЫМ: рейд кончается падением босса, и
    // общее правило в этот момент ещё сказало бы «бой идёт» — чужая сторона на
    // плите. Молчит правило (null) — дальше как обычно.
    if (endRule) {
      const w = endRule(units);
      if (w) return w;
    }
    const sides = livingSides();
    if (sides.length > 1) return null;   // бой идёт
    if (sides.length === 1) return sides[0];
    const last = units.filter((u) => u.dead).sort((a, b) => b.order - a.order)[0];
    return last ? last.sideId : null;
  }

  /** Убрать запись совсем. Нужно служебному респауну: там боец не погибает в
   *  бою, а пересобирается заново, и прежняя запись не должна копиться. */
  function drop(u) {
    units = units.filter((x) => x !== u);
  }

  function reset() {
    units = [];
    eliminatedOrder = 0;
    // КОРОНА — ЗА БОЙ, А НЕ ЗА ЗАХОД НА АРЕНУ. «Драться снова» выводит новые
    // стороны и новые позывные, и корона прошлого боя на них не переносится.
    // Жребий тоже бросается заново: он принадлежит матчу.
    leaderSideId = null;
    leaderChangedT = -Infinity;
    nextRecalcT = -Infinity;
    firstCrownTied = null;
    crownChanges = 0;
    lots.clear();
    // Правило режима переживает пересборку состава: его ставят один раз на весь
    // заход на арену, а `reset` зовут перед каждым боем.
  }

  return {
    add, kill, drop, reset,
    units: () => units,
    living,
    livingSides,
    leaderSide,
    leaderStats,
    enemiesOf,
    targetFor,
    noteWindup,
    winnerSide,
    /**
     * Поставить своё правило конца боя. Функция получает ВЕСЬ список бойцов
     * (вместе с выбывшими — у них стоит `dead`) и возвращает ключ победившей
     * стороны либо null, если по её мнению бой продолжается.
     * Передать null — снять правило и вернуться к общему.
     */
    setEndRule: (fn) => { endRule = typeof fn === 'function' ? fn : null; },
    /**
     * Бой кончился, когда живой стороне не с кем драться — или когда своё
     * правило режима сказало, что кончился.
     */
    isOver: () => (endRule && endRule(units)) ? true : livingSides().length <= 1,
  };
}
