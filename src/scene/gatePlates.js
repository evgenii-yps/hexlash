// gatePlates.js — ОСТРОВА ВОРОТ. Один предмет на два вопроса.
//
// В воротах выбирают дважды: сначала режим боя (DUEL / SQUAD), потом бойцов в
// состав. Остров при этом один и тот же — плита с ядром, именем под ней и тремя
// состояниями: обычное, подсвеченное, запертое. Поэтому здесь не две постройки,
// а одна, которой ДАЮТ СПИСОК: режимы на первом шаге, бойцы на втором.
//
// Второй файл был бы копией этого с другим списком внутри — и разошёлся бы с ним
// на первой же правке подсветки или раскладки. Разное у шагов только содержимое
// списка, и оно приходит снаружи.
//
// ФОРМА ТА ЖЕ, ОТДЕЛКА СВОЯ. Геометрия острова берётся готовой из modePlates
// (`buildSlab`): язык островов в игре один, и рисовать вторую такую же плиту
// значило бы завести место, где скос и обводка могут разойтись между двумя
// дверями. А вот всё, что красит, — тон корпуса, обводка, цвет ядра, плотность
// решётки — здесь своё: игрок должен понимать, что он В ДРУГОМ МЕСТЕ, а не на
// том же экране режимов.
//
// ЭМБЛЕМ НЕТ. На островах дома стоят фигуры — гексарх с учениками, разлом с
// перчатками. Здесь их нет намеренно (решение владельца, ТЗ v7 §5): новую
// геометрию под первую сборку не лепим. Что это за остров, несут подпись и цвет
// ядра. Если на приёмке окажется, что этого мало, — рисуем эмблемы отдельной
// работой, уже зная, чего именно не хватило.
//
// РАСКЛАДКА ПЕРЕНОСОМ, А НЕ СЕТКОЙ. Режимов всегда два, а бойцов сколько купит
// игрок. Поэтому острова не расставляются по заранее назначенным местам: они
// укладываются рядами, ряд переносится, неполный ряд встаёт по центру, а камера
// отъезжает ровно настолько, чтобы вместить получившееся (bounds). Так десять
// островов не потребуют переписывать раскладку — только отодвинут камеру.
//
// ОДНО СВЕЧЕНИЕ. Оба острова светиться не могут никогда: горит только тот, на
// который наведён курсор, второй в это время притухает. Запертый остров не
// загорается вообще — это и есть его главный признак, читаемый раньше подписи.
//
// ОТКАЗ ВИДЕН, А НЕ СЛЫШЕН. Клик по запертому острову не ведёт никуда и коротко
// дрожит. Дрожит предмет целиком, вместе со своей подписью (см. gatePlateTags):
// дрогнувшая плита при неподвижном имени читается как сбой отрисовки.
//
// Экспортирует: GATE_PLATES (настройки), buildGatePlates.
import * as THREE from 'three';
import { buildSlab } from './modePlates.js';
import { makeHexGridTexture } from './arenaTextures.js';

// ───────────────────────────── Настройки ─────────────────────────────
export const GATE_PLATES = {
  // Размер и раскладка. Лёжа острова стоят рядом, стоя — уходят в глубину:
  // так пара продолжает заполнять кадр, а не сжимается в узкую полоску. Это
  // тот же приём, что на островах дома, и то же объяснение.
  halfW: 2.2,
  halfD: 1.7,
  height: 0.42,
  // Шаг между центрами островов. Поперёк — ширина плиты плюс воздух; в глубину
  // — ЗАМЕТНО больше: перспектива съедает расстояние, и при шаге поперёк пара
  // в глубину читалась одной длинной плитой, а подпись дальнего ложилась на
  // ближний остров.
  stepX: 5.8,
  // Шаг в глубину РАЗНЫЙ по ориентациям, и это не украшение.
  //
  // Лёжа ряды стоят один за другим, а подпись ряда висит под его ближней
  // кромкой — в ПИКСЕЛЯХ, высотой около 37–46 в зависимости от кегля. Экранный
  // просвет между рядами при этом сжимается вместе с отъездом камеры, а подпись
  // не сжимается вовсе. На пяти островах при шаге 8.8 просвет оказался 39 px при
  // подписи 37 px, и подписи дальнего ряда легли на плиты ближнего (замерено
  // 844×390). На 10.0 просвет 26 px чистыми. Выше не поднять: на 11.5 дальний
  // остров садится до 55% ближнего при пороге 60.
  //
  // Стоя глубина — главная ось, и растягивать её нельзя: дальний остров и так
  // идёт по нижней границе «не меньше 60% от ближнего». 9.5 — столько, сколько
  // остаётся после того, как перед островами встала кнопка старта: она забирает
  // часть глубины себе, и на 10.0 область нажатия садилась до 43 px при пороге
  // 44 (замерено 390×844, трое бойцов).
  stepZ: 10.0,
  stepZPortrait: 9.5,
  // Сколько островов в ряду. Больше — ряд переносится. Лёжа кадр широкий, стоя
  // узкий, поэтому чисел два.
  //
  // Лёжа кадр широкий, и четвёрка встаёт В ОДИН РЯД. Было три — и четвёртый
  // остров переносился во второй ряд; на телефоне лёжа (844×390) второй ряд не
  // помещался вместе с подписями и кнопкой старта: подписи ложились на плиты, а
  // область нажатия садилась до 29 px при пороге 44. Ряд там дороже столбца —
  // ровно наоборот тому, как обстоит дело стоя.
  //
  // На пятёрке (выбор режима) это ничего не меняет: пять островов всё равно не
  // влезают в один ряд, и раскладка остаётся 2 + 3, как её и мерили.
  colsLandscape: 4,
  // Стоя — по одному в ряд, то есть в глубину, ПОКА ряды помещаются. Кадр узкий:
  // ширина там дорогая, глубина дешёвая. Второй столбец стоя появляется только
  // когда глубина кончилась (см. maxRowsPortrait).
  colsPortrait: 1,
  portraitAspect: 1.0, // уже этого соотношения — раскладка «в глубину»
  // ПРЕДЕЛ ГЛУБИНЫ. Глубина дешёвая, но не бесплатная: перспектива разгоняет
  // ближние острова по экрану куда быстрее дальних, и третий ряд уезжал под
  // нижнюю кромку целиком — отъезд камеры это не лечит, потому что отъезд идёт
  // по лучу и ближнюю кромку поднимает слабо (замерено в портрете 390×844:
  // подписи рядов легли на 355, 546 и 1007 при высоте окна 844).
  //
  // Два — это НЕ новое число: обе позы покоя камеры выверены глазами ровно на
  // двух островах в глубину, и `baseHalfD` в сцене — тот же габарит. Больше двух
  // рядов — начинаем второй столбец, и трое встают ровно в тот прямоугольник,
  // под который позы и мерили.
  //
  // Когда островов столько, что предел не удержать даже всеми столбцами (лёжа —
  // больше шести), побеждают ряды: лучше глубокий кадр, чем острова за краем
  // экрана. Отъезд камеры там упрётся в свой потолок, и раскладку придётся
  // пересматривать заново — это разговор про большой ростер, а не про троих.
  maxRows: 2,
  // ПРЕДЕЛ ГЛУБИНЫ СТОЯ. До 17.09.2026 его не было вовсе: стоя всё уходило в
  // глубину одной колонкой, сколько бы островов ни пришло. На двоих и троих это
  // работало, на ПЯТИ — нет: дальний остров садился до 57% от ближнего (порог
  // 60), область нажатия падала до 31 px (порог 44), а подписи ложились на
  // соседние плиты. Замерено 390×844.
  //
  // Три, а не два: на трёх рядах пара «два столбца × три ряда» вмещает пятерых,
  // и при этом четвёрка встаёт ровным квадратом 2×2. Два ряда стоя потребовали
  // бы трёх столбцов — а три острова поперёк в узком кадре отгоняют камеру за
  // её же потолок, и все трое становятся марками (то самое, из-за чего стоя
  // держат одну колонку).
  //
  // На двоих и троих правило не срабатывает вовсе: ceil(3/3) = 1 столбец —
  // ровно та раскладка, которую владелец принял глазами.
  maxRowsPortrait: 3,

  // Отделка. Холоднее и темнее островов дома: ворота — преддверие боя, а не
  // развилка. Обводка матовая, своего света у неё нет.
  body: 0x10131f,
  rim: 0x5c6b94,
  rimOpacity: 0.22,
  chamfer: 0.34,       // скос угла — тот же, что у островов дома: форма общая
  hexTile: 4.2,        // мировой размер одной ячейки решётки на крышке

  // Цвет ядра приходит СО СПИСКОМ: у режима он свой, у бойца — цвет его ядра.
  // Розовый не берём ни там, ни там: он принадлежит интерфейсу и деньгам, а
  // здесь предметы.
  fallbackCore: '#7184B0',

  dimLevel: 0.5,       // яркость НЕподсвеченного острова, пока горит другой
  litLerp: 6.5,        // 1/с сглаживания подсветки — без щелчка
  lockedLit: 0.0,      // запертый не загорается никогда

  // Ядро — плоский светящийся диск в крышке острова. Не сфера и не столб: на
  // плите, которую разглядывают сверху-сбоку, диск читается, а столб спорит с
  // подлётом камеры.
  coreR: 0.40,
  coreLift: 0.012,     // над крышкой, чтобы не спорить за глубину
  coreDim: 0.16,       // яркость ядра в покое (запертый стоит на ней всегда)
  coreLitBoost: 0.72,  // добавка яркости подсвеченному

  // Отказ: короткое дрожание запертого острова.
  shakeMs: 380,
  shakeAmp: 0.075,     // мировых единиц вбок
  shakeHz: 11,

  // Подпись встаёт под БЛИЖНЕЙ кромкой острова, а не под его центром: от центра
  // она при взгляде сверху-сбоку ложится на саму плиту. Отступ в мировых
  // единицах — он переводится в пиксели проекцией, поэтому при зуме подпись не
  // отрывается от предмета.
  captionDrop: 0.35,
};

const _v = new THREE.Vector3();

/** Плоский диск-ядро в крышке острова. */
function buildCore(colorHex, topY) {
  const geo = new THREE.CircleGeometry(GATE_PLATES.coreR, 40);
  const mat = new THREE.MeshBasicMaterial({
    color: new THREE.Color(colorHex),
    transparent: true,
    opacity: GATE_PLATES.coreDim,
    blending: THREE.AdditiveBlending,
    depthWrite: false,
  });
  const mesh = new THREE.Mesh(geo, mat);
  mesh.rotation.x = -Math.PI / 2;
  mesh.position.y = topY + GATE_PLATES.coreLift;
  return { mesh, mat, dispose: () => { geo.dispose(); mat.dispose(); } };
}

/**
 * @param {object} opts
 * @param {Array<{id:string, core?:string, locked?:boolean}>} opts.items
 *        что стоит на островах: режимы на первом шаге, бойцы на втором.
 *        `core` — цвет ядра, `locked` — остров виден, но не выбирается.
 * @param {number} [opts.maxAniso]
 * @returns {object} острова + их общий контракт
 */
export function buildGatePlates(opts = {}) {
  const o = GATE_PLATES;
  const items = opts.items || [];
  const group = new THREE.Group();
  const hexTex = makeHexGridTexture(opts.maxAniso || 1);
  hexTex.repeat.set(1, 1);

  const make = (item) => {
    const root = new THREE.Group();
    const slab = buildSlab(o.halfW, o.halfD, o.height, hexTex, o);
    root.add(slab.group);

    const core = buildCore(item.core || o.fallbackCore, slab.topY);
    root.add(core.mesh);

    // Одна невидимая коробка на остров — дешёвая цель для луча, и заодно она
    // делает весь остров ОДНИМ предметом: наведение не зависит от того, попал
    // ли курсор в крышку или в бок.
    const pickGeo = new THREE.BoxGeometry(o.halfW * 2, o.height * 2.2, o.halfD * 2);
    const pick = new THREE.Mesh(pickGeo, new THREE.MeshBasicMaterial({ visible: false }));
    pick.position.y = o.height * 0.6;
    pick.userData.gatePlate = item.id;
    root.add(pick);

    group.add(root);
    return {
      id: item.id,
      locked: !!item.locked,
      root, slab, core, pick, pickGeo,
      lit: 0,        // 0…1 — собственная подсветка
      level: 1,      // 1…dimLevel — насколько его топит свет соседа
      picked: false, // выбран в состав — горит и без курсора
      baseX: 0, baseZ: 0,   // поза без дрожания (ставит layout)
      shakeUntil: 0,
    };
  };

  const plates = {};
  for (const it of items) plates[it.id] = make(it);
  const list = Object.values(plates);
  const pickables = list.map((p) => p.pick);

  let hovered = null;
  let portrait = false;
  // Габарит разложенных островов — по нему сцена считает, откуда смотреть.
  // `rows` там же: камере мало знать габарит, ей надо знать, СКОЛЬКО РЯДОВ он
  // накрывает. Один ряд можно смотреть низко, два — уже нет: дальний виден с
  // ребра, и ни подпись под ним не помещается, ни палец в него не попадает.
  const extent = { halfW: o.halfW, halfD: o.halfD, rows: 1 };
  const now = () => (typeof performance !== 'undefined' ? performance.now() : Date.now());

  /**
   * Разложить острова рядами под текущее соотношение кадра.
   *
   * Ряд переносится, когда в нём кончились места; НЕПОЛНЫЙ РЯД встаёт по центру.
   * Последнее — не украшение: тройка в ряду по двое легла бы как 2+1 с дырой
   * справа, и это читается как «одного острова не хватает», хотя все на месте.
   * Та же беда была на плоском экране состава, и решается тем же способом.
   */
  function layout(aspect) {
    portrait = aspect < o.portraitAspect;
    // Столбцов — сколько разрешает ориентация, но не меньше, чем нужно, чтобы
    // уложиться в предел глубины (см. maxRows / maxRowsPortrait в настройках).
    const prefCols = Math.max(1, Math.min(list.length, portrait ? o.colsPortrait : o.colsLandscape));
    // Предел глубины СВОЙ у каждой ориентации: лёжа глубина дорогая (перспектива
    // разгоняет ближние ряды по экрану), стоя дорогая ширина. До пяти островов
    // предел стоя не срабатывал вовсе — см. maxRowsPortrait.
    const rowCap = Math.max(1, portrait ? o.maxRowsPortrait : o.maxRows);
    const needCols = Math.ceil(list.length / rowCap);
    const cols = Math.max(1, Math.min(list.length, Math.max(prefCols, needCols)));
    const rows = Math.ceil(list.length / cols);
    const stepZ = portrait ? o.stepZPortrait : o.stepZ;

    // РЯДЫ РАВНЯЮТСЯ, А ОСТАТОК УХОДИТ В БЛИЖНИЕ. Раньше ряды набивались по
    // порядку — первый полный, последний какой получится, — и на пяти островах
    // получалось 3 + 2: трое в ДАЛЬНЕМ ряду. Дальний ряд на экране самый узкий,
    // шаг между его островами самый мелкий, и подписи там сходятся первыми
    // (замерено 844×390: «SQUAD» и «CHAIN» встали впритык). Ближний ряд на том
    // же экране даёт шаг в полтора раза шире и троих несёт свободно.
    //
    // Порядок чтения при этом не ломается: ряды идут от дальнего к ближнему,
    // то есть сверху вниз, и пятёрка читается «DUEL, SQUAD / CHAIN, RAID,
    // COLLAPSE» — ровно тем порядком, в каком она стоит в таблице режимов.
    //
    // На принятых кадрах правило не срабатывает вовсе: ряд один (лёжа двое или
    // трое) или ряды и так равны (стоя двое, трое).
    const per = Math.floor(list.length / rows);
    const extra = list.length % rows;                 // сколько рядов получат +1
    const counts = [];
    for (let r = 0; r < rows; r++) counts.push(per + (r >= rows - extra ? 1 : 0));
    const widest = Math.max(...counts);

    let at = 0;
    counts.forEach((inRow, row) => {
      for (let c = 0; c < inRow; c++) {
        const p = list[at++];
        p.baseX = (c - (inRow - 1) / 2) * o.stepX;
        p.baseZ = (row - (rows - 1) / 2) * stepZ;
        p.root.position.set(p.baseX, 0, p.baseZ);
      }
    });

    extent.halfW = ((widest - 1) * o.stepX) / 2 + o.halfW;
    extent.halfD = ((rows - 1) * stepZ) / 2 + o.halfD;
    extent.rows = rows;
  }

  /** Габарит разложенного — сцене, чтобы отодвинуть камеру ровно настолько. */
  function bounds() {
    return { halfW: extent.halfW, halfD: extent.halfD, height: o.height, rows: extent.rows };
  }

  /** Подсветить остров. Запертый не подсвечивается — у него это и есть признак. */
  function setHover(id) {
    const p = id ? plates[id] : null;
    hovered = (p && !p.locked) ? id : null;
  }

  /**
   * Отметить выбранные острова. Выбор держится сам, без курсора: игрок должен
   * видеть свой состав, убрав руку с мыши. Невыбранные притухают — так же, как
   * на плоском экране состава, откуда этот шаг и переехал.
   */
  function setSelected(ids) {
    const set = new Set(ids || []);
    for (const p of list) p.picked = set.has(p.id);
  }

  /** Отказать: коротко дрогнуть островом. Возвращает false, если острова нет. */
  function refuse(id) {
    const p = plates[id];
    if (!p) return false;
    p.shakeUntil = now() + o.shakeMs;
    return true;
  }

  /**
   * Прицел для пролёта внутрь острова — та же форма, что отдаёт modePlates.aimFor,
   * потому что её ждёт тот же режиссёр (islandDive).
   */
  function aimFor(id) {
    const p = plates[id];
    if (!p) return null;
    _v.set(0, o.height * 0.5, 0);
    const point = p.root.localToWorld(_v.clone());
    return {
      point,
      halfW: o.halfW,
      halfH: o.height * 0.5 + o.coreR,
      fill: 0.88,
      minDist: 1.2,
    };
  }

  /** Экранная точка, куда встаёт верх подписи. */
  function captionScreen(id, camera, w, h) {
    const p = plates[id];
    if (!p) return { x: 0, y: 0, visible: false };
    // Точка отсчёта — ближняя к камере кромка плиты. Какая из двух ближняя,
    // решает раскладка: лёжа острова стоят по X и ближняя кромка у обоих одна и
    // та же (+Z), стоя они уходят в глубину, и у дальнего ближняя всё равно +Z.
    _v.set(0, -o.captionDrop, o.halfD);
    p.root.localToWorld(_v);
    _v.project(camera);
    const visible = _v.z < 1 && _v.x > -1.6 && _v.x < 1.6;
    return {
      x: (_v.x * 0.5 + 0.5) * w,
      y: (-_v.y * 0.5 + 0.5) * h,
      visible,
    };
  }

  /** Кадр: подсветка, ядро, дрожание отказа. */
  function update(t, dt) {
    const k = 1 - Math.exp(-o.litLerp * dt);
    const tNow = now();

    for (const p of list) {
      // Горит выбранный ИЛИ тот, на который наведён курсор. Выбор сильнее: убрав
      // руку, игрок должен видеть состав, а не пустую комнату.
      const wantLit = p.locked ? o.lockedLit : ((p.picked || hovered === p.id) ? 1 : 0);
      // Притухают соседи того, что сейчас горит: и подсвеченного курсором, и
      // выбранного. Если выбран хоть кто-то — притухают все невыбранные.
      const anyPicked = list.some((x) => x.picked);
      const standsOut = p.picked || hovered === p.id;
      const wantLevel = ((hovered || anyPicked) && !standsOut) ? o.dimLevel : 1;
      p.lit += (wantLit - p.lit) * k;
      p.level += (wantLevel - p.level) * k;

      p.slab.rimMat.opacity = o.rimOpacity * p.level * (1 + p.lit * 1.6);
      p.slab.hexMat.opacity = 0.55 * p.level;
      p.core.mat.opacity = (o.coreDim + o.coreLitBoost * p.lit) * p.level;

      // Дрожание — только по X/Z, вокруг позы, которую поставил layout. Оно
      // затухает само: амплитуда падает к концу, иначе остров останавливается
      // рывком и это читается как поломка, а не как отказ.
      if (p.shakeUntil > tNow) {
        const left = (p.shakeUntil - tNow) / o.shakeMs;      // 1 → 0
        const a = o.shakeAmp * left;
        const ph = Math.sin((tNow / 1000) * Math.PI * 2 * o.shakeHz);
        p.root.position.x = p.baseX + a * ph;
      } else if (p.root.position.x !== p.baseX || p.root.position.z !== p.baseZ) {
        p.root.position.set(p.baseX, 0, p.baseZ);
      }
    }
  }

  /** Дрожит ли остров прямо сейчас — вид синхронит подпись по этому. */
  function shaking(id) {
    const p = plates[id];
    return !!p && p.shakeUntil > now();
  }

  function dispose() {
    for (const p of list) {
      p.slab.dispose();
      p.core.dispose();
      p.pickGeo.dispose();
      p.pick.material.dispose();
    }
    hexTex.dispose();
  }

  return {
    group, plates, list, pickables,
    layout, bounds, setHover, setSelected, refuse, aimFor, captionScreen, update, shaking, dispose,
    get hovered() { return hovered; },
  };
}
