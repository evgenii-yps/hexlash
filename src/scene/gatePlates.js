const _v = new THREE.Vector3();
const _box = new THREE.Box3();
const _bv = new THREE.Vector3();

/**
 * Поставить готовое тело на крышку острова: рост по доле ширины плиты, разворот
 * в три четверти, ноги на плите.
 *
 * ⚠️ РОСТ СЧИТАЕТСЯ ОТ ИЗМЕРЕННОЙ ВЫСОТЫ, а не от известного числа. У тела свой
 * масштаб (см. конец buildFighter), и он менялся; взять его числом значит
 * завести здесь копию чужой константы, которая соврёт молча.
 *
 * ⚠️ И МЕРИТЬ НАДО ТОЛЬКО МЕШИ. Над головой висит табличка HP — спрайт, чей
 * габарит в мировых единицах огромен и к росту отношения не имеет. Общая коробка
 * с ней даёт рост вдвое больше настоящего, и боец уходит в плиту по пояс.
 * Табличку сцена гасит, но скрытое `Box3.setFromObject` всё равно считает.
 *
 * @returns {number} мировая высота поставленного тела (нужна коробке выбора)
 */
function placeBody(body, halfW, topY, o) {
  const g = body.group;
  g.scale.setScalar(1);
  g.position.set(0, 0, 0);
  g.rotation.set(0, 0, 0);
  g.updateMatrixWorld(true);

  _box.makeEmpty();
  g.traverse((x) => {
    if (!x.isMesh && !x.isLine && !x.isPoints) return;
    if (!x.geometry) return;
    if (!x.geometry.boundingBox) x.geometry.computeBoundingBox();
    _bv.copy(x.geometry.boundingBox.max).applyMatrix4(x.matrixWorld);
    _box.expandByPoint(_bv);
    _bv.copy(x.geometry.boundingBox.min).applyMatrix4(x.matrixWorld);
    _box.expandByPoint(_bv);
  });

  const natural = Math.max(0.01, _box.max.y);
  const want = halfW * 2 * o.fighterH;
  const k = want / natural;
  g.scale.setScalar(k);
  g.rotation.y = Math.PI + o.fighterQuarter;
  g.position.set(0, topY + o.fighterLift, 0);
  return want;
}

/** Плоский диск-ядро в крышке острова. */
function buildCore(colorHex, topY) {
  const geo = new THREE.CircleGeometry(GATE_PLATES.coreR, 40);
  const mat = new THREE.MeshBasicMaterial({
    color: new THREE.Color(colorHex),
    transparent: true,
    opacity: GATE_PLATES.coreDim,
    blending: THREE.AdditiveBlending,
    depthWrite: false,
  });
  const mesh = new THREE.Mesh(geo, mat);
  mesh.rotation.x = -Math.PI / 2;
  mesh.position.y = topY + GATE_PLATES.coreLift;
  return { mesh, mat, dispose: () => { geo.dispose(); mat.dispose(); } };
}

/**
 * @param {object} opts
 * @param {Array<{id:string, core?:string, locked?:boolean, emblem?:string, body?:object}>} opts.items
 *        что стоит на островах: режимы на первом шаге, бойцы на втором.
 *        `core` — цвет режима или бойца, `locked` — остров виден, но не
 *        выбирается, `emblem` — вид эмблемы (только у режимов; см. gateEmblems),
 *        `body` — ГОТОВОЕ тело бойца от `buildFighter` (только у бойцов).
 *        Тело сюда приходит собранным и остаётся собственностью сцены: остров
 *        его ставит и тикает, но не строит и не разбирает.
 * @param {number} [opts.maxAniso]
 * @param {boolean} [opts.reduced] «уменьшить движение»: эмблемы стоят
 * @returns {object} острова + их общий контракт
 */
export function buildGatePlates(opts = {}) {
  const o = GATE_PLATES;
  const items = opts.items || [];
  const reduced = !!opts.reduced;
  const group = new THREE.Group();
  const hexTex = makeHexGridTexture(opts.maxAniso || 1);
  hexTex.repeat.set(1, 1);

  const make = (item) => {
    const root = new THREE.Group();
    const slab = buildSlab(o.halfW, o.halfD, o.height, hexTex, o);
    root.add(slab.group);

    const color = item.core || o.fallbackCore;
    // Эмблема, БОЕЦ или диск — ровно одно из трёх, и это не перечисление
    // вариантов, а одно правило: у острова один светящийся предмет. У режима
    // его несёт эмблема, у бойца — его собственное ядро, а диск остаётся только
    // там, где нет ни того ни другого (запасной путь: тело не собралось).
    const emblem = item.emblem
      ? buildGateEmblem(item.emblem, { color, halfW: o.halfW, halfD: o.halfD, topY: slab.topY })
      : null;
    if (emblem) root.add(emblem.group);
    const body = (!emblem && item.body) ? item.body : null;
    const bodyH = body ? placeBody(body, o.halfW, slab.topY, o) : 0;
    if (body) root.add(body.group);
    const core = (emblem || body) ? null : buildCore(color, slab.topY);
    if (core) root.add(core.mesh);

    // Одна невидимая коробка на остров — дешёвая цель для луча, и заодно она
    // делает весь остров ОДНИМ предметом: наведение не зависит от того, попал
    // ли курсор в крышку или в бок.
    //
    // Когда на плите стоит эмблема ИЛИ БОЕЦ, коробка растёт ВВЕРХ до его
    // макушки: клик по тому, что стоит на острове, обязан быть кликом по самому
    // острову (ТЗ §4.2). Вниз коробка не меняется ни на единицу — область
    // нажатия самой плиты уменьшиться не должна.
    const topAir = emblem ? emblem.top : (body ? slab.topY + bodyH : o.height * 1.7);
    const bottomAir = -o.height * 0.5;
    const pickH = topAir - bottomAir;
    const pickGeo = new THREE.BoxGeometry(o.halfW * 2, pickH, o.halfD * 2);
    const pick = new THREE.Mesh(pickGeo, new THREE.MeshBasicMaterial({ visible: false }));
    pick.position.y = (topAir + bottomAir) / 2;
    pick.userData.gatePlate = item.id;
    root.add(pick);

    group.add(root);
    return {
      id: item.id,
      locked: !!item.locked,
      root, slab, core, emblem, body, bodyH, pick, pickGeo,
      lit: 0,        // 0…1 — собственная подсветка
      level: 1,      // 1…dimLevel — насколько его топит свет соседа
      picked: false, // выбран в состав — горит и без курсора
      baseX: 0, baseZ: 0,   // поза без дрожания (ставит layout)
      shakeUntil: 0,
    };
  };

  const plates = {};
  for (const it of items) plates[it.id] = make(it);
  const list = Object.values(plates);
  const pickables = list.map((p) => p.pick);

  let hovered = null;
  let portrait = false;
  // Габарит разложенных островов — по нему сцена считает, откуда смотреть.
  // `rows` там же: камере мало знать габарит, ей надо знать, СКОЛЬКО РЯДОВ он
  // накрывает. Один ряд можно смотреть низко, два — уже нет: дальний виден с
  // ребра, и ни подпись под ним не помещается, ни палец в него не попадает.
  const extent = { halfW: o.halfW, halfD: o.halfD, rows: 1 };
  const now = () => (typeof performance !== 'undefined' ? performance.now() : Date.now());

  /**
   * Разложить острова рядами под текущее соотношение кадра.
   *
   * Ряд переносится, когда в нём кончились места; НЕПОЛНЫЙ РЯД встаёт по центру.
   * Последнее — не украшение: тройка в ряду по двое легла бы как 2+1 с дырой
   * справа, и это читается как «одного острова не хватает», хотя все на месте.
   * Та же беда была на плоском экране состава, и решается тем же способом.
   */
  function layout(aspect) {
    portrait = aspect < o.portraitAspect;
    // Столбцов — сколько разрешает ориентация, но не меньше, чем нужно, чтобы
    // уложиться в предел глубины (см. maxRows / maxRowsPortrait в настройках).
    const prefCols = Math.max(1, Math.min(list.length, portrait ? o.colsPortrait : o.colsLandscape));
    // Предел глубины СВОЙ у каждой ориентации: лёжа глубина дорогая (перспектива
    // разгоняет ближние ряды по экрану), стоя дорогая ширина. До пяти островов
    // предел стоя не срабатывал вовсе — см. maxRowsPortrait.
    const rowCap = Math.max(1, portrait ? o.maxRowsPortrait : o.maxRows);
    const needCols = Math.ceil(list.length / rowCap);
    const cols = Math.max(1, Math.min(list.length, Math.max(prefCols, needCols)));
    const rows = Math.ceil(list.length / cols);
    const stepZ = portrait ? o.stepZPortrait : o.stepZ;

    // РЯДЫ РАВНЯЮТСЯ, А ОСТАТОК УХОДИТ В БЛИЖНИЕ. Раньше ряды набивались по
    // порядку — первый полный, последний какой получится, — и на пяти островах
    // получалось 3 + 2: трое в ДАЛЬНЕМ ряду. Дальний ряд на экране самый узкий,
    // шаг между его островами самый мелкий, и подписи там сходятся первыми
    // (замерено 844×390: «SQUAD» и «CHAIN» встали впритык). Ближний ряд на том
    // же экране даёт шаг в полтора раза шире и троих несёт свободно.
    //
    // Порядок чтения при этом не ломается: ряды идут от дальнего к ближнему,
    // то есть сверху вниз, и пятёрка читается «DUEL, SQUAD / CHAIN, RAID,
    // COLLAPSE» — ровно тем порядком, в каком она стоит в таблице режимов.
    //
    // На принятых кадрах правило не срабатывает вовсе: ряд один (лёжа двое или
    // трое) или ряды и так равны (стоя двое, трое).
    const per = Math.floor(list.length / rows);
    const extra = list.length % rows;                 // сколько рядов получат +1
    const counts = [];
    for (let r = 0; r < rows; r++) counts.push(per + (r >= rows - extra ? 1 : 0));
    const widest = Math.max(...counts);

    let at = 0;
    counts.forEach((inRow, row) => {
      for (let c = 0; c < inRow; c++) {
        const p = list[at++];
        p.baseX = (c - (inRow - 1) / 2) * o.stepX;
        p.baseZ = (row - (rows - 1) / 2) * stepZ;
        p.root.position.set(p.baseX, 0, p.baseZ);
      }
    });

    extent.halfW = ((widest - 1) * o.stepX) / 2 + o.halfW;
    extent.halfD = ((rows - 1) * stepZ) / 2 + o.halfD;
    extent.rows = rows;
  }

  /** Габарит разложенного — сцене, чтобы отодвинуть камеру ровно настолько. */
  function bounds() {
    // `tall` — насколько высоко поднимается САМОЕ ВЫСОКОЕ из того, что стоит на
    // островах, считая от их подошвы. Пустая плита — это её собственная высота;
    // плита с эмблемой или бойцом — до его макушки.
    //
    // ⚠️ КАМЕРЕ ЭТО НУЖНО. Она вмещает разложенное в кадр по ширине и глубине, и
    // пока на плитах ничего не стояло, двух мерок хватало. С эмблемами и
    // бойцами высота стала третьей: тело ростом 2,42 — это больше, чем вся
    // плита с диском (0,42), и камера, не знающая про него, кадрирует пустую
    // комнату, а головы уезжают в хром.
    let tall = o.height;
    let standing = false;
    for (const p of list) {
      if (p.emblem) tall = Math.max(tall, p.emblem.top);
      else if (p.body) { tall = Math.max(tall, p.slab.topY + p.bodyH); standing = true; }
    }
    // `standing` — стоят ли на островах ЛЮДИ. Признак, а не число, и это
    // осознанно: камере важно не «насколько высоко», а «есть ли ряд фигур,
    // сквозь который смотрит следующий ряд». Непрерывная мерка высоты тут была
    // бы хуже — эмблема (2,19) и боец (2,63) различаются на треть, и любой
    // порог между ними пришлось бы ставить впритык к эмблеме: подрастёт она на
    // сантиметр — и поедут принятые кадры выбора режима.
    return { halfW: extent.halfW, halfD: extent.halfD, height: o.height, tall, standing, rows: extent.rows };
  }

  /** Подсветить остров. Запертый не подсвечивается — у него это и есть признак. */
  function setHover(id) {
    const p = id ? plates[id] : null;
    hovered = (p && !p.locked) ? id : null;
  }

  /**
   * Отметить выбранные острова. Выбор держится сам, без курсора: игрок должен
   * видеть свой состав, убрав руку с мыши. Невыбранные притухают — так же, как
   * на плоском экране состава, откуда этот шаг и переехал.
   */
  function setSelected(ids) {
    const set = new Set(ids || []);
    for (const p of list) p.picked = set.has(p.id);
  }

  /** Отказать: коротко дрогнуть островом. Возвращает false, если острова нет. */
  function refuse(id) {
    const p = plates[id];
    if (!p) return false;
    p.shakeUntil = now() + o.shakeMs;
    return true;
  }

  /**
   * Прицел для пролёта внутрь острова — та же форма, что отдаёт modePlates.aimFor,
   * потому что её ждёт тот же режиссёр (islandDive).
   */
  function aimFor(id) {
    const p = plates[id];
    if (!p) return null;
    // Предмет, по которому кадрируем: пустая плита — сама плита, плита с
    // эмблемой — ВСЯ композиция, от подошвы плиты до макушки эмблемы. Прицел
    // соответственно стоит в середине её высоты, а не на крышке: с прицелом на
    // крышке камера смотрит фигуре в колени.
    // Боец кадрируется как эмблема, и по той же причине: на плите стоит высокий
    // предмет, и мерить кадр плитой значило бы въехать бойцу в колени.
    const tall = p.emblem ? p.emblem.top : (p.body ? p.slab.topY + p.bodyH : 0);
    const half = tall ? tall / 2 : o.height * 0.5 + o.coreR;
    _v.set(0, tall ? half : o.height * 0.5, 0);
    const point = p.root.localToWorld(_v.clone());
    return {
      point,
      halfW: o.halfW,
      halfH: half,
      fill: tall ? o.diveFillEmblem : o.diveFill,
      minDist: o.diveMinDist,
    };
  }

  /** Экранная точка, куда встаёт верх подписи. */
  function captionScreen(id, camera, w, h) {
    const p = plates[id];
    if (!p) return { x: 0, y: 0, visible: false };
    // Точка отсчёта — ближняя к камере кромка плиты. Какая из двух ближняя,
    // решает раскладка: лёжа острова стоят по X и ближняя кромка у обоих одна и
    // та же (+Z), стоя они уходят в глубину, и у дальнего ближняя всё равно +Z.
    _v.set(0, -o.captionDrop, o.halfD);
    p.root.localToWorld(_v);
    _v.project(camera);
    const visible = _v.z < 1 && _v.x > -1.6 && _v.x < 1.6;
    return {
      x: (_v.x * 0.5 + 0.5) * w,
      y: (-_v.y * 0.5 + 0.5) * h,
      visible,
    };
  }

  /** Кадр: подсветка, ядро, дрожание отказа. */
  function update(t, dt) {
    const k = 1 - Math.exp(-o.litLerp * dt);
    const tNow = now();

    for (const p of list) {
      // Горит выбранный ИЛИ тот, на который наведён курсор. Выбор сильнее: убрав
      // руку, игрок должен видеть состав, а не пустую комнату.
      const wantLit = p.locked ? o.lockedLit : ((p.picked || hovered === p.id) ? 1 : 0);
      // Притухают соседи того, что сейчас горит: и подсвеченного курсором, и
      // выбранного. Если выбран хоть кто-то — притухают все невыбранные.
      const anyPicked = list.some((x) => x.picked);
      const standsOut = p.picked || hovered === p.id;
      const wantLevel = ((hovered || anyPicked) && !standsOut) ? o.dimLevel : 1;
      p.lit += (wantLit - p.lit) * k;
      p.level += (wantLevel - p.level) * k;

      p.slab.rimMat.opacity = o.rimOpacity * p.level * (1 + p.lit * 1.6);
      p.slab.hexMat.opacity = 0.55 * p.level;
      // Акцент острова несёт ЛИБО эмблема, ЛИБО ядро — смотря что на нём стоит.
      // Числа у них одни и те же (coreDim / coreLitBoost), поэтому отклик на
      // покой и курсор одинаков, чем бы цвет ни носился.
      if (p.core) p.core.mat.opacity = (o.coreDim + o.coreLitBoost * p.lit) * p.level;
      // Время эмблеме отдаём только при включённых анимациях; при выключенных
      // она получает null и стоит.
      if (p.emblem) p.emblem.tick(reduced ? null : t, p.lit, p.level);
      // Боец живёт сам: дыхание и пульс ядра идут из его собственного `update`,
      // мозг у него выключен (ai.on = false по умолчанию), и подсказки о
      // сопернике ему не даны — значит он просто стоит. При выключенных
      // анимациях времени ему не даём вовсе: `setReducedMotion` уже поставил
      // его в покой, и лишний тик только тратил бы кадр.
      if (p.body && !reduced) p.body.update(t, dt);

      // Дрожание — только по X/Z, вокруг позы, которую поставил layout. Оно
      // затухает само: амплитуда падает к концу, иначе остров останавливается
      // рывком и это читается как поломка, а не как отказ.
      if (p.shakeUntil > tNow) {
        const left = (p.shakeUntil - tNow) / o.shakeMs;      // 1 → 0
        const a = o.shakeAmp * left;
        const ph = Math.sin((tNow / 1000) * Math.PI * 2 * o.shakeHz);
        p.root.position.x = p.baseX + a * ph;
      } else if (p.root.position.x !== p.baseX || p.root.position.z !== p.baseZ) {
        p.root.position.set(p.baseX, 0, p.baseZ);
      }
    }
  }

  /** Дрожит ли остров прямо сейчас — вид синхронит подпись по этому. */
  function shaking(id) {
    const p = plates[id];
    return !!p && p.shakeUntil > now();
  }

  function dispose() {
    for (const p of list) {
      // ⚠️ ТЕЛО НЕ РАЗБИРАЕМ И ДАЖЕ НЕ СНИМАЕМ С ГРУППЫ ВРУЧНУЮ — только
      // отвязываем от острова, который сейчас исчезнет. Тела принадлежат сцене:
      // она собрала их на входе в ворота и держит до самого ухода, потому что
      // шаг может смениться туда и обратно, а собирать их заново — это сборка
      // под чёрным кадром, от которой ТЗ как раз и уводит.
      if (p.body) p.root.remove(p.body.group);
      p.slab.dispose();
      p.core?.dispose();
      p.emblem?.dispose();
      p.pickGeo.dispose();
      p.pick.material.dispose();
    }
    hexTex.dispose();
  }

  return {
    group, plates, list, pickables,
    layout, bounds, setHover, setSelected, refuse, aimFor, captionScreen, update, shaking, dispose,
    get hovered() { return hovered; },
  };
}
