// gatePlates.js — ОСТРОВА ВОРОТ. Один предмет на два вопроса.
//
// В воротах выбирают дважды: сначала режим боя (DUEL / SQUAD), потом бойцов в
// состав. Остров при этом один и тот же — плита с ядром, именем под ней и тремя
// состояниями: обычное, подсвеченное, запертое. Поэтому здесь не две постройки,
// а одна, которой ДАЮТ СПИСОК: режимы на первом шаге, бойцы на втором.
//
// Второй файл был бы копией этого с другим списком внутри — и разошёлся бы с ним
// на первой же правке подсветки или раскладки. Разное у шагов только содержимое
// списка, и оно приходит снаружи.
//
// ФОРМА ТА ЖЕ, ОТДЕЛКА СВОЯ. Геометрия острова берётся готовой из modePlates
// (`buildSlab`): язык островов в игре один, и рисовать вторую такую же плиту
// значило бы завести место, где скос и обводка могут разойтись между двумя
// дверями. А вот всё, что красит, — тон корпуса, обводка, цвет ядра, плотность
// решётки — здесь своё: игрок должен понимать, что он В ДРУГОМ МЕСТЕ, а не на
// том же экране режимов.
//
// ЭМБЛЕМЫ — У РЕЖИМОВ, И ОНИ ЗАМЕЩАЮТ ЯДРО. На первой сборке ворот эмблем не
// было вовсе (решение владельца, ТЗ v7 §5: новую геометрию под первую сборку не
// лепим), и что это за остров, несли подпись и цвет плоского ядра в крышке. На
// приёмке этого оказалось мало: пять островов различались только словом.
//
// Теперь у островов РЕЖИМА стоят объёмные эмблемы (gateEmblems.js), и цвет
// режима носят они — диск при этом снимается. Не добавляется, а именно
// снимается: два светящихся пятна на одном острове это два акцента, а акцент на
// предмете один.
//
// У островов БОЙЦА с 17.09.2026 стоит САМ БОЕЦ — то же тело, что в зале FORGE и
// на арене, собранное тем же `buildFighter`. Диск при этом снимается по той же
// причине, что и у эмблем: у бойца есть собственное ядро, и оно и есть свечение
// острова. Два светящихся пятна на одной плите — это два акцента.
//
// ⚠️ ТЕЛО СЮДА ПРИХОДИТ ГОТОВЫМ, а не собирается здесь. Собирать его в момент
// раскладки значило бы собирать на смене шага — под чёрным кадром занавеса, — а
// ТЗ требует обратного: тела строятся заранее, на входе в ворота, пока стоит
// экран загрузки. Кто и когда их строит — забота сцены (ArenaGateScene);
// острову дают уже собранное и он только ставит его на крышку.
//
// ⚠️ И РАЗБИРАЕТ ИХ ТОЖЕ НЕ ОСТРОВ. Тела переживают пересборку островов (шаг
// меняется, тела остаются), поэтому `dispose` острова их не трогает — иначе
// возврат с шага 2 на шаг 1 и обратно оставил бы пустые плиты.
//
// РАСКЛАДКА ПЕРЕНОСОМ, А НЕ СЕТКОЙ. Режимов всегда два, а бойцов сколько купит
// игрок. Поэтому острова не расставляются по заранее назначенным местам: они
// укладываются рядами, ряд переносится, неполный ряд встаёт по центру, а камера
// отъезжает ровно настолько, чтобы вместить получившееся (bounds). Так десять
// островов не потребуют переписывать раскладку — только отодвинут камеру.
//
// ОДНО СВЕЧЕНИЕ. Оба острова светиться не могут никогда: горит только тот, на
// который наведён курсор, второй в это время притухает. Запертый остров не
// загорается вообще — это и есть его главный признак, читаемый раньше подписи.
//
// ОТКАЗ ВИДЕН, А НЕ СЛЫШЕН. Клик по запертому острову не ведёт никуда и коротко
// дрожит. Дрожит предмет целиком, вместе со своей подписью (см. gatePlateTags):
// дрогнувшая плита при неподвижном имени читается как сбой отрисовки.
//
// Экспортирует: GATE_PLATES (настройки), buildGatePlates.
