// hpStagger.js — РАЗВЕСТИ ПЛАШКИ ЗДОРОВЬЯ, когда тел на плите много.
//
// ОТКУДА БЕДА. Плашка висит на своей высоте над бойцом и держит постоянный
// размер на экране. О соседях она не знает ничего — и не должна: это индикатор
// одного бойца. Пока бойцов двое и они стоят врозь, плашки не встречаются. На
// шести телах, которые к середине боя сходятся в кучу, все плашки садятся на
// одну экранную строку: на замере 3 на 3 из шести читались четыре, и то внахлёст.
//
// ПОЧЕМУ НЕ ЛЕСЕНКОЙ ПО ВЫСОТЕ. Первым делом каждому телу дали свой ярус и
// подняли плашку на фиксированную высоту в мире. Не помогло: тела стоят на
// РАЗНОЙ ГЛУБИНЕ, и дальний боец с яруса повыше приходит на ту же экранную
// строку, что ближний с яруса пониже. Замер это и показал — две плашки снова
// сошлись. Расстояние на экране фиксированной высотой в мире не задать.
//
// ЧТО ВМЕСТО. Проход по ЭКРАНУ: раз в кадр плашки проецируются на экран,
// сортируются сверху вниз, и каждая, наехавшая на верхнюю, отодвигается ВНИЗ
// ровно настолько, чтобы не задевать её. Вниз, а не вверх: так плашки остаются
// у своих тел, а не уплывают в пустое небо — в небе уже не понять, чья какая.
//
// ЧЕГО ЭТОТ ПРОХОД НЕ ДЕЛАЕТ:
//   • не трогает ни размер плашки, ни её отрисовку, ни бой;
//   • НЕ ВЫПОЛНЯЕТСЯ ВОВСЕ, пока тел двое, — в бою один на один плашки стоят
//     ровно там, где стояли, и ни одного расчёта здесь не добавляется;
//   • не правит плашку изнутри: положение ставится ОДИН РАЗ при сборке, дальше
//     каждый кадр плашка пересчитывает только свой размер, — поэтому высотой
//     можно распоряжаться снаружи, и защищённый файл остаётся нетронутым.
//
// Экспортирует: declutterPlates.
import * as THREE from 'three';

/** Просвет между плашками, долями высоты плашки. */
const PAD = 0.2;

const _bottom = new THREE.Vector3();
const _top = new THREE.Vector3();

/** Плашка — единственный спрайт среди прямых детей группы: тело собрано из
 *  обычных мешей. Ищем так, а не по индексу: порядок детей — контракт сборки
 *  бойца, и держать его снаружи значило бы держать в двух местах сразу. */
function plateOf(group) {
  return (group.children || []).find((c) => c.isSprite) || null;
}

/**
 * Развести плашки живых тел по экрану. Звать раз в кадр ПОСЛЕ того, как тела
 * обновились (плашка там пересчитывает свой размер) и разошлись.
 *
 * @param {Array} units живые бойцы поля боя
 * @param {THREE.Camera} camera камера сцены
 */
export function declutterPlates(units, camera) {
  if (!camera || !units || units.length < 3) return; // двое — разводить нечего

  const rows = [];
  for (const u of units) {
    const group = u && u.f && u.f.group;
    if (!group) continue;
    const plate = plateOf(group);
    if (!plate || !plate.visible) continue;
    // Считаем всегда от СВОЕГО места, иначе сдвиги копились бы кадр за кадром.
    if (plate.userData.baseY === undefined) plate.userData.baseY = plate.position.y;
    plate.position.y = plate.userData.baseY;

    group.updateMatrixWorld();
    plate.getWorldPosition(_bottom);                    // низ плашки: у неё нижняя привязка
    const scale = group.scale ? group.scale.y || 1 : 1;
    const worldH = plate.scale.y * scale;               // высота в мире (размер ставит сама плашка)
    _top.copy(_bottom); _top.y += worldH;

    const yBottom = _bottom.clone().project(camera).y;  // −1 низ экрана, +1 верх
    const yTop = _top.clone().project(camera).y;
    const h = Math.abs(yTop - yBottom);
    if (!Number.isFinite(h) || h <= 1e-6) continue;
    rows.push({ plate, scale, y: yBottom, h, worldPerY: worldH / h });
  }
  if (rows.length < 3) return;

  // Сверху вниз. Верхняя остаётся на месте; каждая следующая опускается ровно
  // настолько, чтобы её верх не задевал низ предыдущей.
  rows.sort((a, b) => b.y - a.y);
  let ceiling = rows[0].y;                              // низ последней поставленной
  for (let i = 1; i < rows.length; i++) {
    const r = rows[i];
    const allowed = ceiling - r.h * (1 + PAD);          // куда ей можно, не задевая верхнюю
    if (r.y > allowed) {
      const drop = r.y - allowed;                       // на столько вниз, в долях экрана
      r.plate.position.y -= (drop * r.worldPerY) / r.scale;
      r.y = allowed;
    }
    ceiling = r.y;
  }
}
